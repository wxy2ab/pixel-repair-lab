import { expect, test, type Locator } from '@playwright/test'
import type { Catalog } from '../src/shared/types'

const button = (container: Locator, name: string) => container.getByRole('button', { name, exact: true })

test('the Python overview reveals code with each data transfer and verifies a prediction with different input', async ({ page, request }) => {
  const response = await request.get('/api/levels')
  const { levels, issues } = await response.json() as Catalog
  expect(issues).toEqual([])
  const overview = levels.find(level => level.id === 'python-program-overview')
  const basics = levels.find(level => level.id === 'python-program-basics')
  const functions = levels.find(level => level.id === 'foundation-functions-notes')
  if (overview?.kind !== 'lecture' || !overview.execution || !basics || functions?.kind !== 'lecture' || !functions.topic) {
    throw new Error('Missing program overview or function lesson')
  }
  const [, secondCase, thirdCase] = overview.execution.cases
  const wrongGuess = secondCase?.predictions?.find(value => value !== secondCase.expected)
  if (!wrongGuess || !thirdCase) throw new Error('Missing the guided prediction cases')

  await page.goto('/')
  await page.locator('[data-unit="foundations"]').click()
  await page.locator('.mission-list button').filter({ has: page.getByText(overview.title.zh, { exact: true }) }).click()
  await expect(page.getByRole('heading', { level: 1, name: overview.title.zh })).toBeVisible()

  const guide = page.getByTestId('guided-program')
  const code = guide.getByTestId('walkthrough-code')
  const stack = guide.getByTestId('walkthrough-stack')
  const transfer = guide.getByTestId('guided-transfer')
  const output = guide.getByTestId('walkthrough-output')
  const active = stack.locator('[data-stack-frame][data-active]')
  const frames = stack.locator('[data-stack-frame]')
  const binding = (frame: Locator, name: string) => frame.locator(`[data-binding="${name}"]`)
  const practice = page.getByTestId('charge-prediction')
  const actualResult = practice.getByTestId('charge-prediction-result')
  const completed = page.locator('.mission-list [aria-current="step"] .mission-check')
  const next = button(guide, '下一步')
  const previous = button(guide, '上一步')
  const source = overview.execution.source.split('\n')

  async function step(kind: string, line: number) {
    await next.click()
    await expect(guide).toHaveAttribute('data-trace-kind', kind)
    await expect(guide).toHaveAttribute('data-trace-line', String(line))
    await expect(code.locator(`[data-line="${line}"][aria-current="step"] code`)).toHaveText(source[line - 1].trim())
  }

  await expect(guide).toHaveAttribute('data-trace-kind', 'start')
  await expect(guide.getByTestId('guided-input')).toHaveText('6')
  await expect(code.locator('code')).toHaveCount(0)
  await expect(frames).toHaveCount(1)
  await expect(output).toHaveText('还没有输出')
  await expect(binding(stack, 'charge')).toHaveCount(0)
  await expect(practice).toHaveCount(0)
  await expect(previous).toBeDisabled()

  await step('assign', 10)
  await expect(code.locator('code')).toHaveCount(1)
  await expect(binding(active, 'charge')).toContainText('6')
  await expect(output).toHaveText('还没有输出')
  await previous.click()
  await expect(guide).toHaveAttribute('data-trace-kind', 'start')
  await expect(binding(stack, 'charge')).toHaveCount(0)
  await step('assign', 10)

  await step('call', 11)
  await expect(code.locator('[data-line="5"] code')).toHaveText(source[4].trim())
  await expect(frames).toHaveCount(2)
  await expect(stack.locator('[data-stack-frame][data-waiting]')).toHaveCount(1)
  await expect(binding(active, 'current')).toContainText('6')
  await expect(binding(stack, 'result')).toHaveCount(0)
  await step('assign', 6)
  await expect(binding(active, 'extra')).toContainText('3')
  await step('call', 7)
  await expect(code.locator('[data-line="1"] code')).toHaveText(source[0].trim())
  await expect(frames).toHaveCount(3)
  await expect(stack.locator('[data-stack-frame][data-waiting]')).toHaveCount(2)
  await expect(binding(active, 'current')).toContainText('6')
  await expect(binding(active, 'extra')).toContainText('3')
  await step('assign', 2)
  await expect(binding(active, 'total')).toContainText('9')

  await step('return', 3)
  await expect(frames).toHaveCount(2)
  await expect(transfer).toHaveAttribute('data-transfer-kind', 'return')
  await expect(transfer).toContainText('9')
  await expect(binding(active, 'ready')).toHaveCount(0)
  await step('assign', 7)
  await expect(binding(active, 'ready')).toContainText('9')
  await step('return', 8)
  await expect(frames).toHaveCount(1)
  await expect(transfer).toHaveAttribute('data-transfer-kind', 'return')
  await expect(transfer).toContainText('9')
  await expect(binding(active, 'result')).toHaveCount(0)
  await expect(output).toHaveText('还没有输出')
  await step('assign', 11)
  await expect(binding(active, 'result')).toContainText('9')
  await expect(output).toHaveText('还没有输出')
  await step('output', 12)
  await expect(output).toHaveText('9')
  await expect(practice).toHaveCount(0)
  await next.click()
  await expect(guide).toHaveAttribute('data-trace-kind', 'end')
  await expect(practice).toBeVisible()
  await expect(completed).toHaveCount(0)

  const verify = button(practice, '运行验证')
  await expect(verify).toBeDisabled()
  await expect(practice.locator('[data-charge-input="6"]')).toHaveCount(0)
  await button(practice, secondCase.label.zh).click()
  await expect(verify).toBeDisabled()
  await button(practice, wrongGuess).click()
  await expect(actualResult).toHaveCount(0)
  await expect(completed).toHaveCount(0)
  await verify.click()
  await expect(actualResult).toHaveText(secondCase.expected)
  await expect(completed).toHaveCount(0)
  await button(practice, '再猜一次').click()
  await expect(actualResult).toHaveCount(0)
  await expect(verify).toBeDisabled()

  await button(practice, thirdCase.label.zh).click()
  await expect(verify).toBeDisabled()
  await button(practice, thirdCase.expected).click()
  await expect(actualResult).toHaveCount(0)
  await expect(completed).toHaveCount(0)
  await verify.click()
  await expect(actualResult).toHaveText(thirdCase.expected)
  await expect(completed).toBeVisible()

  await page.getByRole('region', { name: '按知识点展开' }).getByRole('button', { name: functions.topic.title.zh, exact: true }).click()
  await expect(page.getByRole('heading', { level: 1, name: functions.title.zh })).toBeVisible()
  await expect(page.getByTestId('guided-program')).toHaveAttribute('data-trace-kind', 'start')
  await page.getByRole('navigation', { name: '课程顺序' }).getByRole('button', { name: '课程全貌', exact: true }).click()
  await expect(page.getByRole('heading', { level: 1, name: basics.title.zh })).toBeVisible()
})
