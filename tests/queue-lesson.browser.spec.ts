import { expect, test, type Locator } from '@playwright/test'
import type { Catalog } from '../src/shared/types'

const button = (panel: Locator, name: string) => panel.getByRole('button', { name, exact: true })

async function names(panel: Locator) {
  return panel.locator('[data-battery-name]').evaluateAll(items => items.map(item => item.getAttribute('data-battery-name')))
}

test('batteries join the back and leave the front, and a new queue checks both predicted orders', async ({ page, request }) => {
  const response = await request.get('/api/levels')
  expect(response.ok()).toBe(true)
  const { levels, issues } = await response.json() as Catalog
  expect(issues).toEqual([])
  const lesson = levels.find(level => level.id === 'queue-notes')
  if (lesson?.kind !== 'lecture' || !lesson.execution?.queueLesson) throw new Error('Missing the battery queue lesson')
  const source = lesson.execution.source.split('\n')

  await page.goto('/#track-algorithms')
  await page.locator('[data-unit="structures"]').click()
  const mission = page.locator('.mission-list').getByRole('button').filter({ has: page.getByText(lesson.title.zh, { exact: true }) })
  await mission.click()
  await expect(page.getByRole('heading', { level: 1, name: lesson.title.zh, exact: true })).toBeVisible()

  const guide = page.getByTestId('queue-lesson')
  const waiting = guide.getByTestId('queue-waiting')
  const line = guide.getByTestId('queue-line')
  const taken = guide.getByTestId('queue-taken')
  const code = guide.getByTestId('queue-lesson-code')
  const poppedOutput = guide.getByTestId('queue-popped-output')
  const remainingOutput = guide.getByTestId('queue-remaining-output')
  const practice = page.getByTestId('queue-prediction')
  const completed = mission.locator('.mission-check')
  const battery = (panel: Locator, name: string) => panel.locator(`[data-battery-name="${name}"] button`)

  async function state(stage: string, lineNumber: number, queue: string[], removed: string[]) {
    await expect(guide).toHaveAttribute('data-queue-stage', stage)
    await expect(code.locator('code')).toHaveCount(lineNumber)
    await expect(code.locator(`[data-line="${lineNumber}"][aria-current="step"] code`)).toHaveText(source[lineNumber - 1])
    expect(await names(line)).toEqual(queue)
    expect(await names(taken)).toEqual(removed)
    await expect(line.locator('[data-queue-head="true"]')).toHaveAttribute('data-battery-name', queue[0])
    await expect(line.locator('[data-queue-tail="true"]')).toHaveAttribute('data-battery-name', queue.at(-1)!)
  }

  await expect(guide).toHaveAttribute('data-queue-stage', 'start')
  await expect(code).toHaveCount(0)
  await expect(practice).toHaveCount(0)
  expect(await names(waiting)).toEqual(['A', 'B', 'C', 'D'])
  expect(await names(line)).toEqual([])
  await battery(waiting, 'B').click()
  await expect(guide).toHaveAttribute('data-queue-stage', 'start')
  await expect(code).toHaveCount(0)

  await battery(waiting, 'A').click()
  await state('push', 3, ['A'], [])
  await battery(waiting, 'B').click()
  await state('push', 4, ['A', 'B'], [])
  await battery(waiting, 'C').click()
  await state('push', 5, ['A', 'B', 'C'], [])
  await battery(line, 'C').click()
  await state('push', 5, ['A', 'B', 'C'], [])
  await battery(line, 'A').click()
  await state('pop', 6, ['B', 'C'], ['A'])
  await battery(waiting, 'D').click()
  await state('push', 7, ['B', 'C', 'D'], ['A'])
  await battery(line, 'B').click()
  await state('pop', 8, ['C', 'D'], ['A', 'B'])
  await button(guide, '上一步').click()
  await state('push', 7, ['B', 'C', 'D'], ['A'])
  await battery(line, 'B').click()
  await state('pop', 8, ['C', 'D'], ['A', 'B'])
  await expect(practice).toHaveCount(0)
  await expect(poppedOutput).toHaveCount(0)
  await button(guide, '下一步').click()
  await state('show-popped', 9, ['C', 'D'], ['A', 'B'])
  await expect(poppedOutput).toHaveText('["A","B"]')
  await expect(remainingOutput).toHaveCount(0)
  await expect(practice).toHaveCount(0)
  await button(guide, '下一步').click()
  await state('show-remaining', 10, ['C', 'D'], ['A', 'B'])
  await expect(remainingOutput).toHaveText('["C","D"]')

  const verify = button(practice, '运行验证')
  const actualPopped = practice.getByTestId('queue-actual-popped')
  const actualRemaining = practice.getByTestId('queue-actual-remaining')
  await expect(practice.locator('[data-queue-operation="pop"]')).toHaveCount(2)
  await expect(verify).toBeDisabled()
  await practice.locator('[data-popped-option="1"]').click()
  await expect(verify).toBeDisabled()
  await practice.locator('[data-remaining-option="0"]').click()
  await expect(actualRemaining).toHaveCount(0)
  await verify.click()
  await expect(practice).toHaveAttribute('data-match', 'false')
  await expect(actualPopped).toHaveText('["P","R"]')
  await expect(actualRemaining).toHaveText('["Q","S"]')
  await expect(completed).toHaveCount(0)

  await button(practice, '再猜一次').click()
  await expect(actualPopped).toHaveCount(0)
  await expect(verify).toBeDisabled()
  await practice.locator('[data-popped-option="1"]').click()
  await practice.locator('[data-queue-case="1"]').click()
  await expect(practice.locator('[data-popped-option="1"]')).toHaveAttribute('aria-pressed', 'false')
  await expect(practice.locator('[data-queue-operation="pop"]')).toHaveCount(3)
  await practice.locator('[data-popped-option="1"]').click()
  const empty = practice.locator('[data-remaining-option="1"]')
  await expect(empty).toHaveText('空队列')
  await empty.click()
  await verify.click()
  await expect(practice).toHaveAttribute('data-match', 'true')
  await expect(actualPopped).toHaveText('["K","L","M"]')
  await expect(actualRemaining).toHaveText('[]')
  await expect(completed).toBeVisible()
})
