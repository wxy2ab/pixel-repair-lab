import { expect, test, type Locator } from '@playwright/test'
import type { Catalog } from '../src/shared/types'

const button = (panel: Locator, name: string) => panel.getByRole('button', { name, exact: true })
const moves = (panel: Locator) => panel.locator('[data-move]').evaluateAll(items => items.map(item => item.getAttribute('data-move')))

test('the two-pointer lesson checks each sum and direction, then runs the predicted path on a new row', async ({ page, request }) => {
  const response = await request.get('/api/levels')
  expect(response.ok()).toBe(true)
  const { levels, issues } = await response.json() as Catalog
  expect(issues).toEqual([])
  const level = levels.find(item => item.id === 'two-pointer-notes')
  if (level?.kind !== 'lecture' || !level.execution?.twoPointerLesson) throw new Error('Missing the two-pointer lesson')

  await page.goto('/#track-algorithms')
  await page.locator('[data-unit="algorithm-intro"]').click()
  const mission = page.locator('.mission-list').getByRole('button').filter({ has: page.getByText(level.title.zh, { exact: true }) })
  await mission.click()
  await expect(page.getByRole('heading', { level: 1, name: level.title.zh, exact: true })).toBeVisible()

  const guide = page.getByTestId('two-pointer-lesson')
  const step = guide.getByTestId('two-pointer-step')
  const code = guide.getByTestId('two-pointer-code')
  const equation = guide.getByTestId('two-pointer-equation')
  const proof = guide.getByTestId('two-pointer-explanation')
  const prediction = page.getByTestId('two-pointer-prediction')
  const card = (name: string) => guide.getByTestId('two-pointer-card-' + name)
  const sum = button(guide, '算总电量')
  const moveLeft = button(guide, '左端向右移')
  const moveRight = button(guide, '右端向左移')

  await expect(step).toHaveAttribute('data-kind', 'start')
  await expect(card('A')).toHaveAttribute('data-state', 'left')
  await expect(card('F')).toHaveAttribute('data-state', 'right')
  await expect(code).toHaveCount(0)
  await expect(prediction).toHaveCount(0)

  await sum.click()
  await expect(step).toHaveAttribute('data-kind', 'sum')
  await expect(step).toHaveAttribute('data-total', '15')
  await expect(equation).toContainText(/1\s*\+\s*14\s*=\s*15/u)
  await expect(code).toContainText('total = charges[left] + charges[right]')
  await moveRight.click()
  await expect(guide.getByTestId('two-pointer-hint')).toBeVisible()
  await expect(step).toHaveAttribute('data-kind', 'sum')
  await expect(step).toHaveAttribute('data-right', '5')
  await moveLeft.click()
  await expect(step).toHaveAttribute('data-kind', 'move')
  await expect(step).toHaveAttribute('data-left', '1')
  await expect(card('A')).toHaveAttribute('data-state', 'excluded')
  await expect(card('A')).toHaveAttribute('data-recent', 'true')
  await expect(card('B')).toHaveAttribute('data-state', 'left')
  await expect(code).toContainText('if total < target:')
  await expect(code).toContainText('left += 1')
  await expect(proof).toContainText('A')
  await expect(proof).toContainText('电量最高')
  await button(guide, '上一步').click()
  await expect(step).toHaveAttribute('data-kind', 'sum')
  await expect(card('A')).toHaveAttribute('data-state', 'left')
  await moveLeft.click()

  await sum.click()
  await expect(step).toHaveAttribute('data-total', '18')
  await expect(equation).toContainText(/4\s*\+\s*14\s*=\s*18/u)
  await moveRight.click()
  await expect(step).toHaveAttribute('data-right', '4')
  await expect(card('F')).toHaveAttribute('data-state', 'excluded')
  await expect(card('E')).toHaveAttribute('data-state', 'right')
  await expect(code).toContainText('else:')
  await expect(code).toContainText('right -= 1')
  await expect(proof).toContainText('F')
  await expect(proof).toContainText('电量最低')

  await sum.click()
  await expect(step).toHaveAttribute('data-total', '15')
  await moveLeft.click()
  await expect(card('B')).toHaveAttribute('data-state', 'excluded')
  await sum.click()
  await expect(step).toHaveAttribute('data-total', '17')
  await expect(equation).toContainText(/6\s*\+\s*11\s*=\s*17/u)
  await expect(prediction).toHaveCount(0)
  await button(guide, '确认配对').click()
  await expect(step).toHaveAttribute('data-kind', 'return')
  await expect(code).toContainText('if total == target:')
  await expect(code).toContainText('return [left, right]')
  await expect(card('C')).toHaveAttribute('data-state', 'found')
  await expect(card('E')).toHaveAttribute('data-state', 'found')
  await expect(prediction).toBeVisible()

  const row = prediction.getByTestId('two-pointer-prediction-row')
  const verify = button(prediction, '运行验证')
  const pick = (name: string) => row.locator(`button[data-battery-name="${name}"]`).click()
  const predictLeft = prediction.getByTestId('two-pointer-move-left')
  const predictRight = prediction.getByTestId('two-pointer-move-right')
  const completed = mission.locator('.mission-check')

  await expect(verify).toBeDisabled()
  await predictRight.click()
  await predictLeft.click()
  await predictLeft.click()
  await pick('L')
  await expect(verify).toBeDisabled()
  await pick('H')
  await expect(prediction.getByTestId('two-pointer-actual-moves')).toHaveCount(0)
  await verify.click()
  await expect(prediction).toHaveAttribute('data-match', 'false')
  await expect(prediction.locator('[data-prediction="moves"]')).toHaveAttribute('data-match', 'false')
  await expect(prediction.locator('[data-prediction="pair"]')).toHaveAttribute('data-match', 'true')
  expect(await moves(prediction.getByTestId('two-pointer-actual-moves'))).toEqual(['right', 'left', 'right'])
  await expect(prediction.getByTestId('two-pointer-actual-pair')).toContainText(/H.*L/u)
  await prediction.getByText('查看每步计算', { exact: true }).click()
  await expect(prediction.getByTestId('two-pointer-actual-sums').locator('li')).toHaveCount(4)
  await expect(prediction.getByTestId('two-pointer-actual-sums').locator('li').last()).toContainText('5 + 12 = 17')
  await expect(completed).toHaveCount(0)
  await prediction.getByTestId('two-pointer-undo').click()
  await predictRight.click()
  await verify.click()
  await expect(prediction).toHaveAttribute('data-match', 'true')
  await expect(completed).toBeVisible()
})
