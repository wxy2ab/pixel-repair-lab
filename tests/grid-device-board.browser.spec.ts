import { expect, test } from '@playwright/test'
import { cardsToPython } from '../src/shared/cards'
import type { Catalog } from '../src/shared/types'

test.use({ launchOptions: { args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] } })

test('the vault shows its devices, reflected beam and changing turns in both board views', async ({ page, request }) => {
  test.slow()
  const { levels } = await (await request.get('/api/levels')).json() as Catalog
  const vault = levels.find(level => level.id === 'challenge-double-seal-vault')
  if (vault?.kind !== 'grid') throw new Error('Missing vault fixture')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/#challenge-zone')
  await page.locator('[data-challenge-level="' + vault.id + '"]').click()
  const inspection = page.getByTestId('station-cell-inspection')
  const canvas = page.getByTestId('station-3d-canvas')
  await expect(page.locator('.station-viewport')).toHaveAttribute('data-ready', 'true', { timeout: 20000 })
  await canvas.press('ArrowRight')
  await canvas.press('ArrowRight')
  await canvas.press('ArrowUp')
  await canvas.press('ArrowUp')
  await expect(inspection).toContainText('钥匙 · 待领取')
  const legend = page.locator('.board-legend')
  await expect(legend.locator('.mechanism-swatch')).toHaveCount(8)
  await expect(legend).toContainText('脉冲大炮')
  await page.getByRole('button', { name: '2D', exact: true }).click()
  const consoleToggle = page.getByTestId('arena-console-toggle')
  await consoleToggle.click()
  const mirror = page.locator('.tile[data-device="mirror"]')
  await mirror.click()
  await expect(inspection).toContainText('反光镜')
  await expect(inspection).toContainText('激光束')
  await expect(mirror.locator('[data-arm="left"]')).toHaveCount(1)
  await expect(mirror.locator('[data-arm="down"]')).toHaveCount(1)
  await page.getByTestId('map-observe-start').click()
  await page.getByTestId('map-observe-play').click()
  const controls = page.getByTestId('map-observe-controls')
  while (Number(await controls.getAttribute('data-step')) > 0) await page.getByTestId('map-observe-prev').click()
  const bomb = page.locator('.tile[data-device="bomb"]')
  await bomb.click()
  await expect(inspection).toContainText('还剩 21 回合')
  await page.getByTestId('map-observe-next').click()
  await page.getByTestId('map-observe-next').click()
  await expect(page.locator('.tile[data-device="cannon"]')).toHaveAttribute('data-device-state', 'on')
  await expect(page.locator('.tile[data-x="6"][data-y="3"]')).toHaveAttribute('data-hazard', 'cannon')
  await expect(inspection).toContainText('还剩 19 回合')
  await page.getByRole('button', { name: '3D', exact: true }).click()
  await expect(page.locator('.station-viewport')).toHaveAttribute('data-ready', 'true')
  await expect(inspection).toContainText('还剩 19 回合')
  const pulse = await canvas.screenshot()
  await page.getByTestId('map-observe-next').click()
  await expect(inspection).toContainText('还剩 18 回合')
  await expect.poll(async () => !(await canvas.screenshot()).equals(pulse)).toBe(true)
  await page.getByTestId('map-observe-exit').click()
  await page.getByRole('button', { name: '2D', exact: true }).click()
  await consoleToggle.click()
  await page.getByRole('tab', { name: 'Python', exact: true }).click()
  await page.getByRole('textbox', { name: '编写 Python', exact: true }).fill(cardsToPython(vault.cards, vault.solutionCards))
  await page.getByRole('button', { name: '运行', exact: true }).click()
  await expect(page.locator('.tile[data-device="chest"]')).toHaveAttribute('data-device-state', 'open', { timeout: 15000 })
  await expect(page.locator('.tile[data-device="door"][data-device-state="open"]')).toHaveCount(2)
  await expect(page.locator('.tile[data-device="key"]')).toHaveAttribute('data-device-state', 'taken')
  await expect(page.locator('.tile[data-device="laser"]')).toHaveAttribute('data-device-state', 'off')
})
