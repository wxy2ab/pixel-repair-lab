import { expect, test, type Locator } from '@playwright/test'
import type { Catalog } from '../src/shared/types'

const button = (panel: Locator, name: string) => panel.getByRole('button', { name, exact: true })

test('while checks before charging, exits on the first false check, and verifies count and final charge', async ({ page, request }) => {
  const response = await request.get('/api/levels')
  expect(response.ok()).toBe(true)
  const { levels, issues } = await response.json() as Catalog
  expect(issues).toEqual([])
  const lesson = levels.find(level => level.id === 'while-loop-notes')
  if (lesson?.kind !== 'lecture' || !lesson.execution?.whileLoop) throw new Error('Missing while-loop lesson')
  const source = lesson.execution.source.split('\n')
  const [firstDemo, zeroDemo, firstPractice, zeroPractice] = lesson.execution.cases

  await page.goto('/')
  await page.locator('[data-unit="python-intermediate"]').click()
  const mission = page.locator('.mission-list').getByRole('button')
    .filter({ has: page.getByText(lesson.title.zh, { exact: true }) })
  await mission.click()
  await expect(page.getByRole('heading', { level: 1, name: lesson.title.zh, exact: true })).toBeVisible()
  const completed = mission.locator('.mission-check')
  const guide = page.getByTestId('while-lesson')
  const code = guide.getByTestId('while-code')
  const charge = guide.getByTestId('while-charge')
  const rounds = guide.getByTestId('while-rounds')
  const output = guide.getByTestId('while-output')
  const practice = page.getByTestId('while-prediction')
  const next = button(guide, '下一步')
  const previous = button(guide, '上一步')

  async function step(stage: string, line: number, current: number, count: number) {
    await next.click()
    await expect(guide).toHaveAttribute('data-while-stage', stage)
    await expect(code.locator(`[data-line="${line}"][aria-current="step"] code`)).toHaveText(source[line - 1].trim())
    await expect(charge).toHaveText(String(current))
    await expect(rounds).toHaveText(String(count))
  }

  await expect(guide).toHaveAttribute('data-while-stage', 'start')
  await expect(guide).toHaveAttribute('data-demo-index', '0')
  await expect(charge).toHaveText(String(firstDemo.input))
  await expect(code.locator('code')).toHaveCount(0)
  await expect(previous).toBeDisabled()
  await expect(practice).toHaveCount(0)
  await step('load', 1, 0, 0)
  await step('check', 2, 0, 0)
  await expect(guide).toHaveAttribute('data-condition', 'true')
  await expect(code.locator('[data-line="3"]')).toHaveCount(0)
  await step('charge', 3, 3, 1)
  await step('check', 2, 3, 1)
  await expect(guide).toHaveAttribute('data-condition', 'true')
  await step('charge', 3, 6, 2)
  await step('stop', 2, 6, 2)
  await expect(guide).toHaveAttribute('data-condition', 'false')
  await expect(output).toHaveCount(0)
  await previous.click()
  await expect(guide).toHaveAttribute('data-while-stage', 'charge')
  await step('stop', 2, 6, 2)
  await step('output', 4, 6, 2)
  await expect(output).toHaveText(firstDemo.expected)
  await expect(practice).toHaveCount(0)

  await next.click()
  await expect(guide).toHaveAttribute('data-demo-index', '1')
  await expect(guide).toHaveAttribute('data-while-stage', 'start')
  await expect(code.locator('code')).toHaveCount(0)
  await expect(charge).toHaveText(String(zeroDemo.input))
  await step('load', 1, zeroDemo.input, 0)
  await step('stop', 2, zeroDemo.input, 0)
  await expect(guide).toHaveAttribute('data-condition', 'false')
  await expect(code.locator('[data-line="3"]')).toHaveCount(0)
  await expect(practice).toHaveCount(0)
  await step('output', 4, zeroDemo.input, 0)
  await expect(code.locator('[data-line="3"]')).toHaveCount(0)
  await expect(output).toHaveText(zeroDemo.expected)
  await expect(practice).toBeVisible()
  await expect(completed).toHaveCount(0)

  const verify = button(practice, '运行验证')
  const actualRounds = practice.getByTestId('while-actual-rounds')
  const actualCharge = practice.getByTestId('while-actual-charge')
  await expect(verify).toBeDisabled()
  await practice.locator('[data-while-case="0"]').click()
  await practice.locator('[data-round-option="2"]').click()
  await expect(verify).toBeDisabled()
  await practice.locator(`[data-charge-option="${firstPractice.expected}"]`).click()
  await expect(actualRounds).toHaveCount(0)
  await expect(actualCharge).toHaveCount(0)
  await verify.click()
  await expect(actualRounds).toHaveText('1')
  await expect(actualCharge).toHaveText(firstPractice.expected)
  await expect(practice.locator('[data-while-prediction-field="rounds"]')).toHaveAttribute('data-match', 'false')
  await expect(practice.locator('[data-while-prediction-field="charge"]')).toHaveAttribute('data-match', 'true')
  await expect(completed).toHaveCount(0)

  await button(practice, '再猜一次').click()
  await expect(actualRounds).toHaveCount(0)
  await expect(actualCharge).toHaveCount(0)
  await expect(verify).toBeDisabled()
  await practice.locator('[data-while-case="1"]').click()
  await practice.locator('[data-round-option="0"]').click()
  await expect(verify).toBeDisabled()
  await practice.locator(`[data-charge-option="${zeroPractice.expected}"]`).click()
  await expect(completed).toHaveCount(0)
  await verify.click()
  await expect(actualRounds).toHaveText('0')
  await expect(actualCharge).toHaveText(zeroPractice.expected)
  await expect(practice).toHaveAttribute('data-match', 'true')
  await expect(completed).toBeVisible()
})
