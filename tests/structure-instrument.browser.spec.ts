test('the conveyor dispatches from the front and replays the new batch only after verification', async ({ page }) => {
  await page.goto('/#track-algorithms')
  await page.locator('[data-unit="structures"]').click()
  await page.locator('.mission-list button').filter({ has: page.getByText('队列', { exact: true }) }).click()
  const guide = page.getByTestId('queue-lesson')
  const model = guide.locator('[data-teaching-model="structure-queue"]')
  await page.setViewportSize({ width: 390, height: 844 })
  await model.scrollIntoViewIfNeeded()
  await expect(model).toHaveAttribute('data-renderer', 'webgl')
  await model.getByRole('button', { name: '俯视' }).click()
  for (const [i, name] of ['A', 'B', 'C', 'A', 'D', 'B'].entries()) {
    await tapPart(model, name)
    await expect(guide.getByTestId('queue-lesson-code').locator('[aria-current=step]')).toHaveAttribute('data-line', String(i + 3))
  }
  await expect(guide.getByTestId('queue-lesson-code').locator('[aria-current=step] code')).toContainText('pop(0)')
  await expect(model.getByText('1 · A', { exact: true })).toBeVisible()
  await expect(model.getByText('2 · B', { exact: true })).toBeVisible()
  const next = guide.getByRole('button', { name: '下一步', exact: true })
  await next.click()
  await next.click()
  const practice = page.getByTestId('queue-prediction')
  const bench = practice.locator('[data-teaching-model="structure-queue"]')
  await bench.scrollIntoViewIfNeeded()
  await expect(bench).toHaveAttribute('data-renderer', 'webgl')
  await expect(bench.getByText('1 · P', { exact: true })).toHaveCount(0)
  await practice.locator('[data-popped-option="0"]').click()
  await practice.locator('[data-remaining-option="0"]').click()
  await practice.getByRole('button', { name: '运行验证' }).click()
  const review = practice.getByTestId('structure-trace')
  await expect(bench.getByText('1 · P', { exact: true })).toBeVisible()
  await review.getByRole('button', { name: '从头回看' }).click()
  await expect(bench.getByText('1 · P', { exact: true })).toHaveCount(0)
  for (let i = 0; i < 5; i++) await review.getByRole('button', { name: '下一步' }).click()
  await expect(review.locator('[aria-current=step] code')).toContainText('pop(0)')
  await expect(bench.getByText('1 · P', { exact: true })).toBeVisible()
  await expect(bench.getByText('2 · R', { exact: true })).toHaveCount(0)
})

test('the handover bench moves a real charged battery from the queue to the stack before writing the register', async ({ page }) => {
  await page.goto('/#track-algorithms')
  await page.locator('[data-unit="structures"]').click()
  await page.locator('.mission-list button').filter({ has: page.getByText('维修站的电池交接单', { exact: true }) }).click()
  const guide = page.getByTestId('battery-dispatch-trial')
  const model = guide.locator('[data-teaching-model="structure-dispatch"]')
  const labels = model.locator('.teaching-model-labels')
  await model.scrollIntoViewIfNeeded()
  await expect(model).toHaveAttribute('data-renderer', 'webgl')
  await expect(labels.getByText('按名登记', { exact: true })).toHaveCount(0)
  for (const role of ['queue-queue', 'stack-stack', 'records-dictionary', 'results-list']) {
    await guide.getByTestId('dispatch-choice-' + role).click()
  }
  await guide.getByRole('button', { name: '试跑小例子' }).click()
  const step = guide.getByTestId('dispatch-step')
  const code = guide.getByTestId('dispatch-current-code')
  await tapPart(model, 'A · 2')
  await expect(code).toContainText('queue.append(name)')
  await tapPart(model, 'B · 4')
  await tapPart(model, 'C · 1')
  await tapPart(model, 'A')
  await expect(step).toHaveAttribute('data-kind', 'queueTake')
  await tapPart(model, 'A · 2')
  await expect(step).toHaveAttribute('data-kind', 'stackAdd')
  await expect(labels.getByText('A · 5', { exact: true })).toBeVisible()
  await tapPart(model, 'B')
  await tapPart(model, 'B · 4')
  await tapPart(model, 'B · 7')
  await expect(step).toHaveAttribute('data-kind', 'stackTake')
  await expect(labels.getByText('B → 4', { exact: true })).toBeVisible()
  await tapPart(model, 'B → 4')
  await expect(code).toContainText('current[battery[0]] = battery[1]')
  await expect(labels.getByText('B → 7', { exact: true })).toBeVisible()
  await guide.getByRole('button', { name: '上一步' }).click()
  await expect(labels.getByText('B → 4', { exact: true })).toBeVisible()
})
