import { expect, test, type Locator } from '@playwright/test'

test.use({ launchOptions: { args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] } })

async function tapPart(model: Locator, name: string, index = 0) {
  await model.scrollIntoViewIfNeeded()
  const label = model.locator('.teaching-model-labels').getByText(name, { exact: true }).nth(index)
  const canvas = model.locator('canvas')
  await expect(label).toBeVisible()
  let position: { x: number; y: number } | undefined
  await expect.poll(async () => {
    position = await model.evaluate((figure, target) => {
      const tag = [...figure.querySelectorAll<HTMLSpanElement>('.teaching-model-labels span')]
        .filter(item => item.textContent === target.name)[target.index]
      const surface = figure.querySelector('canvas')?.getBoundingClientRect()
      if (!surface || !tag?.style.left || tag.hidden) return
      const rect = tag.getBoundingClientRect()
      return { x: rect.x + rect.width / 2 - surface.x, y: rect.y + rect.height / 2 - surface.y }
    }, { name, index })
    return Boolean(position)
  }).toBe(true)
  await canvas.click({ position })
}

test('batteries picked on the 3D stack follow the lesson order and undo restores the removed battery', async ({ page }) => {
  await page.goto('/#track-algorithms')
  await page.locator('[data-unit="structures"]').click()
  await page.locator('.mission-list button').filter({ has: page.getByText('栈', { exact: true }) }).click()
  const lesson = page.getByTestId('stack-lesson')
  const model = lesson.locator('[data-teaching-model="structure-stack"]')
  await model.scrollIntoViewIfNeeded()
  await expect(model).toHaveAttribute('data-renderer', 'webgl')
  await tapPart(model, 'C')
  await expect(lesson).toHaveAttribute('data-stack-stage', 'start')
  for (const name of ['A', 'B', 'C']) {
    await tapPart(model, name)
    await expect(lesson.getByTestId('stack-pile').locator('[data-stack-top]')).toHaveAttribute('data-battery-name', name)
  }
  const topView = model.getByRole('button', { name: '俯视' })
  await topView.click()
  await expect(model.locator('.teaching-model-labels').getByText('A', { exact: true })).toBeHidden()
  await expect(model.locator('.teaching-model-labels').getByText('C', { exact: true })).toBeVisible()
  await topView.click()
  await tapPart(model, 'C')
  await expect(lesson).toHaveAttribute('data-stack-stage', 'pop')
  await expect(model.locator('.teaching-model-labels').getByText('C', { exact: true })).toHaveCount(0)
  await expect(model.locator('.teaching-model-labels').getByText('1 · C', { exact: true })).toBeVisible()
  await lesson.getByRole('button', { name: '上一步', exact: true }).click()
  await expect(model.locator('.teaching-model-labels').getByText('C', { exact: true })).toBeVisible()
})

