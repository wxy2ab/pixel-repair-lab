import { expect, test, type Locator } from '@playwright/test'
import type { Catalog } from '../src/shared/types'

const button = (panel: Locator, name: string) => panel.getByRole('button', { name, exact: true })

test('the two-file lesson imports the function before calling it, then verifies a new charge using both files', async ({ page, request }) => {
  const response = await request.get('/api/levels')
  expect(response.ok()).toBe(true)
  const { levels, issues } = await response.json() as Catalog
  expect(issues).toEqual([])
  const lesson = levels.find(level => level.id === 'python-modules-notes')
  if (lesson?.kind !== 'lecture' || !lesson.execution?.moduleLesson) throw new Error('Missing module lesson')
  const source = { main: lesson.execution.source.split('\n'), module: lesson.execution.moduleLesson.source.split('\n') }

  await page.goto('/')
  await page.locator('[data-unit="python-advanced"]').click()
  const mission = page.locator('.mission-list').getByRole('button')
    .filter({ has: page.getByText(lesson.title.zh, { exact: true }) })
  await mission.click()
  await expect(page.getByRole('heading', { level: 1, name: lesson.title.zh, exact: true })).toBeVisible()

  const completed = mission.locator('.mission-check')
  const guide = page.getByTestId('module-lesson')
  const main = guide.locator('[data-file="main"]')
  const module = guide.locator('[data-file="module"]')
  const importedName = guide.getByTestId('module-imported-name')
  const transfer = guide.getByTestId('module-transfer')
  const argument = guide.getByTestId('module-argument')
  const returned = guide.getByTestId('module-return-value')
  const result = guide.getByTestId('module-result')
  const output = guide.getByTestId('module-output')
  const practice = page.getByTestId('charge-prediction')
  const next = button(guide, '下一步')
  const previous = button(guide, '上一步')

  async function step(stage: string, file: keyof typeof source, line: number) {
    await next.click()
    await expect(guide).toHaveAttribute('data-module-stage', stage)
    const active = `[data-line="${line}"][aria-current="step"] code`
    const code = (file === 'main' ? main : module).locator(active)
    await expect(code).toHaveText(source[file][line - 1].trim())
    expect(await code.textContent()).toBe(source[file][line - 1])
    await expect((file === 'main' ? module : main).locator('[data-line][aria-current="step"]')).toHaveCount(0)
  }

  await expect(guide).toHaveAttribute('data-module-stage', 'start')
  await expect(main).toContainText('main.py')
  await expect(module).toContainText('algorithms.py')
  await expect(guide.locator('[data-line]')).toHaveCount(0)
  await expect(previous).toBeDisabled()
  await expect(practice).toHaveCount(0)

  await step('define', 'module', 1)
  await expect(main.locator('[data-line]')).toHaveCount(0)
  await expect(module.locator('[data-line]')).toHaveCount(1)
  await expect(importedName).toHaveCount(0)
  await step('import', 'main', 1)
  await expect(importedName).toContainText('top_up')
  await expect(transfer).toHaveAttribute('data-direction', 'import')
  await expect(argument).toHaveCount(0)
  await expect(returned).toHaveCount(0)
  await expect(module.locator('[data-line="2"]')).toHaveCount(0)
  await step('input', 'main', 2)
  await expect(transfer).toHaveCount(0)
  await step('call', 'main', 3)
  await expect(transfer).toHaveAttribute('data-direction', 'call')
  await expect(argument).toHaveText('2')
  await expect(module).toContainText('amount')
  await expect(result).toHaveCount(0)
  await step('calculate', 'module', 2)
  await expect(module.locator('[data-line="3"]')).toHaveCount(0)
  await step('return', 'module', 3)
  await expect(transfer).toHaveAttribute('data-direction', 'return')
  await expect(returned).toHaveText('5')
  await expect(result).toHaveCount(0)
  await step('store', 'main', 3)
  await expect(result).toHaveText('5')
  await expect(output).toHaveCount(0)
  await expect(practice).toHaveCount(0)
  await previous.click()
  await expect(guide).toHaveAttribute('data-module-stage', 'return')
  await expect(result).toHaveCount(0)
  await step('store', 'main', 3)
  await step('output', 'main', 4)
  await expect(output).toHaveText('5')

  const verify = button(practice, '运行验证')
  const actual = practice.getByTestId('charge-prediction-result')
  await expect(verify).toBeDisabled()
  await practice.locator('[data-charge-input="0"]').click()
  await expect(verify).toBeDisabled()
  await practice.locator('[data-prediction="0"]').click()
  await expect(actual).toHaveCount(0)
  await verify.click()
  await expect(actual).toHaveText('3')
  await expect(practice.locator('[data-match]')).toHaveAttribute('data-match', 'false')
  await expect(completed).toHaveCount(0)

  await button(practice, '再猜一次').click()
  await expect(actual).toHaveCount(0)
  await expect(verify).toBeDisabled()
  await practice.locator('[data-prediction="3"]').click()
  await practice.locator('[data-charge-input="6"]').click()
  await expect(verify).toBeDisabled()
  await practice.locator('[data-prediction="9"]').click()
  await verify.click()
  await expect(actual).toHaveText('9')
  await expect(practice.locator('[data-match]')).toHaveAttribute('data-match', 'true')
  await expect(completed).toBeVisible()
})
