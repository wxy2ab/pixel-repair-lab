import { expect, test, type Locator } from '@playwright/test'
import type { Catalog } from '../src/shared/types'

const button = (panel: Locator, name: string) => panel.getByRole('button', { name, exact: true })
const arrayText = (values: number[]) => `[${values.join(', ')}]`

test('for visits every battery in order, appends each result, exits, and verifies both predictions', async ({ page, request }) => {
  const response = await request.get('/api/levels')
  expect(response.ok()).toBe(true)
  const { levels, issues } = await response.json() as Catalog
  expect(issues).toEqual([])
  const lesson = levels.find(level => level.id === 'for-loop-notes')
  if (lesson?.kind !== 'lecture' || !lesson.execution?.forLoop) throw new Error('Missing for-loop lesson')
  const [example, firstPractice, secondPractice] = lesson.execution.forLoop.cases
  const source = lesson.execution.source.split('\n')

  await page.goto('/')
  await page.locator('[data-unit="python-intermediate"]').click()
  const mission = page.locator('.mission-list').getByRole('button')
    .filter({ has: page.getByText(lesson.title.zh, { exact: true }) })
  await mission.click()
  await expect(page.getByRole('heading', { level: 1, name: lesson.title.zh, exact: true })).toBeVisible()

  const completed = mission.locator('.mission-check')
  const guide = page.getByTestId('for-lesson')
  const device = guide.getByRole('region', { name: 'Python 调试器', exact: true })
  const code = guide.getByTestId('for-code')
  const row = guide.locator('[data-battery-index]')
  const records = guide.getByTestId('for-results').locator('[data-result-index][data-value]')
  const practice = page.getByTestId('for-prediction')
  const next = button(guide, '下一步')
  const previous = button(guide, '上一步')

  async function step(stage: string, line: number, control = next) {
    await control.click()
    await expect(guide).toHaveAttribute('data-for-stage', stage)
    await expect(code.locator(`[data-line="${line}"][aria-current="step"] code`)).toHaveText(source[line - 1].trim())
  }

  await expect(guide).toHaveAttribute('data-for-stage', 'start')
  await expect(row).toHaveCount(example.batteries.length)
  await expect(code.locator('code')).toHaveCount(0)
  await expect(records).toHaveCount(0)
  await expect(previous).toBeDisabled()
  await expect(practice).toHaveCount(0)
  await step('load', 1)
  await expect(code).not.toContainText('for charge')
  await step('initialize', 2)
  await expect(records).toHaveCount(0)

  for (const [index, charge] of example.batteries.entries()) {
    await step('take', 3, button(device, `取第 ${index + 1} 块电池的电量 ${charge}`))
    await expect(guide.locator(`[data-battery-index="${index}"]`)).toHaveAttribute('data-active', 'true')
    await expect(guide.getByTestId('for-variable')).toContainText(String(charge))
    await expect(records).toHaveCount(index)

    await step('add', 4)
    await expect(guide.getByTestId('for-calculation')).toContainText(String(example.expected[index]))
    await expect(records).toHaveCount(index)
    await step('record', 5, button(device, `记下 ${example.expected[index]}`))
    await expect(records.nth(index)).toHaveAttribute('data-value', String(example.expected[index]))
    await expect(records).toHaveCount(index + 1)
  }
  await expect(guide.locator('[data-battery-index][data-complete="true"]')).toHaveCount(example.batteries.length)
  await step('stop', 3)
  await expect(guide.locator('[data-battery-index][data-active="true"]')).toHaveCount(0)
  await expect(guide.getByTestId('for-rounds')).toContainText(String(example.batteries.length))
  await expect(guide.getByTestId('for-variable')).toContainText(String(example.batteries.at(-1)))
  await expect(code).not.toContainText('say(str(charged))')
  await expect(practice).toHaveCount(0)
  await previous.click()
  await expect(guide).toHaveAttribute('data-for-stage', 'record')
  await step('stop', 3)
  await step('output', 6)
  await expect(guide.getByTestId('for-output')).toContainText(/\[5,\s*9,\s*5\]/)
  await expect(practice).toBeVisible()
  await expect(completed).toHaveCount(0)

  const verify = button(practice, '运行验证')
  const rounds = practice.getByTestId('for-actual-rounds')
  const results = practice.getByTestId('for-actual-results')
  await expect(verify).toBeDisabled()
  await practice.locator('[data-for-case="0"]').click()
  await practice.locator('[data-round-option="3"]').click()
  await expect(verify).toBeDisabled()
  await practice.locator('[data-result-option="1"]').click()
  await expect(rounds).toHaveCount(0)
  await expect(results).toHaveCount(0)
  await verify.click()
  await expect(rounds).toHaveText(String(firstPractice.batteries.length))
  await expect(results).toHaveText(arrayText(firstPractice.expected))
  await expect(practice.locator('[data-for-prediction-field="rounds"]')).toHaveAttribute('data-match', 'false')
  await expect(practice.locator('[data-for-prediction-field="results"]')).toHaveAttribute('data-match', 'true')
  await expect(completed).toHaveCount(0)

  await button(practice, '再猜一次').click()
  await expect(rounds).toHaveCount(0)
  await expect(results).toHaveCount(0)
  await expect(verify).toBeDisabled()
  await practice.locator('[data-for-case="1"]').click()
  await practice.locator('[data-round-option="2"]').click()
  await practice.locator('[data-result-option="1"]').click()
  await expect(completed).toHaveCount(0)
  await verify.click()
  await expect(rounds).toHaveText(String(secondPractice.batteries.length))
  await expect(results).toHaveText(arrayText(secondPractice.expected))
  await expect(practice).toHaveAttribute('data-match', 'true')
  await expect(completed).toBeVisible()
})
