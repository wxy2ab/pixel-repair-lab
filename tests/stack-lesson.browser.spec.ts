import { expect, test, type Locator } from '@playwright/test'
import type { Catalog } from '../src/shared/types'

const button = (panel: Locator, name: string) => panel.getByRole('button', { name, exact: true })

async function names(panel: Locator) {
  return panel.locator('[data-battery-name]').evaluateAll(items => items.map(item => item.getAttribute('data-battery-name')))
}

test('putting batteries on top and taking them off reveals the stack state and verifies both predictions', async ({ page, request }) => {
  const response = await request.get('/api/levels')
  expect(response.ok()).toBe(true)
  const { levels, issues } = await response.json() as Catalog
  expect(issues).toEqual([])
  const lesson = levels.find(level => level.id === 'stack-notes')
  if (lesson?.kind !== 'lecture' || !lesson.execution?.stackLesson) throw new Error('Missing the battery stack lesson')
  const source = lesson.execution.source.split('\n')

  await page.goto('/#track-algorithms')
  await page.locator('[data-unit="structures"]').click()
  const mission = page.locator('.mission-list').getByRole('button').filter({ has: page.getByText(lesson.title.zh, { exact: true }) })
  await mission.click()
  await expect(page.getByRole('heading', { level: 1, name: lesson.title.zh, exact: true })).toBeVisible()

  const guide = page.getByTestId('stack-lesson')
  const device = guide.getByRole('region', { name: '电池分拣台', exact: true })
  const code = device.getByTestId('stack-lesson-code')
  const waiting = device.getByTestId('stack-waiting')
  const pile = device.getByTestId('stack-pile')
  const taken = device.getByTestId('stack-taken')
  const poppedOutput = guide.getByTestId('stack-popped-output')
  const remainingOutput = guide.getByTestId('stack-remaining-output')
  const practice = page.getByTestId('stack-prediction')
  const completed = mission.locator('.mission-check')
  const battery = (panel: Locator, name: string) => panel.locator(`[data-battery-name="${name}"] button`)

  async function state(stage: string, line: number, stack: string[], popped: string[]) {
    await expect(guide).toHaveAttribute('data-stack-stage', stage)
    await expect(code.locator('code')).toHaveCount(line)
    await expect(code.locator(`[data-line="${line}"][aria-current="step"] code`)).toHaveText(source[line - 1])
    expect(await names(pile)).toEqual(stack)
    expect(await names(taken)).toEqual(popped)
    if (stack.length) await expect(pile.locator('[data-stack-top="true"]')).toHaveAttribute('data-battery-name', stack[0])
  }

  await expect(guide).toHaveAttribute('data-stack-stage', 'start')
  await expect(code).toHaveCount(0)
  await expect(practice).toHaveCount(0)
  expect(await names(waiting)).toEqual(['A', 'B', 'C'])
  expect(await names(pile)).toEqual([])
  await battery(waiting, 'C').click()
  await expect(guide).toHaveAttribute('data-stack-stage', 'start')
  await expect(code).toHaveCount(0)

  await battery(waiting, 'A').click()
  await state('push', 3, ['A'], [])
  await battery(waiting, 'B').click()
  await state('push', 4, ['B', 'A'], [])
  await battery(waiting, 'C').click()
  await state('push', 5, ['C', 'B', 'A'], [])
  await battery(pile, 'A').click()
  await state('push', 5, ['C', 'B', 'A'], [])
  await battery(pile, 'C').click()
  await state('pop', 6, ['B', 'A'], ['C'])
  await button(guide, '上一步').click()
  await state('push', 5, ['C', 'B', 'A'], [])
  await battery(pile, 'C').click()
  await state('pop', 6, ['B', 'A'], ['C'])
  await battery(pile, 'B').click()
  await state('pop', 7, ['A'], ['C', 'B'])
  await expect(practice).toHaveCount(0)
  await expect(poppedOutput).toHaveCount(0)
  await button(guide, '下一步').click()
  await state('show-popped', 8, ['A'], ['C', 'B'])
  await expect(poppedOutput).toHaveText('["C","B"]')
  await expect(remainingOutput).toHaveCount(0)
  await expect(practice).toHaveCount(0)
  await button(guide, '下一步').click()
  await state('show-remaining', 9, ['A'], ['C', 'B'])
  await expect(remainingOutput).toHaveText('["A"]')

  const verify = button(practice, '运行验证')
  const actualPopped = practice.getByTestId('stack-actual-popped')
  const actualRemaining = practice.getByTestId('stack-actual-remaining')
  await expect(practice.locator('[data-stack-operation="pop"]')).toHaveCount(2)
  await expect(verify).toBeDisabled()
  await practice.locator('[data-popped-option="0"]').click()
  await expect(verify).toBeDisabled()
  await practice.locator('[data-remaining-option="1"]').click()
  await expect(actualPopped).toHaveCount(0)
  await verify.click()
  await expect(practice).toHaveAttribute('data-match', 'false')
  await expect(actualPopped).toHaveText('["R","S"]')
  await expect(actualRemaining).toHaveText('["P","Q"]')
  await expect(completed).toHaveCount(0)

  await button(practice, '再猜一次').click()
  await expect(actualPopped).toHaveCount(0)
  await expect(verify).toBeDisabled()
  await practice.locator('[data-popped-option="1"]').click()
  await practice.locator('[data-stack-case="1"]').click()
  await expect(practice.locator('[data-popped-option="1"]')).toHaveAttribute('aria-pressed', 'false')
  await expect(practice.locator('[data-stack-operation="pop"]')).toHaveCount(3)
  await practice.locator('[data-popped-option="1"]').click()
  const empty = practice.locator('[data-remaining-option="1"]')
  await expect(empty).toHaveText('空栈')
  await empty.click()
  await verify.click()
  await expect(practice).toHaveAttribute('data-match', 'true')
  await expect(actualPopped).toHaveText('["L","K","M"]')
  await expect(actualRemaining).toHaveText('[]')
  await expect(completed).toBeVisible()
})
