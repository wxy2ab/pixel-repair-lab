test('the function workspace shows the actual return for each input and clears it after an edit', async ({ page, request }) => {
  const { levels } = await (await request.get('/api/levels')).json() as Catalog
  const level = levels.find(candidate => candidate.id === 'shortest-step')
  if (level?.kind !== 'algorithm' || !level.unit) throw new Error('Missing the shortest-step practice')
  await page.goto('/')
  await page.locator(`[data-unit="${level.unit.id}"]`).click()
  await page.locator('.mission-list button').filter({ hasText: level.title.zh }).click()
  const workspace = page.getByRole('region', { name: 'Python 函数工作区' })
  const field = workspace.getByRole('textbox', { name: '编写 Python' })
  const output = workspace.getByTestId('function-return')
  await field.fill(level.solutionCode)
  await expect(output).toHaveText('等待运行')
  await page.getByRole('toolbar', { name: '运行工具条' }).getByRole('button', { name: '运行', exact: true }).click()
  await expect(output).toHaveText('"right"')
  await workspace.getByRole('button', { name: '用例 2', exact: true }).click()
  await expect(output).toHaveText('"down"')
  await field.fill(level.starterCode)
  await expect(output).toHaveText('等待运行')
})
