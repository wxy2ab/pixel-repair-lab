import { expect, test } from '@playwright/test'
import type { Catalog } from '../src/shared/types'

test('the simulated charger pairs each battery with its actual output and keeps course progress separate', async ({ page, request }) => {
  const { levels } = await (await request.get('/api/levels')).json() as Catalog
  const lesson = levels.find(level => level.id === 'python-program-basics')
  if (lesson?.kind !== 'lecture') throw new Error('Missing the first Python lesson')
  await page.goto('/')
  await page.getByRole('button', { name: '开始 Python 课程', exact: true }).click()

  const charger = page.getByRole('region', { name: '维修站补电机', exact: true })
  const desk = page.getByRole('region', { name: /操作台.*补电记录/ })
  const rail = page.locator('.classroom-rail')
  const progress = rail.getByRole('progressbar', { name: '课程主线进度' })
  await expect(progress).toHaveAttribute('value', '0')
  await expect(charger.getByRole('button', { name: '按规则处理' })).toBeVisible()
  await expect(charger.getByTestId('program-basic-result')).toHaveCount(0)
  await expect(desk.locator('progress')).toHaveCount(0)
  const [railBox, chargerBox, deskBox] = await Promise.all([rail.boundingBox(), charger.boundingBox(), desk.boundingBox()])
  expect(railBox!.x + railBox!.width).toBeLessThanOrEqual(chargerBox!.x)
  expect(chargerBox!.x + chargerBox!.width).toBeLessThanOrEqual(deskBox!.x)

  await charger.locator('[data-basic-case="1"]').click()
  await charger.getByRole('button', { name: '按规则处理' }).click()
  await expect(charger.getByTestId('program-basic-process')).toHaveAttribute('aria-current', 'step')
  await expect(charger.getByTestId('program-basic-result')).toHaveCount(0)
  await charger.getByRole('button', { name: '查看输出' }).click()
  await expect(charger.getByTestId('program-basic-result')).toHaveText('4')
  await expect(desk.getByRole('listitem')).toHaveText('输入 1 → 输出 4')
  await charger.locator('[data-basic-case="0"]').click()
  await expect(charger.getByTestId('program-basic-result')).toHaveCount(0)
  await expect(desk.getByRole('heading', { name: '猜一猜' })).toHaveCount(0)
  await charger.getByRole('button', { name: '按规则处理' }).click()
  await charger.getByRole('button', { name: '查看输出' }).click()
  await expect(desk.locator('li[aria-current="true"]')).toHaveText('输入 0 → 输出 3')
  await expect(progress).toHaveAttribute('value', '0')
  await desk.getByRole('button', { name: lesson.question.options[lesson.question.correct].zh, exact: true }).click()
  await expect(progress).toHaveAttribute('value', '1')
  await rail.getByRole('button', { name: '下一课', exact: true }).click()
  await expect(page.getByTestId('program-interfaces').locator('.teaching-screen[data-surface="monitor"]')).toBeVisible()
})

test('the phone charger keeps the controls inside the device and the log below it in English', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await page.getByRole('button', { name: '开始 Python 课程', exact: true }).click()
  await page.getByRole('button', { name: 'EN', exact: true }).click()
  const charger = page.getByRole('region', { name: 'Workshop battery charger', exact: true })
  const desk = page.getByRole('region', { name: /Control desk.*Charge log/ })
  const progress = page.getByRole('progressbar', { name: 'Core course progress' })
  await expect(progress).toBeVisible()
  const [progressBox, chargerBox, deskBox] = await Promise.all([progress.boundingBox(), charger.boundingBox(), desk.boundingBox()])
  expect(progressBox!.y + progressBox!.height).toBeLessThanOrEqual(chargerBox!.y)
  expect(chargerBox!.y + chargerBox!.height).toBeLessThanOrEqual(deskBox!.y)
  await charger.getByRole('button', { name: 'Apply the rule' }).click()
  await charger.getByRole('button', { name: 'Show the output' }).click()
  await expect(charger.getByTestId('program-basic-result')).toHaveText('9')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
})

