import { expect, test, type Locator } from '@playwright/test'
import type { Catalog } from '../src/shared/types'

const button = (panel: Locator, name: string) => panel.getByRole('button', { name, exact: true })

test('list positions and dictionary names lead to different readings, and only the named record changes', async ({ page, request }) => {
  const response = await request.get('/api/levels')
  expect(response.ok()).toBe(true)
  const { levels, issues } = await response.json() as Catalog
  expect(issues).toEqual([])
  const lesson = levels.find(level => level.id === 'collections-notes')
  if (lesson?.kind !== 'lecture' || !lesson.execution?.collectionLesson) throw new Error('Missing collection lesson')
  const source = lesson.execution.source.split('\n')

  await page.goto('/')
  await page.locator('[data-unit="python-intermediate"]').click()
  const mission = page.locator('.mission-list').getByRole('button')
    .filter({ has: page.getByText(lesson.title.zh, { exact: true }) })
  await mission.click()
  await expect(page.getByRole('heading', { level: 1, name: lesson.title.zh, exact: true })).toBeVisible()

  const completed = mission.locator('.mission-check')
  const guide = page.getByTestId('collection-lesson')
  const code = guide.getByTestId('collection-code')
  const next = button(guide, '下一步')
  const previous = button(guide, '上一步')
  const records = guide.locator('[data-record-key]')
  const positionValue = guide.getByTestId('collection-position-value')
  const namedValue = guide.getByTestId('collection-named-value')
  const output = guide.getByTestId('collection-output')
  const practice = page.getByTestId('collection-prediction')

  async function step(stage: string, line: number) {
    await next.click()
    await expect(guide).toHaveAttribute('data-collection-stage', stage)
    await expect(code.locator('code')).toHaveCount(line)
    await expect(code.locator(`[data-line="${line}"][aria-current="step"] code`)).toHaveText(source[line - 1])
  }

  async function showsRecords(panel: Locator, expected: Record<string, number>) {
    await expect(panel.locator('[data-record-key]')).toHaveCount(Object.keys(expected).length)
    for (const [name, charge] of Object.entries(expected)) {
      await expect(panel.locator(`[data-record-key="${name}"]`)).toHaveAttribute('data-charge', String(charge))
    }
  }

  await expect(guide).toHaveAttribute('data-collection-stage', 'start')
  await expect(guide.getByRole('listitem')).toHaveCount(3)
  await expect(guide.locator('[data-battery-index], [data-battery-name]')).toHaveCount(0)
  await expect(code.locator('code')).toHaveCount(0)
  await expect(previous).toBeDisabled()
  await expect(practice).toHaveCount(0)
  await step('load-list', 1)
  await expect(guide.locator('[data-battery-index="0"]')).toBeVisible()
  await expect(guide.locator('[data-battery-name]')).toHaveCount(0)
  await step('index', 2)
  await expect(guide.locator('[data-battery-index][data-active="true"]')).toHaveAttribute('data-battery-index', '1')
  await expect(positionValue).toHaveText('4')
  await expect(records).toHaveCount(0)
  await step('label', 3)
  await expect(guide.locator('[data-battery-index="1"]')).toHaveAttribute('data-battery-name', 'C')
  await showsRecords(guide, { A: 2, C: 4, B: 6 })
  await step('lookup', 4)
  await expect(guide.locator('[data-battery-name][data-active="true"]')).toHaveAttribute('data-battery-name', 'B')
  await expect(namedValue).toHaveText('6')
  await step('update', 5)
  await showsRecords(guide, { A: 2, C: 4, B: 9 })
  await expect(guide.locator('[data-record-key][data-updated="true"]')).toHaveAttribute('data-record-key', 'B')
  await expect(output).toHaveCount(0)
  await expect(practice).toHaveCount(0)
  await previous.click()
  await expect(guide).toHaveAttribute('data-collection-stage', 'lookup')
  await showsRecords(guide, { A: 2, C: 4, B: 6 })
  await step('update', 5)
  await step('output', 6)
  await expect(output).toHaveText('{"A":2,"C":4,"B":9}')

  const verify = button(practice, '运行验证')
  const actualPosition = practice.getByTestId('collection-actual-position')
  const actualNamed = practice.getByTestId('collection-actual-named')
  const actualRecords = practice.getByTestId('collection-actual-records')
  await expect(verify).toBeDisabled()
  await practice.locator('[data-collection-case="0"]').click()
  await expect(practice.locator('[data-battery-name="B"]')).toHaveAttribute('data-battery-index', '0')
  await practice.locator('[data-position-option="7"]').click()
  await practice.locator('[data-named-option="7"]').click()
  await expect(verify).toBeDisabled()
  await practice.locator('[data-record-option="0"]').click()
  await expect(actualRecords).toHaveCount(0)
  await verify.click()
  await expect(practice).toHaveAttribute('data-match', 'false')
  await expect(practice.locator('[data-collection-field="position"]')).toHaveAttribute('data-match', 'true')
  await expect(practice.locator('[data-collection-field="named"]')).toHaveAttribute('data-match', 'false')
  await expect(practice.locator('[data-collection-field="records"]')).toHaveAttribute('data-match', 'false')
  await expect(actualPosition).toHaveText('7')
  await expect(actualNamed).toHaveText('1')
  await showsRecords(actualRecords, { B: 4, C: 7, A: 4 })
  await expect(completed).toHaveCount(0)

  await button(practice, '再猜一次').click()
  await expect(actualNamed).toHaveCount(0)
  await expect(verify).toBeDisabled()
  await practice.locator('[data-position-option="7"]').click()
  await practice.locator('[data-collection-case="1"]').click()
  await expect(practice.locator('[data-battery-name="B"]')).toHaveAttribute('data-battery-index', '2')
  await practice.locator('[data-named-option="0"]').click()
  await practice.locator('[data-record-option="1"]').click()
  await expect(verify).toBeDisabled()
  await practice.locator('[data-position-option="5"]').click()
  await verify.click()
  await expect(practice).toHaveAttribute('data-match', 'true')
  await expect(actualPosition).toHaveText('5')
  await expect(actualNamed).toHaveText('0')
  await showsRecords(actualRecords, { C: 2, A: 5, B: 3 })
  await expect(completed).toBeVisible()
})
