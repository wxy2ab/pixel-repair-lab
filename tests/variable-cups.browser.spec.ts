import { expect, test, type APIRequestContext, type Page } from '@playwright/test'
import type { Catalog } from '../src/shared/types'

async function lessons(request: APIRequestContext) {
  const response = await request.get('/api/levels')
  expect(response.ok()).toBe(true)
  const catalog = await response.json() as Catalog
  expect(catalog.issues).toEqual([])
  const cups = catalog.levels.find(level => level.id === 'variable-cups')
  const next = catalog.levels.find(level => level.id === 'python-program-overview')
  if (cups?.kind !== 'lecture' || !cups.execution || !next) throw new Error('Missing variable introduction')
  return { cups, execution: cups.execution, next }
}

async function openLesson(page: Page, title: string, mobile = false) {
  await page.locator('[data-unit="foundations"]').click()
  if (mobile) await page.getByRole('button', { name: 'Mission list', exact: true }).click()
  await page.locator('.mission-list button').filter({ has: page.getByText(title, { exact: true }) }).click()
  await expect(page.getByRole('heading', { name: title, level: 1 })).toBeVisible()
}

test('numbered cups distinguish empty, zero, name and address, and keep a copied reading when the first name changes', async ({ page, request }) => {
  const { cups, execution, next } = await lessons(request)
  const [demo, firstPractice, secondPractice] = execution.cases
  await page.goto('/')
  await openLesson(page, cups.title.zh)
  const lesson = page.getByTestId('variable-cups')
  const board = lesson.locator('[data-cup-address]')
  const source = lesson.locator('[data-cup-address="22"]')
  const copy = lesson.locator('[data-cup-address="20"]')
  const unused = lesson.locator('[data-cup-address="21"]')
  const code = page.getByTestId('cup-code')
  const check = page.locator('.mission-list [aria-current="step"] .mission-check')
  await expect(board).toHaveCount(4)
  await expect(lesson.locator('[data-cup-address][data-value=""]')).toHaveCount(4)
  await expect(code).toHaveCount(0)
  await expect(page.getByTestId('cup-verify')).toHaveCount(0)
  await source.click()
  await expect(source).toHaveAttribute('data-name', 'charge')
  await expect(source).toHaveAttribute('data-value', String(demo.input))
  await expect(code).toContainText('charge = scan()')
  await expect(code).not.toContainText('saved = charge')

  await unused.click()
  await expect(lesson).toHaveAttribute('data-stage', 'read')
  await expect(page.getByTestId('cup-hint')).toBeVisible()
  await source.click()
  await lesson.locator('[data-testid="cup-read-choice"][data-kind="address"]').click()
  await expect(lesson).toHaveAttribute('data-stage', 'read')
  await expect(lesson.getByTestId('cup-hint')).toContainText('22')
  await lesson.locator('[data-testid="cup-read-choice"][data-kind="value"]').click()
  await expect(source).toHaveAttribute('data-value', String(demo.input))
  await copy.click()
  await expect(copy).toHaveAttribute('data-name', 'saved')
  await expect(copy).toHaveAttribute('data-value', String(demo.input))
  await expect(lesson.locator('.vc-copy-path')).toHaveAttribute('data-direction', 'left')
  await expect(lesson.locator('.vc-copy-path span')).toHaveText(String(demo.input))
  await expect(code).toContainText('saved = charge')
  await source.click()
  await expect(source).toHaveAttribute('data-name', 'charge')
  await expect(source).toHaveAttribute('data-value', '0')
  await expect(source.locator('.vc-cup-note')).toHaveText(`${demo.input} → 0`)
  await expect(copy.locator('.vc-cup-note')).toHaveText('保留 ' + demo.input)
  await expect(copy).toHaveAttribute('data-value', String(demo.input))
  await expect(unused).toHaveAttribute('data-value', '')
  await copy.click()
  await expect(lesson).toHaveAttribute('data-stage', 'done')
  await expect(page.getByTestId('cup-output')).toContainText(String(demo.input))
  await expect(check).toHaveCount(0)

  const selectSample = (input: number) => page.locator(`[data-testid="cup-sample"][data-input="${input}"]`).click()
  const guess = (field: 'source' | 'copy', value: number) =>
    page.locator(`[data-cup-prediction="${field}"] [data-guess="${value}"]`).click()
  const verify = page.getByTestId('cup-verify')
  const feedback = page.getByTestId('cup-feedback')
  await selectSample(firstPractice.input)
  await guess('source', 0)
  await expect(verify).toBeDisabled()
  await guess('copy', 0)
  await verify.click()
  await expect(feedback).toHaveAttribute('data-match', 'false')
  await expect(copy).toHaveAttribute('data-value', String(firstPractice.input))
  await expect(source).toHaveAttribute('data-value', '0')
  await expect(lesson.getByTestId('cup-output')).toHaveText(String(firstPractice.input))
  await expect(check).toHaveCount(0)

  await selectSample(secondPractice.input)
  await expect(copy).toHaveAttribute('data-value', '')
  await expect(copy.locator('.vc-cup-note')).toBeEmpty()
  await expect(lesson.getByTestId('cup-output')).not.toHaveText(String(secondPractice.input))
  await expect(verify).toBeDisabled()
  await guess('source', 0)
  await guess('copy', secondPractice.input)
  await verify.click()
  await expect(feedback).toHaveAttribute('data-match', 'true')
  await expect(copy).toHaveAttribute('data-value', String(secondPractice.input))
  await expect(source).toHaveAttribute('data-value', '0')
  await expect(lesson.getByTestId('cup-output')).toHaveText(String(secondPractice.input))
  await expect(check).toBeVisible()
  await page.reload()
  await page.getByTestId('roadmap-resume').click()
  await expect(page.getByRole('heading', { name: next.title.zh, level: 1 })).toBeVisible()
  await page.getByRole('button', { name: '上一课', exact: true }).click()
  await expect(page.getByRole('heading', { name: cups.title.zh, level: 1 })).toBeVisible()
  await expect(check).toBeVisible()
})

test('the English shelf works on a narrow screen and can use different addresses', async ({ page, request }) => {
  const { cups } = await lessons(request)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await page.getByRole('button', { name: 'EN', exact: true }).click()
  await openLesson(page, cups.title.en, true)
  const lesson = page.getByTestId('variable-cups')
  const cup = (address: number) => lesson.locator(`[data-cup-address="${address}"]`)
  await expect(cup(23)).toHaveAccessibleName(/23/)
  await cup(23).click()
  await cup(23).click()
  await lesson.locator('[data-testid="cup-read-choice"][data-kind="value"]').click()
  for (const address of [21, 23, 21]) await cup(address).click()
  await expect(lesson).toHaveAttribute('data-stage', 'done')
  await expect(cup(23)).toHaveAttribute('data-value', '0')
  await expect(cup(21)).toHaveAttribute('data-name', 'saved')
  await expect(page.getByTestId('cup-verify')).toHaveAccessibleName(/[a-z]/i)
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
})
