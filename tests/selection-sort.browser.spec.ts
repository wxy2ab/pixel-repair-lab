import { expect, test, type Locator } from '@playwright/test'
import type { Catalog } from '../src/shared/types'

const button = (panel: Locator, name: string) => panel.getByRole('button', { name, exact: true })

async function names(panel: Locator) {
  return panel.locator('[data-battery-name]').evaluateAll(cards => cards.map(card => card.getAttribute('data-battery-name')))
}

test('selection sort compares, swaps, and settles one battery per round before verifying a fresh row', async ({ page, request }) => {
  const response = await request.get('/api/levels')
  expect(response.ok()).toBe(true)
  const { levels, issues } = await response.json() as Catalog
  expect(issues).toEqual([])
  const lesson = levels.find(level => level.id === 'selection-sort-notes')
  if (lesson?.kind !== 'lecture' || !lesson.execution?.selectionSort) throw new Error('Missing the selection sort lesson')

  await page.goto('/#track-algorithms')
  await page.locator('[data-unit="algorithm-intro"]').click()
  const mission = page.locator('.mission-list').getByRole('button').filter({ has: page.getByText(lesson.title.zh, { exact: true }) })
  await mission.click()
  await expect(page.getByRole('heading', { level: 1, name: lesson.title.zh, exact: true })).toBeVisible()

  const guide = page.getByTestId('selection-sort-lesson')
  const step = guide.getByTestId('selection-sort-step')
  const code = guide.getByTestId('selection-sort-code')
  const fixed = guide.getByTestId('selection-sort-fixed')
  const unsorted = guide.getByTestId('selection-sort-unsorted')
  const prediction = page.getByTestId('selection-sort-prediction')
  const card = (name: string) => guide.getByTestId('selection-sort-card-' + name)
  const click = (name: string) => button(guide, name).click()

  await expect(step).toHaveAttribute('data-kind', 'start')
  await expect(code).toHaveCount(0)
  expect(await names(unsorted)).toEqual(['A', 'B', 'C', 'D'])
  expect(await names(fixed)).toEqual([])
  await expect(prediction).toHaveCount(0)

  await click('开始第一轮')
  await expect(step).toHaveAttribute('data-candidate', '0')
  await expect(code).toContainText('min_index = start')
  await card('D').click()
  await expect(card('D')).toHaveAttribute('data-mistake', 'true')
  await expect(step).toHaveAttribute('data-kind', 'candidate')
  await card('B').click()
  await expect(step).toHaveAttribute('data-kind', 'compare')
  await expect(step).toHaveAttribute('data-index', '1')
  await expect(code).toContainText('smaller = row[index][1] < row[min_index][1]')
  await expect(guide.getByTestId('selection-sort-relation')).toContainText('3 < 6')
  await click('设为当前最小')
  await expect(step).toHaveAttribute('data-candidate', '1')
  await expect(code).toContainText('min_index = index')
  await card('C').click()
  await expect(step).toHaveAttribute('data-candidate', '1')
  await card('D').click()
  await click('设为当前最小')
  await card('D').click()
  await expect(step).toHaveAttribute('data-kind', 'select')
  await card('A').click()
  await expect(step).toHaveAttribute('data-kind', 'swap')
  for (const line of ['held = row[start]', 'row[start] = row[min_index]', 'row[min_index] = held']) {
    await expect(code).toContainText(line)
  }
  expect(await names(unsorted)).toEqual(['D', 'B', 'C', 'A'])
  expect(await names(fixed)).toEqual([])
  await click('上一步')
  expect(await names(unsorted)).toEqual(['A', 'B', 'C', 'D'])
  await card('A').click()
  await click('固定这一格')
  await expect(step).toHaveAttribute('data-sorted', '1')
  await expect(code).toContainText('settled = start + 1')
  expect(await names(fixed)).toEqual(['D'])
  expect(await names(unsorted)).toEqual(['B', 'C', 'A'])

  await click('开始下一轮')
  await card('C').click()
  await card('A').click()
  await card('B').click()
  await expect(step).toHaveAttribute('data-kind', 'select')
  await click('固定这一格')
  await expect(step).toHaveAttribute('data-sorted', '2')
  expect(await names(fixed)).toEqual(['D', 'B'])
  expect(await names(unsorted)).toEqual(['C', 'A'])

  await click('开始下一轮')
  await card('A').click()
  await click('设为当前最小')
  await card('A').click()
  await card('C').click()
  await click('固定这一格')
  expect(await names(fixed)).toEqual(['D', 'B', 'A'])
  expect(await names(unsorted)).toEqual(['C'])
  await expect(prediction).toHaveCount(0)
  await click('确认最后一格')
  await click('查看结果')
  await expect(step).toHaveAttribute('data-kind', 'return')
  expect(await names(fixed)).toEqual(['D', 'B', 'A', 'C'])
  expect(await names(unsorted)).toEqual([])
  await expect(prediction).toBeVisible()

  const verify = button(prediction, '运行验证')
  const rounds = prediction.getByTestId('selection-sort-pick-rounds')
  const order = prediction.getByTestId('selection-sort-pick-order')
  const completed = mission.locator('.mission-check')
  const fill = async (panel: Locator, batteries: string[]) => {
    for (const name of batteries) await panel.locator(`button[data-battery-name="${name}"]`).click()
  }

  await expect(verify).toBeDisabled()
  await fill(rounds, ['L', 'N', 'P', 'K'])
  await expect(verify).toBeDisabled()
  await fill(order, ['L', 'N', 'P', 'M', 'K'])
  await expect(prediction.getByTestId('selection-sort-actual-order')).toHaveCount(0)
  await verify.click()
  await expect(prediction).toHaveAttribute('data-match', 'false')
  await expect(rounds.locator('[data-slot-index="3"]')).toHaveAttribute('data-match', 'false')
  await expect(prediction.getByTestId('selection-sort-actual-rounds')).toHaveText('L → N → P → M')
  await expect(prediction.getByTestId('selection-sort-actual-order')).toHaveText('L → N → P → M → K')
  await expect(completed).toHaveCount(0)
  await button(rounds, '撤回上一步').click()
  await fill(rounds, ['M'])
  await verify.click()
  await expect(prediction).toHaveAttribute('data-match', 'true')
  await expect(completed).toBeVisible()
})
