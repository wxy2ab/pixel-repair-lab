test('3D fullscreen uses the full canvas and pans and fits the actual camera without taking a turn', async ({ page }) => {
  test.slow()
  await openArena(page, '3d')
  const root = await enterMap(page)
  await expect(root.locator('.station-viewport')).toHaveAttribute('data-ready', 'true', { timeout: 20000 })
  const canvas = page.getByTestId('station-3d-canvas')
  const view = await page.evaluate(() => ({ width: innerWidth, height: innerHeight }))
  const surface = await bounds(canvas)
  expect(surface.width).toBeGreaterThan(view.width * 0.9)
  expect(surface.height).toBeGreaterThan(view.height * 0.72)
  await canvas.focus()
  const zoom = await canvas.getAttribute('data-camera-zoom')
  const center = await canvas.getAttribute('data-camera-center')
  expect(zoom).toBeTruthy()
  expect(center).toBeTruthy()
  await page.keyboard.press('+')
  await expect(canvas).not.toHaveAttribute('data-camera-zoom', zoom!)
  await page.keyboard.press('a')
  await expect(canvas).not.toHaveAttribute('data-camera-center', center!)
  await page.keyboard.press('Home')
  await expect(canvas).toHaveAttribute('data-camera-center', center!)
  await expect(canvas).toHaveAttribute('data-camera-zoom', zoom!)
  await expect(page.getByTestId('arena-turn')).toHaveText('回合 0/42')
  await root.getByRole('button', { name: '控制芽芽', exact: true }).click()
  await page.keyboard.press('ArrowRight')
  await expect(root.locator('.tilemap')).toHaveAttribute('aria-label', '机器人位于 2，5')
})

test('a grid challenge runs command cards from the floating console and keeps the board and cards when leaving', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('pixel-repair-lab:board-view', '2d'))
  await page.goto('/#challenge-browse')
  await page.locator('[data-challenge-level="challenge-six-step-detour"]').click()
  const tools = page.locator('.station-tools .arena-map-controls')
  await expect(tools.getByRole('button', { name: '全屏地图', exact: true })).toBeVisible()
  const inlineToggle = tools.getByTestId('arena-console-toggle')
  const inlinePalette = page.locator('[data-add-card="right"]')
  await inlineToggle.click()
  await expect(inlinePalette).toBeHidden()
  await inlineToggle.click()
  await expect(inlinePalette).toBeVisible()
  const root = await enterMap(page)
  const toggle = root.getByTestId('arena-console-toggle')
  await toggle.click()
  const palette = root.locator('[data-add-card="right"]')
  await palette.click()
  await palette.click()
  await toggle.click()
  await expect(palette).toBeHidden()
  await root.getByTestId('grid-single-step').click()
  await expect(root.getByTestId('grid-step-reading')).toContainText('move("right")')
  await expect(root.locator('.tilemap')).toHaveAttribute('aria-label', '机器人位于 4，3')
  await page.getByRole('button', { name: '退出全屏', exact: true }).click()
  await expect(palette).toBeVisible()
  await expect(root.locator('[data-card="right"]')).toHaveCount(2)
  await expect(root.getByTestId('grid-turn-budget')).toContainText('1 / 6')
})
