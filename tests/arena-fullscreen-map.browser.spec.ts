import { expect, test, type Locator, type Page } from '@playwright/test'

test.use({ launchOptions: { args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] } })

async function openArena(page: Page, view: '2d' | '3d' = '2d') {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.addInitScript(view => localStorage.setItem('pixel-repair-lab:board-view', view), view)
  await page.goto('/#challenge-browse')
  await page.locator('[data-challenge-level="challenge-neon-pinball-cup"]').click()
  await expect(page.getByTestId('arena-turn')).toHaveText('回合 0/42')
}

async function enterMap(page: Page) {
  await page.getByRole('button', { name: '全屏地图', exact: true }).click()
  const root = page.getByTestId('arena-map-workspace')
  await expect(root).toHaveAttribute('data-map-fullscreen', 'true')
  return root
}

async function bounds(locator: Locator) {
  const box = await locator.boundingBox()
  if (!box) throw new Error('Expected a visible map element')
  return box
}

// An IME may replace key with Process while the physical code still identifies the key.
function imeKey(page: Page, code: string, shiftKey = false) {
  return page.evaluate(({ code, shiftKey }) => {
    const target = document.activeElement ?? document.body
    return target.dispatchEvent(new KeyboardEvent('keydown', {
      key: 'Process', code, shiftKey, keyCode: 229, isComposing: true, bubbles: true, cancelable: true,
    }))
  }, { code, shiftKey })
}

test('fullscreen map floats the same editor over the board and preserves a running draft on exit', async ({ page }) => {
  await openArena(page)
  const editor = page.getByRole('textbox', { name: '编写 Python', exact: true })
  const source = 'move("right")\npick()\nguard()'
  await editor.fill(source)
  const step = page.getByTestId('play-toolbar').getByRole('button', { name: '单步执行' })
  await step.click()
  const turn = page.getByTestId('arena-turn')
  await expect(turn).toHaveText('回合 1/42')
  const root = await enterMap(page)
  const toggle = page.getByTestId('arena-console-toggle')
  await expect(editor).toBeHidden()
  await expect(toggle).toHaveAttribute('aria-expanded', 'false')
  const board = root.locator('.station-flat-board .map-well')
  const original = await bounds(board)
  const size = await page.evaluate(() => ({ width: innerWidth, height: innerHeight }))
  expect(original.width).toBeGreaterThan(size.width * 0.72)
  expect(original.height).toBeGreaterThan(size.height * 0.62)

  await toggle.click()
  await expect(editor).toHaveValue(source)
  const panel = await bounds(root.locator('.arena-console'))
  expect(panel.x).toBeLessThan(original.x + original.width)
  expect(panel.y).toBeLessThan(original.y + original.height)
  expect(panel.x + panel.width).toBeGreaterThan(original.x)
  expect(panel.y + panel.height).toBeGreaterThan(original.y)
  const edited = source + '\nwait()'
  await editor.fill(edited)
  const openBoard = await bounds(board)
  expect(Math.abs(openBoard.width - original.width)).toBeLessThan(2)
  expect(Math.abs(openBoard.x - original.x)).toBeLessThan(2)
  await toggle.click()
  await expect(turn).toHaveText('回合 1/42')
  await page.keyboard.press('Escape')
  await expect(root).not.toHaveAttribute('data-map-fullscreen', 'true')
  await expect(editor).toHaveValue(edited)
  await expect(editor).toBeVisible()
  await expect(turn).toHaveText('回合 1/42')
  await enterMap(page)
  await expect.poll(() => root.evaluate(board => document.fullscreenElement?.contains(board))).toBe(true)
  await page.evaluate(() => document.exitFullscreen())
  await expect(root).not.toHaveAttribute('data-map-fullscreen', 'true')
  await expect(page.getByRole('button', { name: '全屏地图', exact: true })).toBeFocused()
})

test('flat map fits a phone without native fullscreen, pans when zoomed, and resets in place', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.addInitScript(() => {
    Element.prototype.requestFullscreen = () => Promise.reject(new DOMException('Unavailable', 'NotAllowedError'))
  })
  await openArena(page)
  const root = await enterMap(page)
  const size = await page.evaluate(() => ({ width: innerWidth, height: innerHeight }))
  const frame = await bounds(root)
  expect(Math.abs(frame.width - size.width)).toBeLessThan(2)
  expect(Math.abs(frame.height - size.height)).toBeLessThan(2)
  const board = root.locator('.map-well')
  const fit = await bounds(board)
  const flat = root.locator('.station-flat-board:visible')
  await flat.focus()
  await page.keyboard.press('+')
  await expect.poll(async () => (await bounds(board)).width).toBeGreaterThan(fit.width * 1.05)
  const zoomed = await bounds(board)
  await page.keyboard.press('d')
  await expect.poll(async () => Math.abs((await bounds(board)).x - zoomed.x)).toBeGreaterThan(2)
  await page.keyboard.press('Home')
  await expect.poll(async () => Math.abs((await bounds(board)).width - fit.width)).toBeLessThan(2)
  await expect.poll(async () => Math.abs((await bounds(board)).x - fit.x)).toBeLessThan(2)
  await root.getByRole('button', { name: '拉近', exact: true }).click()
  await expect.poll(async () => (await bounds(board)).width).toBeGreaterThan(fit.width)
  await root.getByRole('button', { name: '适应全图', exact: true }).click()
  await expect.poll(async () => Math.abs((await bounds(board)).width - fit.width)).toBeLessThan(2)
  const toolbar = root.getByTestId('play-toolbar')
  const expanded = await bounds(toolbar)
  await toolbar.getByRole('button', { name: '收起操作栏', exact: true }).click()
  await expect(toolbar.getByRole('button', { name: '展开操作栏', exact: true })).toHaveAttribute('aria-expanded', 'false')
  const foldedHeight = (await bounds(toolbar)).height
  expect(foldedHeight).toBeLessThan(expanded.height)
  expect(foldedHeight).toBeLessThan(65)
  await expect(toolbar.getByRole('button', { name: '运行', exact: true })).toBeInViewport({ ratio: 1 })
  await expect(toolbar.getByTestId('arena-console-toggle')).toBeInViewport({ ratio: 1 })
  await toolbar.getByRole('button', { name: '展开操作栏', exact: true }).click()
  await expect(toolbar.getByRole('button', { name: '单步执行', exact: true })).toBeVisible()
  await page.getByTestId('arena-console-toggle').click()
  await expect(page.getByRole('textbox', { name: '编写 Python', exact: true })).toBeInViewport()
  const panel = await bounds(root.locator('.arena-console'))
  const coveredHeight = Math.max(0, Math.min(fit.y + fit.height, panel.y + panel.height) - Math.max(fit.y, panel.y))
  expect(coveredHeight).toBeLessThan(fit.height * 0.75)
  await expect(page.getByRole('button', { name: '退出全屏', exact: true })).toBeInViewport({ ratio: 1 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(size.width)
  await page.getByRole('button', { name: '退出全屏', exact: true }).click()
  await expect(root).not.toHaveAttribute('data-map-fullscreen', 'true')
})

test('the first physical movement key starts fullscreen practice and IME keys stay with the focused control', async ({ page }) => {
  await openArena(page)
  const root = await enterMap(page)
  await expect.poll(() => root.evaluate(board => document.fullscreenElement?.contains(board))).toBe(true)
  const character = root.getByRole('button', { name: '控制芽芽', exact: true })
  await character.click()
  // No click on Start or focus() on the board between choosing Sprout and moving.
  expect(await imeKey(page, 'KeyD')).toBe(false)
  const board = root.locator('.tilemap')
  await expect(board).toHaveAttribute('aria-label', '机器人位于 2，5')
  const button = (name: string) => root.getByRole('button', { name, exact: true })
  await button('暂停对局').click()
  await button('收起操作栏').click()
  const resume = button('继续对局')
  await expect(resume).toBeInViewport({ ratio: 1 })
  const turn = await root.getByTestId('arena-turn').innerText()
  await imeKey(page, 'ArrowRight')
  await expect(resume).toBeEnabled()
  await expect(root.getByTestId('arena-turn')).toHaveText(turn)
  await resume.click()
  await expect(button('暂停对局')).toBeEnabled()
  expect(await imeKey(page, 'ArrowRight', true)).toBe(false)
  const events = root.getByTestId('arena-turn-events').locator('[data-actor-id="player"]')
  await expect(events).toContainText('向右发射')
  await root.getByTestId('arena-console-toggle').click()
  const editor = root.locator('#realtime-python')
  await editor.fill('')
  expect(await imeKey(page, 'KeyD')).toBe(true)
  expect(await imeKey(page, 'KeyM')).toBe(true)
  await page.keyboard.insertText('芽芽')
  await expect(editor).toHaveValue('芽芽')
  await expect(character).toHaveAttribute('aria-pressed', 'true')
  await expect(events).toContainText('等待')
  await expect(board).toHaveAttribute('aria-label', '机器人位于 2，5')
})

test('timed arena switches between map and character keys and protects the floating editor', async ({ page }) => {
  await openArena(page)
  await page.getByRole('button', { name: '紧张', exact: true }).click()
  const map = page.getByRole('button', { name: '查看地图', exact: true })
  const character = page.getByRole('button', { name: '控制芽芽', exact: true })
  await expect(map).toHaveAttribute('aria-pressed', 'true')
  await expect(character).toHaveAttribute('aria-pressed', 'false')
  await character.click()
  const root = await enterMap(page)
  await expect(character).toHaveAttribute('aria-pressed', 'true')
  await map.click()
  const toolbar = page.getByTestId('play-toolbar')
  await toolbar.getByRole('button', { name: '开始', exact: true }).click()
  await expect(toolbar.getByRole('button', { name: '暂停对局', exact: true })).toBeEnabled()
  const flat = root.locator('.station-flat-board:visible')
  const events = root.getByTestId('arena-turn-events').locator('[data-actor-id="player"]')
  await page.keyboard.press('ArrowRight')
  await expect(root.getByTestId('station-cell-inspection')).toContainText('(2, 5)')
  for (const key of ['Shift+ArrowRight', 'e', 'g']) await page.keyboard.press(key)
  await expect(events).toContainText('等待')
  await expect(root.locator('.tilemap')).toHaveAttribute('aria-label', '机器人位于 1，5')
  await flat.press('m')
  await expect(character).toHaveAttribute('aria-pressed', 'true')
  await flat.focus()
  await page.keyboard.press('ArrowRight')
  await expect(events).toContainText('向右移动')
  await expect(root.locator('.tilemap')).toHaveAttribute('aria-label', '机器人位于 2，5')
  await page.keyboard.press('e')
  await expect(root.locator('.tile[data-item-id="power-1"]')).toHaveCount(0)
  await page.keyboard.press('Shift+ArrowRight')
  await expect(events).toContainText('向右发射')
  await page.keyboard.press('g')
  await expect(events).toContainText('展开防护')
  await page.getByTestId('arena-console-toggle').click()
  const editor = root.locator('#realtime-python')
  await editor.fill('')
  await editor.pressSequentially('wasdegm')
  await editor.press('ArrowLeft')
  await editor.press('Shift+ArrowRight')
  await expect(editor).toHaveValue('wasdegm')
  await expect(character).toHaveAttribute('aria-pressed', 'true')
  await expect(root.locator('[data-arena-action][aria-pressed="true"]')).toHaveCount(0)
  await expect(events).toContainText('等待')
  await expect(root.locator('.tilemap')).toHaveAttribute('aria-label', '机器人位于 2，5')
  await toolbar.getByRole('button', { name: '暂停对局', exact: true }).click()
  await page.getByRole('button', { name: '退出全屏', exact: true }).click()
  await expect(character).toHaveAttribute('aria-pressed', 'true')
  const turn = await root.getByTestId('arena-turn').innerText()
  await flat.press('m')
  await expect(map).toHaveAttribute('aria-pressed', 'true')
  await expect(root.getByTestId('arena-turn')).toHaveText(turn)
  await expect(toolbar.getByRole('button', { name: '继续对局', exact: true })).toBeEnabled()
})

