import { expect, test, type Page } from '@playwright/test'

const button = (page: Page, name: string) => page.getByRole('button', { name, exact: true })
const mark = (page: Page, kind: 'current' | 'next') =>
  page.locator(`.program-section li[data-execution-${kind}] > .instruction-main`)

async function open(page: Page, id: string) {
  await page.addInitScript(() => localStorage.setItem('pixel-repair-lab:board-view', '2d'))
  await page.goto('/#challenge-zone')
  await page.getByRole('region', { name: '自由选关', exact: true }).locator(`[data-challenge-level="${id}"]`).click()
}

async function add(page: Page, ...ids: string[]) {
  for (const id of ids) await page.locator(`[data-add-card="${id}"]`).click()
}

test('the next command follows the map branch, identifies duplicate cards, and stops at the failing move', async ({ page }) => {
  await open(page, 'challenge-six-step-detour')
  await add(page, 'scan', 'if-wall')
  await button(page, '向代码块添加指令').click()
  await add(page, 'right', 'right', 'right')
  await button(page, '回到主程序').click()
  await add(page, 'otherwise')
  await page.locator('[data-card="otherwise"]').getByRole('button', { name: '向代码块添加指令' }).click()
  await add(page, 'left')
  const current = mark(page, 'current'), next = mark(page, 'next')
  const step = button(page, '单步执行')
  await step.click()
  await expect(current.locator('[data-select-card]')).toHaveAttribute('data-select-card', '0')
  await expect(next.locator('[data-select-card]')).toHaveAttribute('data-select-card', '1')
  await expect(current).toHaveCSS('outline-style', 'solid')
  await expect(next).toHaveCSS('outline-style', 'dashed')
  await step.click()
  await expect(page.locator('.station-action-cue[data-action="if"]')).toContainText('True')
  await expect(next.locator('[data-select-card]')).toHaveAttribute('data-select-card', '1.0')
  await step.click()
  await expect(current.locator('[data-select-card]')).toHaveAttribute('data-select-card', '1.0')
  await expect(next.locator('[data-select-card]')).toHaveAttribute('data-select-card', '1.1')
  await step.click()
  await step.click()
  await expect(page.locator('.output-panel .error-message')).toContainText('第 5 行')
  await expect(current.locator('[data-select-card]')).toHaveAttribute('data-select-card', '1.2')
  await expect(next).toHaveCount(0)
  await page.getByTestId('map-scenario-1').click()
  await step.click()
  await expect(current.locator('[data-select-card]')).toHaveAttribute('data-select-card', '0')
  await step.click()
  await expect(page.locator('.station-action-cue[data-action="if"]')).toContainText('False')
  await expect(next.locator('[data-select-card]')).toHaveAttribute('data-select-card', '2')
  await step.click()
  await expect(next.locator('[data-select-card]')).toHaveAttribute('data-select-card', '2.0')
  await page.locator('[data-parameter="side"]').selectOption('right')
  await expect(current).toHaveCount(0)
  await expect(next).toHaveCount(0)
})

test('the loop header and its move card alternate before resuming playback', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 720 })
  await open(page, 'challenge-brass-key-store')
  await add(page, 'up', 'repeat')
  await button(page, '向代码块添加指令').click()
  await add(page, 'right')
  await button(page, '回到主程序').click()
  await add(page, 'right')
  const step = button(page, '单步执行')
  await step.click()
  await step.click()
  const repeated = page.locator('.program-section [data-card="repeat"] [data-card="right"]')
  await expect(mark(page, 'current').locator('[data-select-card]')).toHaveAttribute('data-select-card', '1')
  await expect(repeated).toHaveAttribute('data-execution-next', 'true')
  await step.click()
  await expect(repeated).toHaveAttribute('data-execution-current', 'true')
  await expect(mark(page, 'next').locator('[data-select-card]')).toHaveAttribute('data-select-card', '1')
  await button(page, '继续运行').click()
  await expect(page.locator('.output-panel .error-message')).toContainText('第 4 行')
  await expect(mark(page, 'current').locator('[data-select-card]')).toHaveAttribute('data-select-card', '2')
  await expect(mark(page, 'next')).toHaveCount(0)
})

test('long generated code follows both lines within its own viewport and preserves the selected card and source', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 740 })
  await open(page, 'challenge-six-step-detour')
  await add(page, ...Array<string>(29).fill('scan'))
  const selected = page.locator('[data-select-card="22"]')
  await selected.check()
  const source = Array(29).fill('nearby = scan()').join('\n')
  const preview = page.getByTestId('generated-code'), step = button(page, '单步执行')
  await step.click()
  await step.focus()
  await preview.scrollIntoViewIfNeeded()
  const scrollY = await page.evaluate(() => window.scrollY)
  for (let index = 1; index < 23; index++) await step.press('Enter')
  await expect(preview.locator('[aria-current="step"]')).toHaveAttribute('data-line', '23')
  await expect(preview.locator('[data-next]')).toHaveAttribute('data-line', '24')
  expect(await preview.evaluate(el => {
    const top = el.getBoundingClientRect().top + el.clientTop
    return el.scrollTop > 0 && [...el.querySelectorAll('[aria-current="step"], [data-next]')].every(row => {
      const bounds = row.getBoundingClientRect()
      return bounds.top >= top - 1 && bounds.bottom <= top + el.clientHeight + 1
    })
  })).toBe(true)
  expect(await page.evaluate(() => window.scrollY)).toBe(scrollY)
  await expect(step).toBeFocused()
  await expect(selected).toBeChecked()
  expect(await preview.textContent()).toBe(source)
  await button(page, '复制到手写模式').click()
  await expect(page.getByRole('textbox', { name: '编写 Python' })).toHaveValue(source)
})
