import { expect, test, type Locator } from '@playwright/test'
import type { Catalog } from '../src/shared/types'

const button = (panel: Locator, name: string) => panel.getByRole('button', { name, exact: true })

test('insertion and removal shift list indexes, and a new row checks both the order and the indexed battery', async ({ page, request }) => {
  const response = await request.get('/api/levels')
  expect(response.ok()).toBe(true)
  const { levels, issues } = await response.json() as Catalog
  expect(issues).toEqual([])
  const lesson = levels.find(level => level.id === 'list-positions')
  if (lesson?.kind !== 'lecture' || !lesson.execution?.listPositions) throw new Error('Missing the list positions lesson')
  const source = lesson.execution.source.split('\n')

  await page.goto('/#track-algorithms')
  await page.locator('[data-unit="structures"]').click()
  const mission = page.locator('.mission-list').getByRole('button').filter({ has: page.getByText(lesson.title.zh, { exact: true }) })
  await mission.click()
  await expect(page.getByRole('heading', { name: lesson.title.zh, level: 1, exact: true })).toBeVisible()

  const guide = page.getByTestId('list-positions-lesson')
  const batteries = guide.getByTestId('list-position-batteries')
  const code = guide.getByTestId('list-positions-code')
  const output = guide.getByTestId('list-positions-output')
  const picked = guide.getByTestId('list-positions-battery')
  const practice = page.getByTestId('list-positions-prediction')
  const completed = mission.locator('.mission-check')
  const battery = (name: string) => batteries.locator(`[data-battery-name="${name}"]`)

  async function state(stage: string, line: number, order: string[]) {
    await expect(guide).toHaveAttribute('data-list-stage', stage)
    await expect(code.locator('code')).toHaveCount(line)
    await expect(code.locator(`[data-line="${line}"][aria-current="step"] code`)).toHaveText(source[line - 1])
    expect(await batteries.locator('[data-battery-name]').evaluateAll(elements => elements.map(element => element.getAttribute('data-battery-name')))).toEqual(order)
    for (const [index, name] of order.entries()) await expect(battery(name)).toHaveAttribute('data-battery-index', String(index))
  }

  await expect(guide).toHaveAttribute('data-list-stage', 'start')
  await expect(battery('A')).toHaveAttribute('data-battery-index', '0')
  await expect(guide.getByRole('status')).toContainText('从左边的 0 开始数')
  await expect(code).toHaveCount(0)
  await expect(practice).toHaveCount(0)
  await battery('A').getByRole('button').click()
  await expect(guide.getByRole('status')).toContainText('再试一次')
  await expect(code).toHaveCount(0)
  await battery('B').getByRole('button').click()
  await state('read', 2, ['A', 'B', 'C'])
  await expect(picked).toHaveText('B')

  await guide.locator('[data-insert-index="0"]').click()
  await expect(guide).toHaveAttribute('data-list-stage', 'read')
  await expect(guide.getByRole('status')).toContainText('再试一次')
  await guide.locator('[data-insert-index="1"]').click()
  await state('insert', 3, ['A', 'D', 'B', 'C'])
  await expect(picked).toHaveText('D')
  await expect(battery('B')).toHaveAttribute('data-previous-index', '1')
  await expect(battery('C')).toHaveAttribute('data-previous-index', '2')
  await expect(battery('A')).not.toHaveAttribute('data-previous-index', /./u)

  await battery('B').getByRole('button').click()
  await state('remove', 4, ['A', 'D', 'C'])
  await expect(picked).toHaveText('B')
  await expect(battery('B')).toHaveCount(0)
  await expect(battery('C')).toHaveAttribute('data-previous-index', '3')
  await expect(battery('C')).toHaveAttribute('data-charge', '6')
  await button(guide, '上一步').click()
  await state('insert', 3, ['A', 'D', 'B', 'C'])
  await battery('B').getByRole('button').click()
  await state('remove', 4, ['A', 'D', 'C'])
  await expect(practice).toHaveCount(0)
  await battery('D').getByRole('button').click()
  await state('select', 5, ['A', 'D', 'C'])
  await expect(picked).toHaveText('D')
  await expect(output).toHaveCount(0)
  await button(guide, '下一步').click()
  await state('output', 6, ['A', 'D', 'C'])
  await expect(output).toHaveText('D')

  const verify = button(practice, '运行验证')
  const actualOrder = practice.getByTestId('list-actual-order')
  const actualPicked = practice.getByTestId('list-actual-picked')
  await expect(practice.locator('[data-battery-name="Q"]')).toHaveAttribute('data-charge', '0')
  await expect(verify).toBeDisabled()
  await practice.locator('[data-order-option="0"]').click()
  await expect(verify).toBeDisabled()
  await practice.locator('[data-picked-option="Q"]').click()
  await expect(actualOrder).toHaveCount(0)
  await verify.click()
  await expect(practice).toHaveAttribute('data-match', 'false')
  await expect(actualOrder).toHaveText('["R","T","Q","S"]')
  await expect(actualPicked).toHaveText('Q')
  await expect(completed).toHaveCount(0)

  await button(practice, '再猜一次').click()
  await expect(actualOrder).toHaveCount(0)
  await expect(verify).toBeDisabled()
  await practice.locator('[data-order-option="1"]').click()
  await practice.locator('[data-list-case="1"]').click()
  await expect(practice.locator('[data-order-option="1"]')).toHaveAttribute('aria-pressed', 'false')
  await practice.locator('[data-order-option="1"]').click()
  await practice.locator('[data-picked-option="M"]').click()
  await verify.click()
  await expect(practice).toHaveAttribute('data-match', 'false')
  await expect(actualOrder).toHaveText('["L","M","N"]')
  await expect(actualPicked).toHaveText('N')
  await expect(completed).toHaveCount(0)
  await practice.locator('[data-picked-option="N"]').click()
  await verify.click()
  await expect(practice).toHaveAttribute('data-match', 'true')
  await expect(completed).toBeVisible()
})
