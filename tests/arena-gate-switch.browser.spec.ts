import { expect, test } from '@playwright/test'

test.use({ launchOptions: { args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] } })

test('picking the organ stop opens its two marked gates in the arena and on the minimap', async ({ page }) => {
  test.slow()
  await page.addInitScript(() => localStorage.setItem('pixel-repair-lab:board-view', '2d'))
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/#challenge-browse')
  await page.locator('[data-challenge-level="challenge-chime-pipe-gallery"]').click()
  await page.getByRole('textbox', { name: '编写 Python', exact: true }).fill('pick()\nwait()')
  await page.getByRole('button', { name: '全屏地图', exact: true }).click()
  const arena = page.getByTestId('arena-map-workspace')
  const switchTile = arena.locator('.tile[data-gate-switch="organ-stop"]')
  const firstGate = arena.locator('.tile[data-x="4"][data-y="8"]')
  const secondGate = arena.locator('.tile[data-x="8"][data-y="9"]')
  const minimap = arena.getByTestId('minimap-surface')
  await expect(switchTile).toBeVisible()
  await expect(firstGate).toHaveAttribute('data-switch-gate', 'locked')
  await expect(secondGate).toHaveAttribute('data-switch-gate', 'locked')
  await expect(minimap.locator('[data-minimap-marker="switch"]')).toHaveCount(1)
  await switchTile.click()
  await expect(arena.getByTestId('station-cell-inspection')).toContainText('闸门开关 · 打开 (4, 8) · (8, 9)')
  await arena.getByRole('button', { name: '3D', exact: true }).click()
  await expect(arena.locator('.station-viewport')).toHaveAttribute('data-ready', 'true', { timeout: 20000 })
  await expect(arena.getByTestId('station-cell-inspection')).toContainText('闸门开关')
  await arena.getByRole('button', { name: '2D', exact: true }).click()
  await arena.getByRole('button', { name: '单步执行', exact: true }).click()
  await expect(switchTile).toHaveCount(0)
  for (const gate of [firstGate, secondGate]) {
    await expect(gate).toHaveAttribute('data-switch-gate', 'open')
    await expect(gate).toHaveAttribute('data-arena-change', 'opened')
  }
  await expect(minimap.locator('[data-minimap-marker="switch"]')).toHaveCount(0)
  await arena.getByRole('button', { name: '战况', exact: true }).click()
  await expect(arena.getByTestId('arena-turn-events')).toContainText('开关启动 · 打开 (4, 8) · (8, 9)')
  await arena.getByRole('button', { name: '战况', exact: true }).click()
  await firstGate.click()
  await arena.getByRole('button', { name: '3D', exact: true }).click()
  await expect(arena.locator('.station-viewport')).toHaveAttribute('data-ready', 'true', { timeout: 20000 })
  await expect(arena.getByTestId('station-cell-inspection')).toContainText('(4, 8) 通道已开')
})
