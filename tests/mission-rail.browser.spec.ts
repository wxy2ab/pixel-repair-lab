import { expect, test, type Page } from '@playwright/test'

const railKey = 'pixel-repair-lab:mission-rail'
const enterPython = (page: Page) => page.locator('[data-unit="foundations"]').click()
const heading = (page: Page) => page.getByRole('heading', { level: 1 })

test('compact navigation moves between lessons and temporarily opens the full list without changing the layout', async ({ page }) => {
  await page.goto('/')
  await enterPython(page)
  const list = page.locator('.mission-list')
  const first = await list.locator('[aria-current="step"] .mission-name').innerText()
  const second = await list.locator('.mission-name').nth(1).innerText()
  const work = page.locator('.app-main > main')
  const pinnedWidth = await work.evaluate(node => node.clientWidth)
  await page.getByRole('button', { name: '精简导航', exact: true }).click()

  const compact = page.getByRole('navigation', { name: '精简导航' })
  await expect(list).toBeHidden()
  await expect(compact.getByRole('button', { name: '上一课' })).toBeDisabled()
  await compact.getByRole('button', { name: '下一课' }).click()
  await expect(heading(page)).toHaveText(second)
  await compact.getByRole('button', { name: '上一课' }).click()
  await expect(heading(page)).toHaveText(first)
  const compactWidth = await work.evaluate(node => node.clientWidth)
  expect(compactWidth).toBeGreaterThan(pinnedWidth + 100)

  const open = compact.getByRole('button', { name: '展开任务列表栏' })
  await open.click()
  const drawer = page.getByRole('dialog', { name: '任务列表' })
  await expect(drawer.locator('[aria-current="step"] .mission-name')).toHaveText(first)
  expect(await work.evaluate(node => node.clientWidth)).toBe(compactWidth)
  await page.keyboard.press('Escape')
  await expect(drawer).toBeHidden()
  await expect(open).toBeFocused()

  // Reloading while the drawer is open restores the compact preference, not the drawer.
  await open.click()
  await page.reload()
  await enterPython(page)
  await expect(compact).toBeVisible()
  await expect(drawer).toBeHidden()
  await open.click()
  await drawer.getByRole('button', { name: '固定侧栏' }).click()
  await expect(drawer).toBeHidden()
  await expect(list.locator('[aria-current="step"]')).toBeInViewport()
  expect(await work.evaluate(node => node.clientWidth)).toBe(pinnedWidth)
})

test('the legacy hidden preference leaves the full workspace available after a drawer selection', async ({ page }) => {
  await page.addInitScript(key => localStorage.setItem(key, 'hidden'), railKey)
  await page.goto('/')
  await page.locator('[data-challenge-level="challenge-quiet-power-window"]').click()
  const work = page.locator('.app-main > main')
  const open = page.getByRole('button', { name: '展开任务列表栏', exact: true })
  await expect(open).toBeVisible()
  await expect(page.locator('.mission-list')).toBeHidden()
  expect(await work.evaluate(node => node.getBoundingClientRect().left)).toBeLessThan(2)
  const width = await work.evaluate(node => node.clientWidth)
  const editor = page.getByRole('textbox', { name: '编写 Python' })
  const draft = (await editor.inputValue()) + '\n    # 接下来检查第二个用例'
  await editor.fill(draft)
  const secondCase = page.getByRole('group', { name: '选择要查看的用例' }).getByRole('button', { name: '用例 2', exact: true })
  await secondCase.click()

  await open.click()
  const drawer = page.getByRole('dialog', { name: '任务列表' })
  await expect(drawer.locator('[aria-current="step"]')).toBeInViewport()
  const edge = await drawer.evaluate(node => node.getBoundingClientRect().right)
  await page.mouse.click(edge + 8, 20)
  await expect(drawer).toBeHidden()
  await expect(open).toBeFocused()
  await expect(editor).toHaveValue(draft)
  await expect(secondCase).toHaveAttribute('aria-pressed', 'true')
  await open.click()
  const destination = drawer.locator('.mission-list button:not([aria-current])').first()
  const title = await destination.locator('.mission-name').innerText()
  await destination.click()
  await expect(heading(page)).toHaveText(title)
  await expect(drawer).toBeHidden()
  await expect(open).toBeVisible()
  expect(await work.evaluate(node => node.clientWidth)).toBe(width)
})

test('on a phone the list opens on demand and selecting a lesson keeps the desktop preference', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await page.getByRole('button', { name: 'EN', exact: true }).click()
  await enterPython(page)
  const open = page.getByRole('button', { name: 'Mission list', exact: true })
  await expect(open).toBeVisible()
  await expect(page.locator('.mission-list')).toBeHidden()
  await open.click()
  const drawer = page.getByRole('dialog', { name: 'Mission list' })
  const next = drawer.locator('.mission-list button:not([aria-current])').first()
  const title = await next.locator('.mission-name').innerText()
  await next.click()
  await expect(heading(page)).toHaveText(title)
  await expect(drawer).toBeHidden()
  await expect(open).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)

  await page.setViewportSize({ width: 1366, height: 900 })
  await expect(page.locator('.mission-list [aria-current="step"] .mission-name')).toHaveText(title)
  await expect(page.locator('.mission-list [aria-current="step"]')).toBeInViewport()
})
