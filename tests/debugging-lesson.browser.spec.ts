import { expect, test, type Locator } from '@playwright/test'
import type { Catalog } from '../src/shared/types'

const button = (panel: Locator, name: string) => panel.getByRole('button', { name, exact: true })

test('one battery hides the early return, a row exposes it, and moving return fixes a new run', async ({ page, request }) => {
  const response = await request.get('/api/levels')
  expect(response.ok()).toBe(true)
  const { levels, issues } = await response.json() as Catalog
  expect(issues).toEqual([])
  const lesson = levels.find(level => level.id === 'python-debugging-notes')
  if (lesson?.kind !== 'lecture' || !lesson.execution?.debugging) throw new Error('Missing debugging lesson')
  const source = lesson.execution.source.split('\n')
  const { returnLine, loopLine } = lesson.execution.debugging

  await page.goto('/')
  await page.locator('[data-unit="python-advanced"]').click()
  const mission = page.locator('.mission-list').getByRole('button')
    .filter({ has: page.getByText(lesson.title.zh, { exact: true }) })
  await mission.click()
  await expect(page.getByRole('heading', { level: 1, name: lesson.title.zh, exact: true })).toBeVisible()

  const completed = mission.locator('.mission-check')
  const guide = page.getByTestId('debugging-lesson')
  const code = guide.getByTestId('debugging-code')
  const batteries = guide.getByTestId('debug-batteries')
  const expected = guide.getByTestId('debug-expected')
  const actual = guide.getByTestId('debug-actual')
  const returnLocation = guide.getByTestId('debug-return-location')
  const practice = page.getByTestId('debugging-prediction')
  const next = button(guide, '下一步')

  async function atStep(stage: string, line: number) {
    await expect(guide).toHaveAttribute('data-debug-stage', stage)
    const active = code.locator(`[data-line="${line}"][aria-current="step"] code`)
    await expect(active).toHaveText(source[line - 1].trim())
    expect(await active.textContent()).toBe(source[line - 1])
  }

  async function step(stage: string, line: number) {
    await next.click()
    await atStep(stage, line)
  }

  await expect(guide).toHaveAttribute('data-debug-phase', 'single')
  await expect(guide).toHaveAttribute('data-debug-stage', 'start')
  await expect(batteries.locator('[data-battery-index]')).toHaveCount(1)
  await expect(code.locator('code')).toHaveCount(0)
  await expect(practice).toHaveCount(0)
  await button(guide, '试跑一块').click()
  await atStep('define', 1)
  await step('load', 6)
  await step('call', 7)
  await step('initialize', 2)
  await step('take', 3)
  await step('charge', 4)
  await expect(batteries.locator('[data-battery-index="0"]')).toHaveAttribute('data-charge', '5')
  await step('return', 5)
  await step('store', 7)
  await step('output', 8)
  await expect(expected).toHaveText('[5]')
  await expect(actual).toHaveText('[5]')

  await button(guide, '换一排电池').click()
  await expect(guide).toHaveAttribute('data-debug-phase', 'row')
  await expect(guide).toHaveAttribute('data-debug-stage', 'start')
  await expect(batteries.locator('[data-battery-index]')).toHaveCount(3)
  await expect(code.locator('code')).toHaveCount(0)
  await step('define', 1)
  await step('load', 6)
  await step('call', 7)
  await step('initialize', 2)
  await step('take', 3)
  await step('charge', 4)
  await step('return', 5)
  await expect(batteries.locator('[data-charged]')).toHaveCount(1)
  await expect(batteries.locator('[data-skipped] .debug-battery-status')).toHaveText(['未处理', '未处理'])
  await expect(batteries.locator('[data-battery-index="1"]')).toHaveAttribute('data-charge', '4')
  await expect(batteries.locator('[data-battery-index="2"]')).toHaveAttribute('data-charge', '1')
  await step('store', 7)
  await step('output', 8)
  await expect(expected).toHaveText('[5,7,4]')
  await expect(actual).toHaveText('[5]')
  await expect(practice).toHaveCount(0)

  await guide.locator(`[data-debug-line-choice="${loopLine}"]`).click()
  await expect(guide).toHaveAttribute('data-debug-phase', 'row')
  await expect(button(guide, '移到循环外')).toHaveCount(0)
  await guide.locator(`[data-debug-line-choice="${returnLine}"]`).click()
  await expect(guide).toHaveAttribute('data-debug-phase', 'repair')
  await expect(returnLocation).toHaveAttribute('data-location', 'inside')
  const fixedReturn = code.locator(`[data-line="${returnLine}"] code`)
  expect(await fixedReturn.textContent()).toBe(source[returnLine - 1])
  await button(guide, '移到循环外').click()
  await expect(returnLocation).toHaveAttribute('data-location', 'after')
  await expect(returnLocation.locator('.debug-line-place')).toContainText('循环外')
  expect(await fixedReturn.textContent()).toBe('    return results')
  await expect(practice).toHaveCount(0)
  await button(guide, '重新试跑').click()
  await expect(guide.getByTestId('debug-repaired-output')).toHaveText('[5,7,4]')
  await expect(batteries.locator('[data-charged]')).toHaveCount(3)
  await expect(batteries.locator('[data-skipped]')).toHaveCount(0)
  await expect(completed).toHaveCount(0)

  const verify = button(practice, '运行验证')
  const verified = practice.getByTestId('debugging-actual-results')
  await expect(verify).toBeDisabled()
  await practice.locator('[data-debug-case="0"]').click()
  await expect(practice.locator('[data-battery-index="0"][data-charge="0"]').first()).toBeVisible()
  await expect(verify).toBeDisabled()
  await practice.locator('[data-results-option="0"]').click()
  await expect(verified).toHaveCount(0)
  await verify.click()
  await expect(verified).toHaveText('[3,8,5]')
  await expect(practice).toHaveAttribute('data-match', 'false')
  await expect(completed).toHaveCount(0)

  await button(practice, '再猜一次').click()
  await expect(verified).toHaveCount(0)
  await expect(verify).toBeDisabled()
  await practice.locator('[data-results-option="1"]').click()
  await practice.locator('[data-debug-case="1"]').click()
  await expect(verify).toBeDisabled()
  await practice.locator('[data-results-option="1"]').click()
  await verify.click()
  await expect(verified).toHaveText('[7,4]')
  await expect(practice).toHaveAttribute('data-match', 'true')
  await expect(completed).toBeVisible()
})
