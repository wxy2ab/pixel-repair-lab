import { expect, test, type Locator, type Page } from '@playwright/test'
import { ARENA_TURN_MS } from '../src/engine/realtimeProtocol'

test.use({ launchOptions: { args: [
  '--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader',
  // On Windows a GPU-composited SwiftShader canvas can freeze Chromium's entire
  // frame timeline when scrolled back into view. Keep WebGL, composite in software.
  ...(process.platform === 'win32' ? ['--disable-gpu-compositing'] : []),
] } })

async function openCup(page: Page) {
  await page.addInitScript(() => localStorage.setItem('pixel-repair-lab:board-view', '2d'))
  await page.goto('/#challenge-zone')
  await page.locator('[data-challenge-level="challenge-neon-pinball-cup"]').click()
  await expect(page.locator('.arena-combat-goal')).toContainText('对手已停机 0/3')
}

async function bounds(locator: Locator) {
  const box = await locator.boundingBox()
  if (!box) throw new Error('Expected a visible map element')
  return box
}

async function expectMapControls(page: Page) {
  const viewport = page.locator('.station-viewport')
  const controls = viewport.locator('.arena-map-controls')
  const fullscreen = controls.getByRole('button', { name: '全屏地图', exact: true })
  const toggle = controls.getByTestId('arena-console-toggle')
  await fullscreen.click({ trial: true })
  await toggle.click({ trial: true })
  const strip = await bounds(controls)
  const surface = await bounds(viewport.locator('.station-flat-board'))
  expect(strip.y + strip.height).toBeLessThanOrEqual(surface.y + 1)
  expect(surface.y - strip.y - strip.height).toBeLessThan(100)
  for (const button of [fullscreen, toggle]) {
    const box = await bounds(button)
    expect(box.x).toBeGreaterThanOrEqual(surface.x - 1)
    expect(box.x + box.width).toBeLessThanOrEqual(surface.x + surface.width + 1)
  }
  return toggle
}

test('starting a phone duel from the editor uncovers the shot and keeps the editor preference', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.addInitScript(() => localStorage.setItem('pixel-repair-lab:board-view', '2d'))
  await page.goto('/#challenge-browse')
  await page.locator('[data-challenge-level="challenge-brass-bell-lane"]').click()
  const editor = page.locator('#advanced-python')
  const toggle = page.getByTestId('arena-console-toggle')
  const source = 'shoot("right")\nshoot("right")'
  await editor.fill(source)
  const shooter = page.locator('.station-flat-board .tile[data-x="1"][data-y="3"]')
  const covered = () => shooter.evaluate(tile => {
    const rect = tile.getBoundingClientRect()
    const top = document.elementFromPoint(rect.x + rect.width / 2, rect.y + rect.height / 2)
    return !top || Boolean(top.closest('.arena-console'))
  })
  expect(await covered()).toBe(true)
  // The floating Run toolbar and editor shortcut also work when the page is scrolled away from the map.
  await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }))
  await expect(shooter).not.toBeInViewport()
  await page.keyboard.press('Control+Enter')
  await expect(page.getByTestId('arena-turn')).toHaveText('回合 1/12')
  await expect(toggle).toHaveAttribute('aria-expanded', 'false')
  expect(await covered()).toBe(false)
  expect(await page.evaluate(() => localStorage.getItem('pixel-repair-lab:arena-console'))).toBeNull()
  await toggle.click()
  await expect(editor).toBeVisible()
  await expect(editor).toHaveValue(source)
})

