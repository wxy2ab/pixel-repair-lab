import { expect, test, type Locator, type Page } from '@playwright/test'

test.use({ launchOptions: { args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] } })

async function openCup(page: Page) {
  await page.addInitScript(() => localStorage.setItem('pixel-repair-lab:board-view', '2d'))
  await page.goto('/#challenge-zone')
  await page.locator('[data-challenge-level="challenge-neon-pinball-cup"]').click()
  await expect(page.locator('.arena-combat-goal')).toContainText('对手已停机 0/3')
}

async function bounds(locator: Locator) {
  const box = await locator.boundingBox()
  if (!box) throw new Error('Expected a visible map element')
  return box
}

async function expectMapControls(page: Page) {
  const viewport = page.locator('.station-viewport')
  const controls = viewport.locator('.arena-map-controls')
  const fullscreen = controls.getByRole('button', { name: '全屏地图', exact: true })
  const toggle = controls.getByTestId('arena-console-toggle')
  await fullscreen.click({ trial: true })
  await toggle.click({ trial: true })
  const strip = await bounds(controls)
  const surface = await bounds(viewport.locator('.station-flat-board'))
  expect(strip.y + strip.height).toBeLessThanOrEqual(surface.y + 1)
  expect(surface.y - strip.y - strip.height).toBeLessThan(100)
  for (const button of [fullscreen, toggle]) {
    const box = await bounds(button)
    expect(box.x).toBeGreaterThanOrEqual(surface.x - 1)
    expect(box.x + box.width).toBeLessThanOrEqual(surface.x + surface.width + 1)
  }
  return toggle
}

test('map controls sit above the board and the floating console preserves Python combat, replay position and draft', async ({ page }) => {
  await openCup(page)
  const toggle = await expectMapControls(page)
  const workspace = page.getByTestId('arena-map-workspace')
  const viewport = page.locator('.station-viewport')
  expect((await bounds(viewport)).width).toBeGreaterThan((await bounds(workspace)).width * .95)
  const editor = page.getByRole('textbox', { name: '编写 Python', exact: true })
  const source = 'move("right")\npick()\nshoot("right")\nguard()'
  await editor.fill(source)
  const board = page.locator('.tilemap')
  const open = await bounds(board)
  const panel = workspace.locator('.arena-console')
  const popup = await bounds(panel)
  const coveredWidth = Math.min(open.x + open.width, popup.x + popup.width) - Math.max(open.x, popup.x)
  const coveredHeight = Math.min(open.y + open.height, popup.y + popup.height) - Math.max(open.y, popup.y)
  expect(coveredWidth).toBeGreaterThan(0)
  expect(coveredWidth).toBeLessThan(open.width)
  expect(coveredHeight).toBeGreaterThan(0)
  await panel.getByRole('button', { name: '收起程序控制台', exact: true }).click()
  await expect(panel).toBeHidden()
  await expect(toggle).toBeFocused()
  await expect(editor).toBeHidden()
  await expect(toggle).toHaveAttribute('aria-expanded', 'false')
  const closed = await bounds(board)
  expect(closed.width).toBeCloseTo(open.width, 0)
  expect(closed.x).toBeCloseTo(open.x, 0)
  const step = page.getByTestId('play-toolbar').getByRole('button', { name: '单步执行' })
  const turn = page.getByTestId('arena-turn')
  await step.click()
  await expect(turn).toHaveText('回合 1/42')
  await step.click()
  await expect(page.locator('[data-robot-id="player"]')).toContainText('强化 +1')
  await step.click()
  await expect(board.locator('.arena-pulse-line[data-side="player"]').first()).toBeVisible()
  await expect(page.getByTestId('arena-turn-events').locator('[data-actor-id="player"]')).toContainText('向右发射')
  await toggle.click()
  await expect(panel).toBeFocused()
  await expect(editor).toHaveValue(source)
  await expect(toggle).toHaveAttribute('aria-expanded', 'true')
  await expect(turn).toHaveText('回合 3/42')
  await step.click()
  await expect(page.locator('[data-robot-id="player"]')).toContainText('防守中')
})

test('the folded console leaves all combat controls on screen on a phone and restores a paused match', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await openCup(page)
  const toggle = await expectMapControls(page)
  await toggle.click()
  await expect(page.locator('.arena-console')).toBeHidden()
  await toggle.click()
  await page.getByRole('textbox', { name: '编写 Python' }).click({ trial: true })
  await toggle.click()
  await page.getByRole('button', { name: '紧张', exact: true }).click()
  await expect(page.getByTestId('arena-console-toggle')).toHaveAttribute('aria-expanded', 'false')
  const bar = page.getByTestId('play-toolbar')
  await bar.getByRole('button', { name: '开始', exact: true }).click()
  const controls = bar.locator('[data-arena-action]')
  await expect(controls).toHaveCount(11)
  for (const button of await controls.all()) await expect(button).toBeInViewport({ ratio: 1 })
  const turn = page.getByTestId('arena-turn')
  await bar.locator('[data-arena-action="right"]').click()
  await expect(turn).toHaveText('回合 1/42')
  await bar.locator('[data-arena-action="shoot-right"]').click()
  await expect(page.getByTestId('arena-turn-events').locator('[data-actor-id="player"]')).toContainText('向右发射')
  await bar.locator('[data-arena-action="guard"]').click()
  await expect(page.locator('[data-robot-id="player"]')).toContainText('防守中')
  await bar.getByRole('button', { name: '暂停对局' }).click()
  const savedTurn = await turn.textContent()
  await page.reload()
  await expect(turn).toHaveText(savedTurn!)
  await expect(page.getByTestId('arena-console-toggle')).toHaveAttribute('aria-expanded', 'false')
  await expect(bar.getByRole('button', { name: '继续对局' })).toBeEnabled()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
})

test('the 3D combat board stays full width, follows Sprout and shows firing and guarding gestures', async ({ page }) => {
  test.slow()
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await openCup(page)
  await page.getByRole('button', { name: '3D', exact: true }).click()
  const scene = page.locator('.station-viewport')
  await expect(scene).toHaveAttribute('data-ready', 'true', { timeout: 20000 })
  const canvas = page.getByTestId('station-3d-canvas')
  const openWidth = (await bounds(canvas)).width
  expect(openWidth).toBeGreaterThan((await bounds(page.getByTestId('arena-map-workspace'))).width * .95)
  await page.getByRole('button', { name: '跟随芽芽' }).click()
  await page.getByRole('textbox', { name: '编写 Python' }).fill('shoot("right")\nguard()')
  await page.getByTestId('arena-console-toggle').click()
  expect((await bounds(canvas)).width).toBeCloseTo(openWidth, 0)
  await expect(scene).toHaveAttribute('data-camera', 'follow')
  const step = page.getByTestId('play-toolbar').getByRole('button', { name: '单步执行' })
  await step.click()
  await expect(canvas).toHaveAttribute('data-robot-action', 'shoot')
  await step.click()
  await expect(canvas).toHaveAttribute('data-robot-action', 'guard')
  await expect(scene).toHaveAttribute('data-ready', 'true')
})
