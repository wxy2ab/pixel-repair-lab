import { expect, test, type Page } from '@playwright/test'

async function openChallenge(page: Page, id: string) {
  await page.goto('/#challenge-zone')
  await page.locator(`[data-challenge-level="${id}"]`).click()
}

test('a failed data step reviews the discrepancy and preserves the chosen settings', async ({ page }) => {
  await openChallenge(page, 'challenge-temperature-incident-log')
  const review = page.getByRole('region', { name: '失败复盘' })
  const control = (name: string) => page.getByTestId('data-controls').locator(`[data-parameter="${name}"]`)
  const run = page.getByRole('button', { name: '运行实验', exact: true })
  await expect(review).toHaveCount(0)
  await control('trim').check()
  await run.click()
  await review.getByRole('button', { name: '复盘这次' }).click()
  await expect(review.getByText('第 1 步 · 有效传感器日志')).toBeVisible()
  await expect(review.locator('.challenge-review-gaps li')).toHaveText(['结果多出 3 条记录。'])
  await expect(review).not.toContainText('删除缺失和无效温度')
  await review.getByRole('button', { name: /让读数可以计算/ }).click()
  await expect(page.getByRole('heading', { level: 1, name: '让读数可以计算' })).toBeVisible()
  await page.getByRole('button', { name: '返回原挑战' }).click()
  await expect(page.getByRole('heading', { level: 1, name: '高温复查工单' })).toBeVisible()
  await expect(review.getByText('第 1 步 · 有效传感器日志')).toBeVisible()

  await review.getByRole('button', { name: '直接重试' }).click()
  await expect(control('trim')).toBeFocused()
  await expect(control('trim')).toBeChecked()
  await expect(control('dropMissing')).not.toBeChecked()
  await expect(page.getByTestId('data-output').locator('tbody tr')).toHaveCount(14)
  await control('dropMissing').check()
  await control('deduplicate').check()
  await run.click()
  await expect(page.getByTestId('data-feedback')).toHaveText('当前步骤通过。')
  await expect(review).toHaveCount(0)
})

test('an incorrect AI audit reviews the flag counts without identifying the right rows', async ({ page }) => {
  await openChallenge(page, 'challenge-late-dispatch-amendment')
  const review = page.getByRole('region', { name: '失败复盘' })
  const prompt = page.getByRole('textbox', { name: '给 AI 写提示词' })
  const audit = page.getByRole('button', { name: '提交核对' })
  const flag = (id: string) => page.locator(`[data-ai-audit="${id}"]`)
  await prompt.fill('请去掉警示卡。')
  await page.getByRole('button', { name: '发送给 AI' }).click()
  await expect(audit).toBeVisible()
  await expect(review).toHaveCount(0)
  await flag('tag').check()
  await audit.click()
  await review.getByRole('button', { name: '复盘这次' }).click()
  await expect(review.getByText('第 1 轮 · 清单核对')).toBeVisible()
  await expect(review.locator('.challenge-review-gaps li')).toHaveText(['还有 5 行差异没有标记。', '有 1 行数量正确，却被标记了。'])

  await review.getByRole('button', { name: '直接重试' }).click()
  await expect(flag('battery')).toBeFocused()
  await expect(flag('tag')).toBeChecked()
  await expect(prompt).toHaveValue('请去掉警示卡。')
  await flag('tag').uncheck()
  for (const id of ['battery', 'fuse', 'seal', 'strap', 'tester']) await flag(id).check()
  await audit.click()
  await review.getByRole('button', { name: '复盘这次' }).click()
  await expect(review.getByText('第 1 轮 · 装箱清单')).toBeVisible()
  await expect(review.locator('.challenge-review-gaps li')).toHaveText([
    '有 3 种物品还没装够。', '有 1 种物品装多了。', '有 1 种应留在货架上的物品还在箱里。',
  ])
  await review.getByRole('button', { name: '直接重试' }).click()
  await expect(prompt).toBeFocused()
  await expect(prompt).toHaveValue('请去掉警示卡。')
})
