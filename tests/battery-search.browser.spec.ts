import { expect, test, type Locator } from '@playwright/test'
import type { Catalog } from '../src/shared/types'

const button = (panel: Locator, name: string) => panel.getByRole('button', { name, exact: true })
const battery = (panel: Locator, name: string) => panel.getByTestId('battery-search-row').locator(`[data-battery-name="${name}"]`)

async function finish(panel: Locator) {
  const next = button(panel, '下一步')
  for (let i = 0; i < 22 && await next.isEnabled(); i++) await next.click()
  await expect(next).toBeDisabled()
  await expect(panel.getByTestId('battery-search-step')).toHaveAttribute('data-kind', 'return')
}

test('the algorithm opener reveals batteries, compares both searches step by step, and checks fresh predictions', async ({ page, request }) => {
  const response = await request.get('/api/levels')
  expect(response.ok()).toBe(true)
  const { levels, issues } = await response.json() as Catalog
  expect(issues).toEqual([])
  const level = levels.find(item => item.id === 'linear-search-notes')
  if (level?.kind !== 'lecture' || !level.execution?.batterySearch) throw new Error('Missing the battery search opener')

  await page.goto('/#track-algorithms')
  await page.locator('[data-unit="algorithm-intro"]').click()
  await expect(page.getByRole('heading', { level: 1, name: level.title.zh, exact: true })).toBeVisible()

  const mission = page.locator('.mission-list').getByRole('button').filter({ has: page.getByText(level.title.zh, { exact: true }) })
  const completion = mission.locator('.mission-check')
  const guide = page.getByTestId('battery-search-lesson')
  const linear = guide.getByTestId('battery-search-linear')
  const binary = guide.getByTestId('battery-search-binary')
  const prediction = page.getByTestId('battery-search-prediction')
  const wrong = guide.getByTestId('battery-search-manual-card-F')
  const right = guide.getByTestId('battery-search-manual-card-E')

  await expect(wrong).not.toHaveAttribute('data-charge', /./)
  await expect(right).not.toHaveAttribute('data-charge', /./)
  await expect(binary).toHaveCount(0)
  await wrong.click()
  await expect(wrong).toHaveAttribute('data-charge', '12')
  await expect(linear).toHaveCount(0)
  await right.click()
  await expect(right).toHaveAttribute('data-charge', '10')
  await expect(linear).toBeVisible()
  await expect(binary).toBeVisible()
  await expect(prediction).toHaveCount(0)
  await expect(binary.getByTestId('battery-search-code')).toHaveCount(0)

  for (const panel of [linear, binary]) {
    const names = await panel.getByTestId('battery-search-row').locator('[data-battery-name]')
      .evaluateAll(items => items.map(item => item.getAttribute('data-battery-name')))
    expect(names).toEqual(['A', 'B', 'C', 'D', 'E', 'F', 'G'])
  }

  const next = button(binary, '下一步')
  const step = binary.getByTestId('battery-search-step')
  const code = binary.getByTestId('battery-search-code')
  const count = binary.getByTestId('battery-search-compare-count')
  await next.click()
  await expect(step).toHaveAttribute('data-kind', 'select')
  await expect(battery(binary, 'D')).toHaveAttribute('data-state', 'checking')
  await expect(code).toContainText('middle = (first + last) // 2')
  await next.click()
  await expect(step).toHaveAttribute('data-kind', 'compare')
  await expect(code).toContainText('matches = charge == target')
  await expect(binary.getByTestId('battery-search-relation')).toHaveText('8 < 10')
  await expect(count).toHaveText('1')
  await next.click()
  await expect(step).toHaveAttribute('data-kind', 'narrow')
  await expect(step).toHaveAttribute('data-first', '4')
  await expect(code).toContainText('first = middle + 1')
  await expect(battery(binary, 'A')).toHaveAttribute('data-state', 'excluded')
  await expect(battery(binary, 'E')).toHaveAttribute('data-state', 'candidate')

  await next.click()
  await expect(battery(binary, 'F')).toHaveAttribute('data-state', 'checking')
  await next.click()
  await next.click()
  await expect(code).toContainText('last = middle - 1')
  await expect(step).toHaveAttribute('data-last', '4')
  await expect(binary.getByTestId('battery-search-relation')).toHaveText('12 > 10')
  await expect(battery(binary, 'G')).toHaveAttribute('data-state', 'excluded')
  await expect(battery(binary, 'E')).toHaveAttribute('data-state', 'candidate')
  await button(binary, '上一步').click()
  await expect(step).toHaveAttribute('data-kind', 'compare')
  await expect(battery(binary, 'G')).toHaveAttribute('data-state', 'candidate')
  await finish(binary)
  await expect(count).toHaveText('3')
  await expect(battery(binary, 'E')).toHaveAttribute('data-state', 'found')
  await expect(prediction).toHaveCount(0)

  await button(linear, '下一步').click()
  await expect(battery(linear, 'A')).toHaveAttribute('data-state', 'checking')
  await expect(linear.getByTestId('battery-search-code')).toContainText('for index in range(len(charges))')
  await finish(linear)
  await expect(linear.getByTestId('battery-search-compare-count')).toHaveText('5')
  await expect(battery(linear, 'E')).toHaveAttribute('data-state', 'found')
  await expect(prediction).toBeVisible()

  const verify = button(prediction, '运行验证')
  await expect(verify).toBeDisabled()
  await prediction.locator('[data-battery-name="P"]').click()
  await prediction.locator('[data-linear-option="6"]').click()
  await expect(verify).toBeDisabled()
  await prediction.locator('[data-binary-option="3"]').click()
  await expect(prediction.getByTestId('battery-search-actual-battery')).toHaveCount(0)
  await verify.click()
  await expect(prediction).toHaveAttribute('data-match', 'false')
  await expect(prediction.locator('[data-search-field="linear"]')).toHaveAttribute('data-match', 'false')
  await expect(prediction.getByTestId('battery-search-actual-battery')).toHaveText('P')
  await expect(prediction.getByTestId('battery-search-actual-linear')).toHaveText('7')
  await expect(prediction.getByTestId('battery-search-actual-binary')).toHaveText('3')
  await expect(prediction.getByTestId('battery-search-path-binary')).toHaveText('L → N → P')
  await expect(completion).toHaveCount(0)

  await prediction.locator('[data-linear-option="7"]').click()
  await verify.click()
  await expect(prediction).toHaveAttribute('data-match', 'true')
  await expect(completion).toBeVisible()
})
