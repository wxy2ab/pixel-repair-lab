import { expect, test, type Page } from '@playwright/test'
import { cardsToPython } from '../src/shared/cards'
import type { Catalog } from '../src/shared/types'

test.use({ launchOptions: { args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] } })

const button = (page: Page, name: string) => page.getByRole('button', { name, exact: true })

test('the detour preview switches the inspected wall in the 3D scene and in the flat map', async ({ page, request }) => {
  test.slow()
  const { levels } = await (await request.get('/api/levels')).json() as Catalog
  const level = levels.find(item => item.id === 'challenge-six-step-detour')
  if (level?.kind !== 'grid') throw new Error('Missing detour map')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  await button(page, '关卡预览').click()
  await page.getByLabel('关卡 JSON 文件').setInputFiles({ name: 'detour.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(level)) })
  const picker = page.getByTestId('map-scenario-picker')
  await expect(picker.getByRole('button')).toHaveCount(2)
  await expect(page.locator('.station-viewport')).toHaveAttribute('data-ready', 'true', { timeout: 20000 })
  const canvas = page.getByTestId('station-3d-canvas')
  await canvas.press('ArrowLeft')
  const target = page.getByTestId('station-cell-inspection')
  await expect(target).toHaveText('(2, 3) 墙')
  await picker.getByRole('button', { name: '地图 2' }).click()
  await expect(target).toHaveText('(2, 3) 地板')
  await button(page, '2D').click()
  const left = page.locator('.tile[data-x="2"][data-y="3"]')
  const right = page.locator('.tile[data-x="4"][data-y="3"]')
  await expect(left).toHaveClass(/tile--floor/)
  await expect(right).toHaveClass(/tile--wall/)
  await picker.getByRole('button', { name: '地图 1' }).click()
  await expect(left).toHaveClass(/tile--wall/)
  await expect(right).toHaveClass(/tile--floor/)
})

test('the 3D arena camera and picking preserve the playable replay state', async ({ page, request }) => {
  test.slow()
  const { levels } = await (await request.get('/api/levels')).json() as Catalog
  const arena = levels.find(level => level.id === 'challenge-freight-carousel')
  if (arena?.kind !== 'arena') throw new Error('Missing arena fixture')

  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/#challenge-zone')
  await page.locator(`[data-challenge-level="${arena.id}"]`).click()
  const canvas = page.getByTestId('station-3d-canvas')
  const turn = page.getByTestId('arena-turn')
  const tiles = page.locator('.tilemap')
  await expect(button(page, '3D')).toHaveAttribute('aria-pressed', 'true')
  await expect(canvas).toBeVisible()
  await expect(page.locator('.station-viewport')).toHaveAttribute('data-ready', 'true', { timeout: 20000 })
  await expect.poll(() => canvas.evaluate((element: HTMLCanvasElement) => {
    const gl = element.getContext('webgl2')
    return Boolean(gl && !gl.isContextLost() && gl.drawingBufferWidth > 0)
  })).toBe(true)
  await expect(turn).toHaveText(`回合 0/${arena.maxTurns}`)
  const initialBoard = await tiles.innerHTML()
  await canvas.click()
  const inspection = page.getByTestId('station-cell-inspection')
  await expect(inspection).toBeVisible()
  const picked = await inspection.textContent()
  await canvas.press('ArrowRight')
  await expect(inspection).not.toHaveText(picked ?? '')
  const beforeZoom = await canvas.screenshot()
  await button(page, '拉近').click()
  await expect.poll(async () => !(await canvas.screenshot()).equals(beforeZoom)).toBe(true)
  await button(page, '拉远').click()
  await canvas.scrollIntoViewIfNeeded()
  const beforeOrbit = await canvas.screenshot()
  const bounds = await canvas.boundingBox()
  if (!bounds) throw new Error('Missing camera surface')
  const x = bounds.x + bounds.width / 2
  const y = bounds.y + bounds.height / 2
  await page.mouse.move(x, y)
  await page.mouse.down()
  await page.mouse.move(x + 48, y + 10, { steps: 4 })
  await page.mouse.up()
  await expect.poll(async () => !(await canvas.screenshot()).equals(beforeOrbit)).toBe(true)
  await button(page, '复位镜头').focus()
  await button(page, '复位镜头').press('Enter')
  await expect(turn).toHaveText(`回合 0/${arena.maxTurns}`)
  expect(await tiles.innerHTML()).toBe(initialBoard)
  const initialScene = await canvas.screenshot()

  await page.getByRole('textbox', { name: '编写 Python', exact: true }).fill(arena.solutionCode)
  await button(page, '运行').click()
  const replay = page.getByRole('slider', { name: '回放进度', exact: true })
  await replay.fill('4')
  await expect(turn).toHaveText(`回合 4/${arena.maxTurns}`)
  const savedFrame = await tiles.innerHTML()
  expect(savedFrame).not.toBe(initialBoard)
  await expect.poll(async () => !(await canvas.screenshot()).equals(initialScene)).toBe(true)
  await button(page, '跟随芽芽').click()
  for (const frame of ['4', '7', '4']) {
    await replay.fill(frame)
    await expect(turn).toHaveText(`回合 ${frame}/${arena.maxTurns}`)
    const playerTile = tiles.locator('.tile:has(> .pixel-bot:not(.pixel-bot--enemy))')
    const x = await playerTile.getAttribute('data-x'), y = await playerTile.getAttribute('data-y')
    await canvas.click()
    await expect(inspection).toContainText(`(${x}, ${y}) 芽芽`)
  }
  await button(page, '现场全景').click()
  expect(await tiles.innerHTML()).toBe(savedFrame)
  await button(page, '2D').click()
  await expect(button(page, '2D')).toHaveAttribute('aria-pressed', 'true')
  await expect(canvas).toBeHidden()
  expect(await tiles.innerHTML()).toBe(savedFrame)
  await button(page, '3D').click()
  await expect(canvas).toBeVisible()
  await expect(replay).toHaveValue('4')
  expect(await tiles.innerHTML()).toBe(savedFrame)
  await expect(page.locator('.station-viewport')).toHaveAttribute('data-ready', 'true')
  await canvas.evaluate((element: HTMLCanvasElement) => {
    const extension = element.getContext('webgl2')?.getExtension('WEBGL_lose_context')
    if (!extension) throw new Error('The test browser requires the WebGL context-loss extension')
    extension.loseContext()
  })
  await expect(button(page, '2D')).toHaveAttribute('aria-pressed', 'true')
  await expect(replay).toHaveValue('4')
  expect(await tiles.innerHTML()).toBe(savedFrame)
})

test('a grid lesson still runs the learner program when WebGL is unavailable', async ({ page, request }) => {
  const { levels } = await (await request.get('/api/levels')).json() as Catalog
  const lesson = levels.find(level => level.id === 'first-steps')
  if (lesson?.kind !== 'grid') throw new Error('Missing grid lesson fixture')
  await page.addInitScript(() => {
    const getContext = HTMLCanvasElement.prototype.getContext
    Object.defineProperty(HTMLCanvasElement.prototype, 'getContext', {
      value: function (this: HTMLCanvasElement, type: string, ...args: unknown[]) {
        return /webgl/.test(type) ? null : Reflect.apply(getContext, this, [type, ...args])
      },
    })
  })
  await page.goto('/')
  await page.locator(`[data-unit="${lesson.unit?.id}"]`).click()
  await page.locator('.mission-list').getByRole('button').filter({ hasText: lesson.title.zh }).click()
  await expect(button(page, '2D')).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('.tilemap')).toBeVisible()
  await expect(page.locator('.tilemap > .tile')).toHaveCount(lesson.tiles.length * lesson.tiles[0].length)
  await page.getByRole('tab', { name: 'Python', exact: true }).click()
  await page.getByRole('textbox', { name: '编写 Python', exact: true }).fill(cardsToPython(lesson.cards, lesson.solutionCards))
  await button(page, '运行').click()
  await expect(page.locator('.output-panel .win-message')).toContainText('任务完成', { timeout: 10000 })
})
