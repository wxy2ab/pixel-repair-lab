import { expect, test, type Locator, type Page } from '@playwright/test'

test.use({ launchOptions: { args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] } })

async function openModel(page: Page, unit: string, lesson: string, scene: string) {
  await page.goto('/')
  await page.locator(`[data-unit="${unit}"]`).click()
  await page.locator('.mission-list button').filter({ has: page.getByText(lesson, { exact: true }) }).click()
  const model = page.locator(`[data-teaching-model="${scene}"]`)
  await model.scrollIntoViewIfNeeded()
  await expect(model).toHaveAttribute('data-renderer', 'webgl')
  return model
}

async function touchLabel(model: Locator, name: string) {
  const canvas = model.locator('canvas')
  const tag = model.locator('.teaching-model-labels').getByText(name, { exact: true })
  await expect(tag).toBeVisible()
  const [surface, rect] = await Promise.all([canvas.boundingBox(), tag.boundingBox()])
  if (!surface || !rect) throw new Error('A visible model and label are required')
  await canvas.click({ position: { x: rect.x + rect.width / 2 - surface.x, y: rect.y + rect.height / 2 - surface.y } })
}

test('touching address cups stores, reads and copies one card, keeping zero separate from an empty cup', async ({ page }) => {
  const model = await openModel(page, 'foundations', '什么是变量？', 'python-address-cups')
  const shelf = page.getByTestId('variable-cups')
  await model.getByRole('button', { name: '俯视' }).click()
  await touchLabel(model, '@22')
  await expect(shelf.locator('[data-cup-address="22"]')).toHaveAttribute('data-name', 'charge')
  await touchLabel(model, '@22')
  await shelf.locator('[data-kind="value"]').click()
  await touchLabel(model, '@20')
  await touchLabel(model, '@22')
  const labels = model.locator('.teaching-model-labels')
  await expect(labels.getByText('0', { exact: true })).toHaveCount(1)
  await expect(labels.getByText('3', { exact: true })).toHaveCount(1)
  await expect(shelf.locator('[data-cup-address="21"]')).toHaveAttribute('data-value', '')
})

test('the 3D call stack separates both charge variables and hands a return back before assignment', async ({ page }) => {
  const model = await openModel(page, 'foundations', '函数与参数', 'python-call-stack')
  const guide = page.getByTestId('guided-program')
  const labels = model.locator('.teaching-model-labels')
  // The model battery sends its actual value to the same lesson as the read button.
  await touchLabel(model, '6')
  await expect(guide).toHaveAttribute('data-trace-kind', 'assign')
  const next = guide.getByRole('button', { name: '下一步', exact: true })
  await next.click()
  await expect(labels.getByText('charge', { exact: true })).toHaveCount(2)
  await next.click()
  await expect(labels.getByText('9', { exact: true })).toHaveCount(1)
  await expect(guide.locator('[data-scope-role="main"] [data-binding="charge"] dd')).toHaveText('6')
  await next.click()
  await expect(labels.getByText('return 9', { exact: true })).toBeVisible()
  await expect(labels.getByText('result', { exact: true })).toHaveCount(0)
  await next.click()
  await expect(labels.getByText('result', { exact: true })).toBeVisible()
  await guide.getByRole('button', { name: '上一步' }).click()
  await expect(labels.getByText('result', { exact: true })).toHaveCount(0)
  for (let i = 0; i < 3; i++) await next.click()
  const practice = page.getByTestId('function-prediction')
  await practice.locator('[data-charge-input="0"]').click()
  const checked = practice.locator('[data-teaching-model="python-verified-values"]')
  await checked.scrollIntoViewIfNeeded()
  await expect(checked).toHaveAttribute('data-renderer', 'webgl')
  const readings = checked.locator('.teaching-model-labels')
  await expect(readings.getByText('3', { exact: true })).toHaveCount(0)
  await practice.locator('[data-prediction-field="return"] [data-prediction="3"]').click()
  await practice.locator('[data-prediction-field="caller"] [data-prediction="0"]').click()
  await practice.getByRole('button', { name: '运行验证' }).click()
  await expect(readings.getByText('3', { exact: true })).toBeVisible()
  await expect(readings.getByText('0', { exact: true })).toHaveCount(2)
})

test('the two physical file sockets distinguish importing a name from sending input and returning its value', async ({ page }) => {
  const model = await openModel(page, 'python-advanced', '模块', 'python-module-link')
  const labels = model.locator('.teaching-model-labels')
  const next = page.getByTestId('module-lesson').getByRole('button', { name: '下一步', exact: true })
  await next.click()
  await next.click()
  await expect(labels.getByText('← import', { exact: true })).toBeVisible()
  await expect(labels.getByText('amount = 2', { exact: true })).toHaveCount(0)
  await next.click()
  await next.click()
  await expect(labels.getByText('amount = 2', { exact: true })).toBeVisible()
  await next.click()
  await next.click()
  await expect(labels.getByText('return 5', { exact: true })).toBeVisible()
  await expect(labels.getByText('result = 5', { exact: true })).toHaveCount(0)
})
