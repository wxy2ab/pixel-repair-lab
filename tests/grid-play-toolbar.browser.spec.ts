import { expect, test, type Page } from '@playwright/test'
import { cardsToPython } from '../src/shared/cards'
import type { Catalog } from '../src/shared/types'
import { challengeScoresKey } from '../src/web/challengeScore'

const button = (page: Page, name: string) => page.getByRole('button', { name, exact: true })

async function openDetour(page: Page) {
  await page.addInitScript(() => localStorage.setItem('pixel-repair-lab:board-view', '2d'))
  await page.goto('/#challenge-zone')
  await page.getByRole('region', { name: '自由选关', exact: true }).locator('[data-challenge-level="challenge-six-step-detour"]').click()
}

test('cards step once per click from a fixed mobile toolbar, and a stopped move keeps the last real trail', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 700 })
  await openDetour(page)
  for (let i = 0; i < 3; i++) await page.locator('[data-add-card="right"]').click()
  const bar = page.getByRole('toolbar', { name: '运行工具条' })
  const step = bar.getByRole('button', { name: '单步执行' })
  const reading = bar.getByTestId('grid-step-reading')
  const position = () => step.evaluate(node => {
    const { x, y } = node.getBoundingClientRect()
    return [Math.round(x), Math.round(y)]
  })
  const original = await position()
  await page.evaluate(() => window.scrollTo(0, 0))
  expect(await position()).toEqual(original)
  await page.evaluate(() => window.scrollTo(0, document.documentElement.scrollHeight))
  expect(await position()).toEqual(original)
  await step.click()
  await expect(reading).toHaveAttribute('data-line', '1')
  await expect(reading).toContainText('move("right")')
  await expect(page.locator('.tile[data-x="4"][data-y="3"] [data-trail="recent"]')).toHaveCount(1)
  await expect(page.locator('[data-trail="history"]')).toHaveCount(0)
  await page.waitForTimeout(900)
  await expect(page.getByTestId('grid-turn-budget')).toContainText('1 / 6')
  expect(await position()).toEqual(original)
  await step.click()
  await expect(reading).toHaveAttribute('data-line', '2')
  await expect(page.locator('.tile[data-x="3"][data-y="3"] [data-trail="history"]')).toHaveCount(1)
  expect(await position()).toEqual(original)
  const toggle = bar.getByRole('button', { name: '显示路线' })
  await toggle.click()
  await expect(page.locator('[data-trail]')).toHaveCount(0)
  await toggle.click()
  await expect(page.locator('[data-trail="recent"]')).toHaveCount(2)
  await step.click()
  await expect(reading).toHaveAttribute('data-line', '3')
  await expect(page.locator('.output-panel .error-message')).toContainText('第 3 行')
  await expect(page.getByTestId('grid-turn-budget')).toContainText('2 / 6')
  await expect(page.locator('[data-trail="recent"]')).toHaveCount(2)
  expect(await position()).toEqual(original)
  await toggle.click()
  await page.reload()
  // Reopen from free choice when no arena checkpoint restores the level.
  if (!await bar.isVisible()) {
    await page.getByRole('region', { name: '自由选关', exact: true }).locator('[data-challenge-level="challenge-six-step-detour"]').click()
  }
  await expect(bar.getByRole('button', { name: '显示路线' })).toHaveAttribute('aria-pressed', 'false')
})

test('single stepping checks the chosen variant and a Python error after the last movement gets a separate step', async ({ page }) => {
  await page.addInitScript(() => {
    localStorage.setItem('pixel-repair-lab:algorithms', JSON.stringify({
      first_item: 'def first_item(entries):\n    return entries[0]',
    }))
    const save = Storage.prototype.setItem
    Storage.prototype.setItem = function (key, value) {
      if (key === 'pixel-repair-lab:show-trail') throw new DOMException('Storage is full', 'QuotaExceededError')
      save.call(this, key, value)
    }
  })
  await openDetour(page)
  await page.getByTestId('map-scenario-1').click()
  await page.getByRole('tab', { name: 'Python' }).click()
  const editor = page.getByRole('textbox', { name: '编写 Python' })
  await editor.fill('move("left")\nmove("left")\nmove("up")\nmissing_function()')
  const step = button(page, '单步执行')
  const reading = page.getByTestId('grid-step-reading')
  await step.click()
  await expect(reading).toHaveAttribute('data-line', '1')
  await expect(page.locator('.tilemap')).toHaveAccessibleName('机器人位于 2，3')
  const listing = page.getByTestId('execution-source')
  await expect(listing.locator('[data-current]')).toHaveAttribute('data-line', '1')
  await expect(listing.locator('[data-next]')).toHaveAttribute('data-line', '2')
  await button(page, '显示路线').click()
  await expect(page.locator('[data-trail]')).toHaveCount(0)
  await button(page, '显示路线').click()
  await expect(page.locator('[data-trail="recent"]')).toHaveCount(2)
  await step.click()
  await expect(reading).toHaveAttribute('data-line', '2')
  await step.click()
  await expect(reading).toHaveAttribute('data-line', '3')
  await expect(page.locator('.tilemap')).toHaveAccessibleName('机器人位于 1，2')
  await expect(listing.locator('[data-next] code')).toHaveText('missing_function()')
  await expect(page.locator('.output-panel .error-message')).toHaveCount(0)
  await step.click()
  await expect(reading).toHaveAttribute('data-line', '4')
  await expect(reading).toContainText('missing_function()')
  await expect(listing.locator('[data-current]')).toHaveAttribute('data-line', '4')
  await expect(listing.locator('[data-next]')).toHaveCount(0)
  await editor.fill('move("left")\nmove("left")\nmove("up")')
  await expect(listing).toHaveCount(0)
  await expect(page.locator('[data-trail]')).toHaveCount(0)
  await step.click()
  await expect(reading).toHaveAttribute('data-line', '1')
  await page.getByTestId('map-scenario-0').click()
  await expect(reading).toHaveCount(0)
  await expect(page.getByTestId('grid-turn-budget')).toContainText('0 / 6')
  await editor.fill('from my_algorithms import first_item\nvalues = []\nchoice = first_item(values)')
  await step.click()
  await expect(page.locator('.station-action-cue[data-action="call"]')).toContainText('first_item')
  await step.click()
  await expect(reading).toHaveAttribute('data-line', '2')
  await expect(reading).toContainText('my_algorithms.first_item.py')
  await expect(reading.locator('code')).toHaveText('return entries[0]')
  await editor.fill('from my_algorithms import first_item\nmove("right")\nchoice = first_item([])')
  await step.click()
  await expect(listing.locator('[data-source-name="main.py"] [data-current] code')).toHaveText('move("right")')
  await expect(listing.locator('[data-next] code')).toHaveText('choice = first_item([])')
  await step.click()
  await expect(listing.locator('[data-source-name="my_algorithms.first_item.py"] [data-next] code')).toHaveText('return entries[0]')
  await step.click()
  await expect(listing.locator('[data-source-name="main.py"]')).toHaveCount(0)
  await expect(listing.locator('[data-current] code')).toHaveText('return entries[0]')
  await expect(listing.locator('[data-next]')).toHaveCount(0)
})

test('a single-step attempt can pause and resume autoplay and awards its win once at the end', async ({ page, request }) => {
  await openDetour(page)
  const { levels } = await (await request.get('/api/levels')).json() as Catalog
  const detour = levels.find(level => level.id === 'challenge-six-step-detour')
  if (detour?.kind !== 'grid') throw new Error('Missing detour challenge')
  await page.getByRole('tab', { name: 'Python' }).click()
  await page.getByRole('textbox', { name: '编写 Python' }).fill(cardsToPython(detour.cards, detour.solutionCards))
  const step = button(page, '单步执行')
  const reading = page.getByTestId('grid-step-reading')
  const summary = page.getByRole('region', { name: '通关总结', exact: true })
  const countWins = () => page.evaluate(([key, id]) => {
    const records = JSON.parse(localStorage.getItem(key) || '{}')[id] || {}
    return Object.values<{ attempts: unknown[] }>(records).reduce((total, entry) => total + entry.attempts.length, 0)
  }, [challengeScoresKey, detour.id])
  await step.click()
  await expect(reading).toContainText('nearby = scan()')
  await expect(summary).toHaveCount(0)
  expect(await countWins()).toBe(0)
  await button(page, '继续运行').click()
  await button(page, '暂停').click()
  const pausedAt = await reading.getAttribute('data-line')
  await page.waitForTimeout(850)
  await expect(reading).toHaveAttribute('data-line', pausedAt!)
  expect(await countWins()).toBe(0)
  await button(page, '继续运行').click()
  await expect(summary).toBeVisible()
  expect(await countWins()).toBe(1)
  await page.getByTestId('map-scenario-1').click()
  await button(page, '显示路线').click()
  expect(await countWins()).toBe(1)
})
