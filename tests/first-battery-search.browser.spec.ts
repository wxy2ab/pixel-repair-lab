import { expect, test, type Locator } from '@playwright/test'
import type { Catalog } from '../src/shared/types'

const button = (panel: Locator, name: string) => panel.getByRole('button', { name, exact: true })

test('the intermediate opener saves a match, searches farther left, and checks the bounds and final index on a new row', async ({ page, request }) => {
  const response = await request.get('/api/levels')
  expect(response.ok()).toBe(true)
  const { levels, issues } = await response.json() as Catalog
  expect(issues).toEqual([])
  const lesson = levels.find(level => level.id === 'binary-search-notes')
  if (lesson?.kind !== 'lecture' || !lesson.execution?.firstBatterySearch) throw new Error('Missing the intermediate search opener')

  await page.goto('/#track-algorithms')
  await page.locator('[data-unit="routing"]').click()
  await expect(page.getByRole('heading', { level: 1, name: lesson.title.zh, exact: true })).toBeVisible()
  const mission = page.locator('.mission-list').getByRole('button').filter({ has: page.getByText(lesson.title.zh, { exact: true }) })
  const guide = page.getByTestId('first-battery-search-lesson')
  const step = guide.getByTestId('first-battery-search-step')
  const card = (name: string) => guide.getByTestId('first-battery-' + name)
  const code = guide.getByTestId('first-battery-search-code')
  const prediction = page.getByTestId('first-battery-search-prediction')
  const compare = button(guide, '比较电量')
  const narrow = button(guide, '缩小范围')
  const remember = button(guide, '记下这个位置')
  const finish = button(guide, '查看结果')
  const add = button(guide, '加入相同电量的电池')

  await expect(step).toHaveAttribute('data-kind', 'start')
  await expect(code).toHaveCount(0)
  await expect(prediction).toHaveCount(0)
  await expect(card('H')).toHaveCount(0)
  await card('A').click()
  await expect(guide.getByTestId('first-battery-search-hint')).toBeVisible()
  await expect(step).toHaveAttribute('data-kind', 'start')
  await card('D').click()
  await expect(step).toHaveAttribute('data-index', '3')
  await expect(code).toContainText('middle = (first + last) // 2')
  await compare.click()
  await expect(code).toContainText('matches = charge == target')
  await narrow.click()
  await expect(step).toHaveAttribute('data-first', '4')
  await expect(step).toHaveAttribute('data-last', '6')
  await card('F').click()
  await compare.click()
  await finish.click()
  await expect(code).toContainText('return [middle, comparisons]')
  await expect(guide.getByTestId('first-battery-search-result')).toContainText(/F.*5/u)
  await expect(prediction).toHaveCount(0)

  await add.click()
  await expect(step).toHaveAttribute('data-kind', 'start')
  await expect(step).toHaveAttribute('data-last', '8')
  await expect(card('H')).toBeVisible()
  await expect(card('I')).toBeVisible()
  await card('E').click()
  await compare.click()
  await narrow.click()
  await expect(step).toHaveAttribute('data-first', '5')
  await card('F').click()
  await compare.click()
  await expect(step).toHaveAttribute('data-index', '6')
  await remember.click()
  await expect(step).toHaveAttribute('data-kind', 'remember')
  await expect(step).toHaveAttribute('data-saved', '6')
  await expect(code).toContainText('found = middle')
  await narrow.click()
  await expect(step).toHaveAttribute('data-first', '5')
  await expect(step).toHaveAttribute('data-last', '5')
  await expect(step).toHaveAttribute('data-saved', '6')
  await expect(card('F')).toHaveAttribute('data-state', 'saved')
  await expect(code).toContainText('last = middle - 1')
  await button(guide, '上一步').click()
  await expect(step).toHaveAttribute('data-kind', 'remember')
  await expect(step).toHaveAttribute('data-last', '8')
  await narrow.click()
  await card('H').click()
  await compare.click()
  await remember.click()
  await expect(step).toHaveAttribute('data-saved', '5')
  await narrow.click()
  await expect(step).toHaveAttribute('data-first', '5')
  await expect(step).toHaveAttribute('data-last', '4')
  await expect(guide.getByTestId('first-battery-search-range')).toContainText('空')
  await expect(prediction).toHaveCount(0)
  await finish.click()
  await expect(code).toContainText('return found')
  await expect(guide.getByTestId('first-battery-search-result')).toContainText(/H.*5/u)

  const verify = button(prediction, '运行验证')
  await expect(verify).toBeDisabled()
  await prediction.locator('[data-range-option="1"]').click()
  await expect(verify).toBeDisabled()
  await prediction.locator('[data-index-option="4"]').click()
  const actualRanges = prediction.getByTestId('first-battery-search-actual-ranges')
  await expect(actualRanges).toHaveCount(0)
  await verify.click()
  await expect(prediction).toHaveAttribute('data-match', 'false')
  await expect(prediction.locator('[data-prediction="ranges"]')).toHaveAttribute('data-match', 'true')
  await expect(prediction.locator('[data-prediction="index"]')).toHaveAttribute('data-match', 'false')
  await expect(prediction.getByTestId('first-battery-search-actual-index')).toHaveText('3')
  await expect(actualRanges.locator('li')).toHaveCount(3)
  await expect(actualRanges.locator('li').last()).toHaveAttribute('data-first', '3')
  await expect(actualRanges.locator('li').last()).toHaveAttribute('data-last', '2')
  await expect(mission.locator('.mission-check')).toHaveCount(0)
  await button(prediction, '再猜一次').click()
  await prediction.locator('[data-index-option="3"]').click()
  await verify.click()
  await expect(prediction).toHaveAttribute('data-match', 'true')
  await expect(mission.locator('.mission-check')).toBeVisible()
})
