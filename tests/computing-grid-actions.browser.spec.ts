import { expect, test, type Page } from '@playwright/test'

test.use({ launchOptions: { args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] } })

async function openGrid(page: Page, unit: string, title: string, code: string) {
  await page.goto('/')
  await page.locator(`[data-unit="${unit}"]`).click()
  await page.locator('.mission-list button').filter({ has: page.getByText(title, { exact: true }) }).click()
  await page.getByRole('tab', { name: 'Python' }).click()
  await page.getByRole('textbox', { name: '编写 Python' }).fill(code)
  return page.getByTestId('grid-single-step')
}

test('two scans and a submission trigger real player animation on the same square; rewinding restores the previous output', async ({ page }) => {
  const step = await openGrid(page, 'computer', '把灯读成数字', 'scan()\nscan()\nsubmit(5)')
  const canvas = page.getByTestId('station-3d-canvas')
  await canvas.scrollIntoViewIfNeeded()
  await expect(page.locator('.station-viewport')).toHaveAttribute('data-ready', 'true')
  await step.click()
  await expect(canvas).toHaveAttribute('data-robot-action', 'scan')
  await expect(canvas).toHaveAttribute('data-robot-motion', 'done')
  await step.click()
  await expect(canvas).toHaveAttribute('data-robot-motion', 'playing')
  await expect(page.getByTestId('grid-step-reading')).toHaveAttribute('data-line', '2')
  await step.click()
  await expect(canvas).toHaveAttribute('data-robot-action', 'submit')
  await expect(page.locator('.station-action-cue')).toContainText('5')
  const bench = page.getByTestId('grid-hardware-bench')
  await expect(bench).toContainText('程序提交 5')
  await page.getByRole('button', { name: '回看上一步' }).click()
  await expect(canvas).toHaveAttribute('data-robot-action', 'scan')
  await expect(bench).toContainText('程序提交 —')
})

test('a failed delivery in the flat view uses the attempted value and reduced motion retains the action badge', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.addInitScript(() => localStorage.setItem('pixel-repair-lab:board-view', '2d'))
  const step = await openGrid(page, 'computer', '把灯读成数字', 'scan()\nsubmit(0)')
  await step.click()
  const robot = page.locator('.tile .action-robot')
  await expect(robot).toHaveAttribute('data-robot-action', 'scan')
  await step.click()
  await expect(robot).toHaveAttribute('data-robot-action', 'submit')
  await expect(robot).toHaveAttribute('data-failed', 'true')
  await expect(robot.locator('.action-robot__badge')).toBeVisible()
  await expect(page.locator('.station-action-cue')).toContainText('0')
})

test('the memory probe follows the actual address for repeated values, including writing the same value', async ({ page }) => {
  const step = await openGrid(page, 'architecture', '记忆储物柜', 'a = load(1)\nstore(5, a)\nstore(5, a)\nload(5)')
  const bench = page.getByTestId('grid-hardware-bench')
  await step.click()
  await expect(bench).toHaveAttribute('data-address', '1')
  await step.click()
  await expect(bench.locator('.grid-bench-transfer')).toContainText('RAM[5] · 0 → 4')
  await step.click()
  await expect(bench.locator('.grid-bench-transfer')).toHaveAttribute('data-changed', 'false')
  await expect(bench.locator('.grid-bench-transfer')).toContainText('4 → 4')
  await step.click()
  await expect(bench).toHaveAttribute('data-access', 'load')
  await expect(bench).toHaveAttribute('data-address', '5')
})

test('clocking the grid distinguishes the executed instruction from the next address and rewinds a RAM write', async ({ page }) => {
  const step = await openGrid(page, 'architecture', 'CPU 的四个时钟', 'for tick in range(4):\n    step()')
  const cpu = page.getByTestId('grid-cpu-bench')
  await step.click()
  await expect(page.locator('.station-action-cue[data-action="for"]')).toBeVisible()
  await step.click()
  await expect(cpu.locator('.grid-instruction-tape [aria-current="step"]')).toContainText('LOAD 0')
  await step.click()
  await step.click()
  await expect(cpu.locator('[data-action="alu"]')).toContainText('8 + 5 = 13')
  await expect(cpu.locator('.grid-instruction-tape [data-next]')).toContainText('STORE 2')
  await step.click()
  await step.click()
  await expect(cpu.locator('[data-action="write"]')).toContainText('RAM[2] 0 → 13')
  await page.getByRole('button', { name: '回看上一步' }).click()
  await cpu.getByRole('combobox').selectOption('2')
  await expect(cpu.getByTestId('cpu-probe-reading')).toContainText('RAM[2] = 0')
})
