import { expect, test, type Locator } from '@playwright/test'
import type { Catalog } from '../src/shared/types'

const button = (container: Locator, name: string) => container.getByRole('button', { name, exact: true })
const part = (container: Locator, name: string) => container.locator(`[data-boolean-part="${name}"]`)

test('the charge threshold includes equality, both conditions matter, and departure predictions use actual results', async ({ page, request }) => {
  const response = await request.get('/api/levels')
  expect(response.ok()).toBe(true)
  const { levels, issues } = await response.json() as Catalog
  expect(issues).toEqual([])
  const lesson = levels.find(level => level.id === 'boolean-notes')
  if (lesson?.kind !== 'lecture' || !lesson.execution?.boolean) throw new Error('Missing Boolean lesson')
  const { threshold } = lesson.execution.boolean

  await page.goto('/')
  await page.locator('[data-unit="foundations"]').click()
  const mission = page.locator('.mission-list').getByRole('button')
    .filter({ has: page.getByText(lesson.title.zh, { exact: true }) })
  await mission.click()
  await expect(page.getByRole('heading', { level: 1, name: lesson.title.zh, exact: true })).toBeVisible()

  const completed = mission.locator('.mission-check')
  const guide = page.getByTestId('boolean-lesson')
  const code = guide.getByTestId('boolean-code')
  const practice = page.getByTestId('departure-prediction')
  const next = button(guide, '下一步')
  const previous = button(guide, '上一步')

  await expect(guide).toHaveAttribute('data-boolean-stage', 'start')
  await expect(code.locator('code')).toHaveCount(0)
  await expect(previous).toBeDisabled()
  await expect(practice).toHaveCount(0)
  for (const [input, truth] of [[threshold - 1, 'false'], [threshold, 'true'], [threshold + 1, 'true']] as const) {
    const point = guide.locator(`[data-charge-point="${input}"]`)
    await expect(point).not.toHaveAttribute('data-value', /.+/)
    await next.click()
    await expect(guide).toHaveAttribute('data-boolean-stage', 'compare')
    await expect(point).toHaveAttribute('data-active', 'true')
    await expect(point).toHaveAttribute('data-value', truth)
    await expect(code).toContainText(`result >= ${threshold}`)
    await expect(code.locator('code')).toHaveCSS('font-variant-ligatures', 'none')
    await expect(code).not.toContainText('door_open()')
  }
  await previous.click()
  await expect(guide.locator(`[data-charge-point="${threshold}"]`)).toHaveAttribute('data-active', 'true')
  await next.click()

  for (const gate of ['false', 'true']) {
    await next.click()
    await expect(guide).toHaveAttribute('data-door-open', gate)
    await expect(guide).toHaveAttribute('data-boolean-stage', 'charge')
    await expect(part(guide, 'charge')).toHaveAttribute('data-value', 'true')
    await expect(part(guide, 'door')).not.toHaveAttribute('data-value', /.+/)
    await expect(code).not.toContainText('door_open()')
    await next.click()
    await expect(guide).toHaveAttribute('data-boolean-stage', 'door')
    await expect(part(guide, 'door')).toHaveAttribute('data-value', gate)
    await expect(code).toContainText('door_open()')
    await expect(code).not.toContainText('enough and door')
    await expect(practice).toHaveCount(0)
    await next.click()
    await expect(guide).toHaveAttribute('data-boolean-stage', 'decision')
    await expect(part(guide, 'decision')).toHaveAttribute('data-value', gate)
    await expect(code).toContainText('enough and door')
    if (gate === 'false') await expect(practice).toHaveCount(0)
  }
  await expect(practice).toBeVisible()
  await expect(completed).toHaveCount(0)

  const verify = button(practice, '运行验证')
  const decision = practice.getByTestId('departure-prediction-result')
  const guessDeparture = practice.locator('[data-prediction="true"]')
  await expect(verify).toBeDisabled()
  await practice.locator('[data-departure-case="0"]').click()
  await expect(verify).toBeDisabled()
  await guessDeparture.click()
  await expect(decision).toHaveCount(0)
  await verify.click()
  await expect(decision).toHaveText('False')
  await expect(practice.locator('[data-condition="charge"]')).toHaveAttribute('data-truth', 'false')
  await expect(practice.locator('[data-condition="door"]')).toHaveAttribute('data-truth', 'true')
  await expect(practice).toHaveAttribute('data-match', 'false')
  await expect(completed).toHaveCount(0)
  await button(practice, '再猜一次').click()
  await expect(decision).toHaveCount(0)
  await expect(verify).toBeDisabled()

  await practice.locator('[data-departure-case="1"]').click()
  await guessDeparture.click()
  await verify.click()
  await expect(decision).toHaveText('False')
  await expect(practice.locator('[data-condition="charge"]')).toHaveAttribute('data-truth', 'true')
  await expect(practice.locator('[data-condition="door"]')).toHaveAttribute('data-truth', 'false')
  await expect(completed).toHaveCount(0)

  await practice.locator('[data-departure-case="2"]').click()
  await expect(decision).toHaveCount(0)
  await expect(verify).toBeDisabled()
  await guessDeparture.click()
  await expect(completed).toHaveCount(0)
  await verify.click()
  await expect(decision).toHaveText('True')
  await expect(practice).toHaveAttribute('data-match', 'true')
  await expect(completed).toBeVisible()
})
