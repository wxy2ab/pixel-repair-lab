import { expect, test, type Locator } from '@playwright/test'
import type { Catalog } from '../src/shared/types'

const button = (panel: Locator, name: string) => panel.getByRole('button', { name, exact: true })

test('the prefix totals lesson adds a chosen range, builds cumulative values, then predicts on a fresh row', async ({ page, request }) => {
  const response = await request.get('/api/levels')
  expect(response.ok()).toBe(true)
  const { levels, issues } = await response.json() as Catalog
  expect(issues).toEqual([])
  const level = levels.find(item => item.id === 'prefix-totals-notes')
  if (level?.kind !== 'lecture' || !level.execution?.prefixTotalsLesson) throw new Error('Missing the prefix totals lesson')

  await page.goto('/#track-algorithms')
  await page.locator('[data-unit="algorithm-intro"]').click()
  const mission = page.locator('.mission-list').getByRole('button').filter({ has: page.getByText(level.title.zh, { exact: true }) })
  await mission.click()
  await expect(page.getByRole('heading', { level: 1, name: level.title.zh, exact: true })).toBeVisible()

  const guide = page.getByTestId('prefix-totals-lesson')
  const step = guide.getByTestId('prefix-totals-step')
  const code = guide.getByTestId('prefix-totals-code')
  const prediction = page.getByTestId('prefix-totals-prediction')
  const card = (name: string) => guide.getByTestId('prefix-battery-' + name)
  const cumulative = (name: string) => guide.getByTestId('prefix-value-' + name)
  const click = (name: string) => button(guide, name).click()

  await expect(step).toHaveAttribute('data-kind', 'select')
  await expect(code).toHaveCount(0)
  await card('B').click()
  await card('D').click()
  await expect(step).toHaveAttribute('data-left', '1')
  await expect(step).toHaveAttribute('data-right', '3')
  await card('C').click()
  await expect(guide.getByTestId('prefix-totals-hint')).toBeVisible()
  await expect(step).toHaveAttribute('data-kind', 'start')
  for (const [index, name] of ['B', 'C', 'D'].entries()) {
    await card(name).click()
    await expect(step).toHaveAttribute('data-kind', 'direct')
    await expect(step).toHaveAttribute('data-index', String(index + 1))
    await expect(code).toContainText('direct += charges[index]')
  }
  await expect(guide.getByTestId('prefix-totals-direct')).toContainText('7')
  await expect(prediction).toHaveCount(0)

  await click('开始累计')
  await expect(cumulative('start')).toHaveAttribute('data-total', '0')
  await expect(code).toContainText('prefix = [0]')
  for (const [name, total] of [['A', 3], ['B', 4], ['C', 8], ['D', 10], ['E', 15]] as const) {
    await card(name).click()
    await expect(cumulative(name)).toHaveAttribute('data-total', String(total))
    await expect(code).toContainText('prefix.append(prefix[-1] + charge)')
  }

  await cumulative('D').click()
  await expect(step).toHaveAttribute('data-kind', 'included')
  const bands = guide.locator('.prefix-bands')
  await expect(bands.locator('[data-band="through"] [data-covered] b')).toHaveText(['A', 'B', 'C', 'D'])
  await expect(bands.locator('[data-band="before"]')).toHaveCount(0)
  await expect(code).toContainText('included = prefix[right + 1]')
  await click('上一步')
  await expect(step).toHaveAttribute('data-kind', 'prefix')
  await cumulative('D').click()
  await cumulative('A').click()
  await expect(step).toHaveAttribute('data-kind', 'before')
  await expect(code).toContainText('before = prefix[left]')
  await click('相减')
  await expect(step).toHaveAttribute('data-kind', 'subtract')
  await expect(bands.locator('[data-band="through"] [data-cancelled] b')).toHaveText(['A'])
  await expect(bands.locator('[data-band="difference"] [data-covered] b')).toHaveText(['B', 'C', 'D'])
  await expect(code).toContainText('segment = included - before')
  await expect(prediction).toHaveCount(0)
  await click('核对结果')
  await expect(step).toHaveAttribute('data-kind', 'return')
  await expect(guide.getByTestId('prefix-totals-result')).toContainText('7')
  await expect(prediction).toBeVisible()

  const practice = prediction.getByTestId('prefix-totals-practice-row')
  const names = await practice.locator('[data-in-range="true"]').evaluateAll(items => items.map(item => item.getAttribute('data-battery-name')))
  expect(names).toEqual(['J', 'K', 'L'])
  const verify = button(prediction, '运行验证')
  await expect(verify).toBeDisabled()
  await prediction.locator('[data-prefix-option="1"]').click()
  await expect(verify).toBeDisabled()
  await prediction.locator('[data-total-option="4"]').click()
  await expect(prediction.getByTestId('prefix-totals-actual-total')).toHaveCount(0)
  await verify.click()
  await expect(prediction).toHaveAttribute('data-match', 'false')
  await expect(prediction.locator('[data-prediction="prefix"]')).toHaveAttribute('data-match', 'true')
  await expect(prediction.locator('[data-prediction="total"]')).toHaveAttribute('data-match', 'false')
  await expect(prediction.getByTestId('prefix-totals-actual-prefix')).toHaveText('[0, 2, 7, 7, 11, 14]')
  await expect(prediction.getByTestId('prefix-totals-actual-total')).toContainText('9')
  await expect(prediction.getByTestId('prefix-totals-actual-equation')).toContainText(/11\s*[-–−]\s*2\s*=\s*9/u)
  await expect(mission.locator('.mission-check')).toHaveCount(0)
  await button(prediction, '再猜一次').click()
  await prediction.locator('[data-total-option="9"]').click()
  await verify.click()
  await expect(prediction).toHaveAttribute('data-match', 'true')
  await expect(mission.locator('.mission-check')).toBeVisible()

  await click('重选区间')
  await card('A').click()
  await card('A').click()
  await card('A').click()
  await click('开始累计')
  for (const name of ['A', 'B', 'C', 'D', 'E']) await card(name).click()
  await cumulative('A').click()
  await cumulative('start').click()
  await click('相减')
  await click('核对结果')
  await expect(guide.getByTestId('prefix-totals-result')).toContainText('3')
})
