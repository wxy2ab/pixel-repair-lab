import { expect, test } from '@playwright/test'

test('a child steps the selected route-planning case, sees a failing line, then replays a corrected route', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('pixel-repair-lab:board-view', '2d'))
  await page.goto('/')
  await page.locator('button[data-unit="routing"]').click()
  await page.locator('.mission-list').getByRole('button').filter({ has: page.getByText('设计整条最短路线', { exact: true }) }).click()
  const editor = page.getByRole('textbox', { name: '编写 Python' })
  const toolbar = page.getByRole('toolbar', { name: '运行工具条' })
  const step = toolbar.getByRole('button', { name: '单步执行' })
  const status = toolbar.getByTestId('algorithm-step-status')
  const source = page.getByTestId('execution-source')
  await editor.fill('def plan_route(tiles, start, goal):\n    path = []\n    return missing')
  await page.getByRole('button', { name: '用例 3', exact: true }).click()
  await step.click()
  await expect(status).toContainText('用例 3 · 第 1 行')
  await expect(source.locator('[data-current]')).toHaveAttribute('data-line', '1')
  await expect(source.locator('[data-next]')).toHaveAttribute('data-line', '2')
  await step.click()
  await expect(status).toContainText('第 2 行')
  await expect(status).not.toContainText('missing')
  await step.click()
  await expect(status).toContainText('第 3 行')
  await expect(status.locator('.error-message')).toBeVisible()
  await expect(source.locator('[data-current]')).toHaveAttribute('data-line', '3')
  await expect(source.locator('[data-next]')).toHaveCount(0)
  await expect(step).toBeDisabled()
  await toolbar.getByRole('button', { name: '回看上一步' }).click()
  await expect(status).toContainText('第 2 行')
  await expect(source.locator('[data-next]')).toHaveAttribute('data-line', '3')
  await editor.fill('def plan_route(tiles, start, goal):\n    return ["right", "up"]')
  await expect(status).toHaveCount(0)
  await expect(source).toHaveCount(0)
  await step.click()
  await step.click()
  await expect(status).toContainText('这个用例通过了')
  const board = page.getByTestId('route-case-board')
  await board.getByRole('button', { name: '下一步' }).click()
  await expect(board.locator('[data-trail="recent"]')).toHaveCount(2)
  await board.getByRole('button', { name: '下一步' }).click()
  await expect(board.locator('[data-trail="history"]')).toHaveCount(2)
  await toolbar.getByTestId('trail-toggle').click()
  await expect(board.locator('[data-trail]')).toHaveCount(0)
  await expect(page.getByRole('button', { name: '保存到我的算法' })).toHaveCount(0)
  await editor.fill('def plan_route(tiles, start, goal): return []')
  await step.click()
  const repeat = source.locator('[data-current][data-next]')
  await expect(repeat).toHaveAttribute('data-line', '1')
  await expect(repeat).toHaveCSS('border-top-style', 'solid')
  await expect(repeat).toHaveCSS('outline-style', 'dashed')
  await step.click()
  await expect(source.locator('[data-next]')).toHaveCount(0)
})

test('next markers follow imports and the branch taken by the selected input', async ({ page }) => {
  await page.goto('/')
  await page.locator('button[data-unit="python-advanced"]').click()
  await page.locator('.mission-list').getByRole('button').filter({ has: page.getByText('完成两轮充电', { exact: true }) }).click()
  await page.getByRole('textbox', { name: '编写 Python' }).fill([
    'from algorithms import charge_total',
    'def charge_twice(current, first, second):',
    '    if current < 0:',
    '        return -1',
    '    return charge_total(current, first)',
  ].join('\n'))
  const step = page.getByRole('toolbar').getByRole('button', { name: '单步执行' })
  const source = page.getByTestId('execution-source')
  const main = source.locator('[data-source-name="main.py"]')
  const helper = source.locator('[data-source-name="algorithms.charge_total.py"]')
  await step.click()
  await expect(main.locator('[data-current] code')).toHaveText('from algorithms import charge_total')
  await expect(helper.locator('[data-next] code')).toHaveText('def charge_total(current, added):')
  await step.click()
  await expect(helper.locator('[data-current]')).toHaveAttribute('data-line', '1')
  await expect(main.locator('[data-next]')).toHaveAttribute('data-line', '2')
  await step.click()
  await step.click()
  await expect(main.locator('[data-current]')).toHaveAttribute('data-line', '3')
  await expect(main.locator('[data-next]')).toHaveAttribute('data-line', '5')
  await page.getByRole('button', { name: '用例 2', exact: true }).click()
  await expect(source).toHaveCount(0)
})
