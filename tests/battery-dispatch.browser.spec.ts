import { expect, test, type Locator } from '@playwright/test'
import type { Catalog } from '../src/shared/types'

const button = (panel: Locator, name: string) => panel.getByRole('button', { name, exact: true })

async function batteryNames(panel: Locator) {
  return panel.locator('[data-battery-name]').evaluateAll(items => items.map(item => item.getAttribute('data-battery-name')))
}

test('the optional battery handover traces four chosen structures and verifies two predictions with Python', async ({ page, request }) => {
  const response = await request.get('/api/levels')
  expect(response.ok()).toBe(true)
  const { levels, issues } = await response.json() as Catalog
  expect(issues).toEqual([])
  const level = levels.find(item => item.id === 'dispatch-report')
  if (level?.kind !== 'algorithm' || !level.batteryDispatch) throw new Error('Missing the data structures capstone')

  const mission = page.locator('.mission-list').getByRole('button').filter({ has: page.getByText(level.title.zh, { exact: true }) })
  const navigation = page.locator('.algorithm-route-nav')
  const guide = page.getByTestId('battery-dispatch-trial')
  const prediction = page.getByTestId('dispatch-prediction')
  const step = guide.getByTestId('dispatch-step')
  const queue = guide.getByTestId('dispatch-queue')
  const pile = guide.getByTestId('dispatch-stack')
  const records = guide.getByTestId('dispatch-records')
  const taken = guide.getByTestId('dispatch-retrieval')
  const runTrial = button(guide, '试跑小例子')
  const next = button(guide, '下一步')
  const charge = (name: string) => records.locator(`[data-battery-name="${name}"]`)
  const completed = mission.locator('.mission-check')

  await page.addInitScript(() => {
    localStorage.setItem('pixel-repair-lab:algorithms', JSON.stringify({
      charge_total: 'def charge_total(current, added):\n    total = current + added\n    return total',
    }))
  })
  await page.goto('/#track-algorithms')
  await page.locator('[data-unit="structures"]').click()
  await mission.click()
  await expect(page.getByRole('heading', { level: 1, name: level.title.zh, exact: true })).toBeVisible()
  await expect(mission).toContainText('选做')
  const progress = await navigation.locator('small').textContent()
  await button(navigation, '跳过选做挑战').click()
  await expect(navigation).toContainText('阶段 2/4')
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem('pixel-repair-lab:completed') ?? '[]'))).toEqual([])
  await page.getByRole('button', { name: '学习模块', exact: true }).click()
  await page.locator('[data-unit="structures"]').click()
  await mission.click()
  await expect(navigation.locator('small')).toHaveText(progress!)

  await page.getByText('用自己写的补电函数', { exact: true }).click()
  const personal = page.getByRole('button', { name: '用我的函数 · charge_total', exact: true })
  await personal.click()
  await expect(personal).toHaveAttribute('aria-pressed', 'true')
  await expect(guide.locator('[aria-pressed=true]')).toHaveCount(0)
  await expect(prediction).toHaveCount(0)

  await guide.getByTestId('dispatch-choice-queue-stack').click()
  await guide.getByTestId('dispatch-choice-stack-stack').click()
  await guide.getByTestId('dispatch-choice-records-dictionary').click()
  await guide.getByTestId('dispatch-choice-results-list').click()
  await runTrial.click()
  await expect(guide.getByTestId('dispatch-role-queue')).toHaveAttribute('data-needs-change', 'true')
  await expect(step).toHaveCount(0)
  await guide.getByTestId('dispatch-choice-queue-queue').click()
  await runTrial.click()
  await expect(step).toHaveAttribute('data-kind', 'start')
  await expect(guide.getByTestId('dispatch-current-code')).toHaveCount(0)
  expect(await batteryNames(queue)).toEqual([])
  await expect(charge('B')).toHaveAttribute('data-charge', '4')

  for (let index = 0; index < 3; index++) await next.click()
  expect(await batteryNames(queue)).toEqual(['A', 'B', 'C'])
  await expect(queue.locator('[data-queue-head]')).toHaveAttribute('data-battery-name', 'A')
  await expect(queue.locator('[data-queue-tail]')).toHaveAttribute('data-battery-name', 'C')
  await next.click()
  await expect(step).toHaveAttribute('data-kind', 'queueTake')
  await expect(guide.getByTestId('dispatch-moving-battery')).toHaveAttribute('data-battery-name', 'A')
  await expect(guide.getByTestId('dispatch-current-code').locator('code')).toHaveText('name = queue.pop(0)')
  expect(await batteryNames(queue)).toEqual(['B', 'C'])
  for (let index = 0; index < 3; index++) await next.click()
  expect(await batteryNames(pile)).toEqual(['B', 'A'])
  await expect(pile.locator('[data-stack-top]')).toHaveAttribute('data-charge', '7')
  await expect(charge('B')).toHaveAttribute('data-charge', '4')
  await next.click()
  await expect(step).toHaveAttribute('data-kind', 'stackTake')
  await expect(guide.getByTestId('dispatch-moving-battery')).toHaveAttribute('data-charge', '7')
  expect(await batteryNames(pile)).toEqual(['A'])
  await next.click()
  await expect(step).toHaveAttribute('data-kind', 'update')
  await expect(charge('B')).toHaveAttribute('data-charge', '7')
  await expect(guide.getByTestId('dispatch-current-code').locator('code')).toHaveText('current[battery[0]] = battery[1]')
  await next.click()
  expect(await batteryNames(taken)).toEqual(['B'])

  for (let index = 0; index < 20 && await next.isEnabled(); index++) await next.click()
  await expect(step).toHaveAttribute('data-kind', 'return')
  expect(await batteryNames(taken)).toEqual(['B', 'C', 'A'])
  await expect(prediction).toBeVisible()
  await button(guide, '上一步').click()
  await expect(step).toHaveAttribute('data-kind', 'record')
  await expect(prediction).toHaveCount(0)
  await next.click()
  await expect(prediction).toBeVisible()

  const verify = button(prediction, '运行验证')
  expect(await batteryNames(prediction.getByTestId('dispatch-prediction-ticket'))).toEqual(['P', 'R', 'Q', 'S'])
  await prediction.locator('[data-order-option="1"]').click()
  await expect(verify).toBeDisabled()
  await prediction.locator('[data-record-option="0"]').click()
  await expect(prediction.getByTestId('dispatch-actual-order')).toHaveCount(0)
  await verify.click()
  await expect(prediction.locator('[data-dispatch-field="order"]')).toHaveAttribute('data-match', 'true')
  await expect(prediction.locator('[data-dispatch-field="records"]')).toHaveAttribute('data-match', 'false')
  await expect(prediction.getByTestId('dispatch-actual-order')).toHaveText('R → S → Q')
  await expect(prediction.getByTestId('dispatch-actual-records').locator('[data-record-key="P"]')).toHaveAttribute('data-charge', '5')
  await expect(completed).toHaveCount(0)

  await prediction.locator('[data-record-option="1"]').click()
  await verify.click()
  await expect(prediction).toHaveAttribute('data-match', 'true')
  await expect(completed).toBeVisible()
  await expect(navigation.locator('small')).toHaveText(progress!)
})
