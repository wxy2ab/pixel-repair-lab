import { expect, test } from '@playwright/test'

test('the terminal keeps its previous command and the calculator takes input on its own keypad', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '开始 Python 课程', exact: true }).click()
  await page.locator('.mission-list button').filter({ hasText: '命令行程序' }).click()
  const terminal = page.getByRole('region', { name: '模拟终端' })
  await terminal.getByRole('button', { name: '提交命令' }).click()
  await expect(terminal.getByTestId('program-interface-output')).toHaveText('9')
  await terminal.getByRole('button', { name: '起始电量 1 格' }).click()
  await expect(terminal.locator('.device-terminal-history')).toContainText('charge 6')
  await expect(terminal.locator('.device-terminal-history samp')).toHaveText('9')
  await expect(terminal.getByTestId('program-interface-output')).toHaveText('—')
  await terminal.getByRole('button', { name: '提交命令' }).click()
  await expect(terminal.getByTestId('program-interface-output')).toHaveText('4')
  await page.locator('.mission-list button').filter({ hasText: '图形界面程序' }).click()
  const calculator = page.getByRole('region', { name: '模拟计算器' })
  await calculator.getByRole('button', { name: '起始电量 0 格' }).click()
  await calculator.getByRole('button', { name: '计算新电量' }).click()
  await expect(calculator.getByTestId('program-interface-output')).toHaveText('3')
})

test('the browser form, server and reply show the real values only when they arrive', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await page.getByRole('button', { name: '开始 Python 课程', exact: true }).click()
  // The lesson list collapses on phones.
  const route = page.locator('.mission-list button').filter({ hasText: '网页程序' })
  if (!(await route.isVisible())) {
    await page.getByRole('button', { name: '任务列表', exact: true }).click()
  }
  await route.click()
  const browser = page.getByRole('region', { name: '模拟浏览器' })
  const server = page.getByTestId('interface-processor')
  const result = browser.getByTestId('program-interface-output')
  await browser.getByRole('button', { name: '起始电量 0 格' }).click()
  await expect(server.getByTestId('processor-input')).toHaveText('—')
  await expect(result).toHaveText('—')
  await browser.getByRole('button', { name: '发送到服务器' }).click()
  await expect(result).toHaveText('3')
  await page.getByRole('button', { name: '回放这次运行' }).click()
  const next = page.getByRole('button', { name: '下一步', exact: true })
  await expect(result).toHaveText('—')
  await expect(server.getByTestId('processor-result')).toHaveText('—')
  await next.click()
  await expect(page.getByTestId('program-device').locator('[data-travel="out"] strong')).toHaveText('0')
  await next.click()
  await expect(server.getByTestId('processor-input')).toHaveText('0')
  await expect(server.getByTestId('processor-result')).toHaveText('3')
  await expect(result).toHaveText('—')
  await next.click()
  await expect(page.getByTestId('program-device').locator('[data-travel="back"] strong')).toHaveText('3')
  await expect(result).toHaveText('—')
  await next.click()
  await expect(result).toHaveText('3')
  await browser.getByRole('button', { name: '起始电量 1 格' }).click()
  await expect(result).toHaveText('—')
  await expect(server.getByTestId('processor-input')).toHaveText('—')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
})

test('an English browser form can retry a failed request with a different starting charge', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '开始 Python 课程', exact: true }).click()
  await page.locator('.mission-list button').filter({ hasText: '网页程序' }).click()
  await page.getByRole('button', { name: 'EN', exact: true }).click()
  const browser = page.getByRole('region', { name: 'Simulated browser' })
  const send = browser.getByRole('button', { name: 'Send to server' })
  await page.route('**/api/program/run', route => route.fulfill({ status: 503 }), { times: 1 })
  await send.click()
  await expect(page.getByRole('alert')).toContainText('Try again')
  await expect(browser.getByTestId('program-interface-output')).toHaveText('—')
  await browser.getByRole('button', { name: 'Start with 1 unit', exact: true }).click()
  await send.click()
  await expect(browser.getByTestId('program-interface-output')).toHaveText('4')
  await expect(page.getByRole('alert')).toHaveCount(0)
})
