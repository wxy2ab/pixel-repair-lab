import { expect, test, type Locator, type Page } from '@playwright/test'

test.use({ launchOptions: { args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] } })

async function openLesson(page: Page, unit: string, title: string) {
  await page.goto('/')
  await page.locator(`[data-unit="${unit}"]`).click()
  await page.locator('.mission-list button').filter({ has: page.getByText(title, { exact: true }) }).click()
}

const label = (model: Locator, value: string) => model.locator('.teaching-model-labels').getByText(value, { exact: true })

async function tapLabel(model: Locator, value: string, index = 0) {
  await model.scrollIntoViewIfNeeded()
  await expect(model).toHaveAttribute('data-renderer', 'webgl')
  const tag = label(model, value).nth(index)
  await expect(tag).toBeVisible()
  const canvas = model.locator('canvas')
  const [surface, part] = await Promise.all([canvas.boundingBox(), tag.boundingBox()])
  if (!surface || !part) throw new Error('Missing model surface or label')
  await canvas.click({ position: { x: part.x + part.width / 2 - surface.x, y: part.y + part.height / 2 - surface.y } })
}

test('reordering the assembly line changes the real program, and stepping displays the missing result', async ({ page }) => {
  await openLesson(page, 'foundations', '指令与顺序')
  const lesson = page.getByTestId('sequence-lesson')
  const model = lesson.locator('[data-teaching-model="sequence-assembly"]')
  await tapLabel(model, '◀')
  await expect(lesson.locator('[data-visual-block]').first()).toHaveAttribute('data-visual-block', 'read')
  await lesson.getByRole('button', { name: '检查顺序' }).click()
  await lesson.getByRole('button', { name: '把显示提前' }).click()
  await tapLabel(model, '读取电量')
  await expect(lesson).toHaveAttribute('data-step', '1')
  await tapLabel(model, '显示结果')
  await expect(label(model, '? result')).toBeVisible()
  await expect(lesson).toHaveAttribute('data-blocked', 'true')
  await lesson.getByRole('button', { name: '上一步' }).click()
  await expect(label(model, '? result')).toHaveCount(0)
})

test('selecting index and name reads and updates the actual registry while the source battery keeps its charge', async ({ page }) => {
  await openLesson(page, 'python-intermediate', '列表与字典')
  const lesson = page.getByTestId('collection-lesson')
  const model = lesson.locator('[data-teaching-model="collection-registry"]')
  const next = lesson.getByRole('button', { name: '下一步' })
  await next.click()
  await tapLabel(model, '[1]')
  await expect(lesson).toHaveAttribute('data-collection-stage', 'index')
  await next.click()
  await tapLabel(model, 'B')
  await expect(lesson).toHaveAttribute('data-collection-stage', 'lookup')
  await expect(label(model, '6')).toHaveCount(2)
  await expect(label(model, '9')).toHaveCount(0)
  await tapLabel(model, 'B')
  await expect(lesson).toHaveAttribute('data-collection-stage', 'update')
  await expect(label(model, '6')).toHaveCount(1)
  await expect(label(model, '9')).toBeVisible()
  await lesson.getByRole('button', { name: '上一步' }).click()
  await expect(label(model, '9')).toHaveCount(0)
})

test('the capstone rack opens its exit at the actual outer return and shuts again when rewound', async ({ page }) => {
  await openLesson(page, 'python-advanced', '给整架电池补电')
  const lesson = page.getByTestId('charging-challenge')
  const model = lesson.locator('[data-teaching-model="return-rack"]')
  await model.scrollIntoViewIfNeeded()
  await expect(model).toHaveAttribute('data-renderer', 'webgl')
  await lesson.getByRole('button', { name: '试跑小例子' }).click()
  const next = lesson.getByRole('button', { name: '下一步' })
  const fix = lesson.getByRole('button', { name: '移到循环外' })
  for (let step = 0; step < 40 && !await fix.isVisible(); step++) await next.click()
  await expect(fix).toBeVisible()
  await expect(label(model, '交回 1 排')).toBeVisible()
  await expect(label(model, '2')).toBeVisible()
  await lesson.getByRole('button', { name: '上一步' }).click()
  await expect(label(model, '交回 1 排')).toHaveCount(0)
})

test('the debugger gate counts only charged batteries and the prediction rack starts with the new inputs', async ({ page }) => {
  await openLesson(page, 'python-advanced', '调试')
  const guide = page.getByTestId('debugging-lesson')
  const model = guide.locator('[data-teaching-model="return-rack"]')
  const next = guide.getByRole('button', { name: '下一步' })
  await model.scrollIntoViewIfNeeded()
  await expect(model).toHaveAttribute('data-renderer', 'webgl')
  await guide.getByRole('button', { name: '试跑一块' }).click()
  for (let step = 0; step < 8; step++) await next.click()
  await guide.getByRole('button', { name: '换一排电池' }).click()
  for (let step = 0; step < 7; step++) await next.click()
  await expect(label(model, '交回 1/3')).toBeVisible()
  await expect(label(model, '未处理')).toHaveCount(2)
  await expect(label(model, '7')).toHaveCount(0)
  await next.click()
  await next.click()
  await guide.locator('[data-debug-line-choice="5"]').click()
  await guide.getByRole('button', { name: '移到循环外' }).click()
  await guide.getByRole('button', { name: '重新试跑' }).click()
  await expect(label(model, '交回 3/3')).toBeVisible()
  await expect(label(model, '未处理')).toHaveCount(0)
  await expect(label(model, '7')).toBeVisible()
  const prediction = page.getByTestId('debugging-prediction')
  await prediction.locator('[data-debug-case="0"]').click()
  const newRack = prediction.locator('[data-teaching-model="return-rack"]')
  await newRack.scrollIntoViewIfNeeded()
  await expect(label(newRack, '0')).toBeVisible()
  await expect(label(newRack, '8')).toHaveCount(0)
  await prediction.locator('[data-results-option="1"]').click()
  await prediction.getByRole('button', { name: '运行验证' }).click()
  await expect(label(newRack, '8')).toBeVisible()
  await expect(label(newRack, '交回 3 块')).toBeVisible()
})
