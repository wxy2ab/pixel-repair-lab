import { expect, test, type Locator } from '@playwright/test'
import type { Catalog } from '../src/shared/types'

const button = (panel: Locator, name: string) => panel.getByRole('button', { name, exact: true })
const row = (panel: Locator, index: number) => panel.locator(`[data-row-index="${index}"]`)
const battery = (panel: Locator, index: number) => panel.locator(`[data-battery-index="${index}"]`)

async function showsRows(panel: Locator, rows: number[][]) {
  await expect(panel.locator('[data-row-index]')).toHaveCount(rows.length)
  for (const [index, charges] of rows.entries()) {
    const current = row(panel, index)
    await expect(current.locator('[data-battery-index]')).toHaveCount(charges.length)
    for (const [column, charge] of charges.entries()) {
      await expect(battery(current, column)).toHaveAttribute('data-charge', String(charge))
    }
  }
}

test('the outer loop moves row by row while the inner loop charges each battery; verification keeps uneven and empty rows', async ({ page, request }) => {
  const response = await request.get('/api/levels')
  expect(response.ok()).toBe(true)
  const { levels, issues } = await response.json() as Catalog
  expect(issues).toEqual([])
  const lesson = levels.find(level => level.id === 'nested-loops-notes')
  if (lesson?.kind !== 'lecture' || !lesson.execution?.nestedLoops) throw new Error('Missing nested-loop lesson')
  const source = lesson.execution.source.split('\n')

  await page.goto('/')
  await page.locator('[data-unit="python-advanced"]').click()
  const mission = page.locator('.mission-list').getByRole('button')
    .filter({ has: page.getByText(lesson.title.zh, { exact: true }) })
  await mission.click()
  await expect(page.getByRole('heading', { level: 1, name: lesson.title.zh, exact: true })).toBeVisible()

  const completed = mission.locator('.mission-check')
  const guide = page.getByTestId('nested-loops-lesson')
  const code = guide.getByTestId('nested-loops-code')
  const rounds = guide.getByTestId('nested-loops-rounds')
  const saved = guide.getByTestId('nested-loops-saved')
  const output = guide.getByTestId('nested-loops-output')
  const practice = page.getByTestId('nested-loops-prediction')
  const next = button(guide, '下一步')
  const previous = button(guide, '上一步')

  async function step(stage: string, line: number, count: number) {
    await next.click()
    await expect(guide).toHaveAttribute('data-nested-stage', stage)
    const activeCode = code.locator(`[data-line="${line}"][aria-current="step"] code`)
    await expect(activeCode).toHaveText(source[line - 1].trim())
    expect(await activeCode.textContent()).toBe(source[line - 1])
    await expect(rounds).toHaveText(String(count))
  }

  await expect(guide).toHaveAttribute('data-nested-stage', 'start')
  await showsRows(guide, [[1, 4], [2, 0]])
  await expect(code.locator('code')).toHaveCount(0)
  await expect(previous).toBeDisabled()
  await expect(practice).toHaveCount(0)
  await step('load', 1, 0)
  await step('initialize', 2, 0)
  await step('select-row', 3, 0)
  await expect(row(guide, 0)).toHaveAttribute('data-active', 'true')
  await expect(code.locator('[data-line="4"]')).toHaveCount(0)
  await step('initialize-row', 4, 0)
  await step('take', 5, 0)
  await expect(battery(row(guide, 0), 0)).toHaveAttribute('data-active', 'true')
  await expect(code.locator('[data-line="6"]')).toHaveCount(0)
  await step('charge', 6, 1)
  await showsRows(guide, [[4, 4], [2, 0]])
  await previous.click()
  await expect(guide).toHaveAttribute('data-nested-stage', 'take')
  await expect(rounds).toHaveText('0')
  await showsRows(guide, [[1, 4], [2, 0]])
  await step('charge', 6, 1)
  await step('take', 5, 1)
  await expect(battery(row(guide, 0), 1)).toHaveAttribute('data-active', 'true')
  await step('charge', 6, 2)
  await step('finish-row', 5, 2)
  await expect(saved).toHaveText('[]')
  await step('record-row', 7, 2)
  await expect(saved).toHaveText('[[4,7]]')
  await step('select-row', 3, 2)
  await expect(row(guide, 0)).toHaveAttribute('data-complete', 'true')
  await expect(row(guide, 1)).toHaveAttribute('data-active', 'true')
  await expect(guide.locator('[data-battery-index][data-active]')).toHaveCount(0)
  await step('initialize-row', 4, 2)
  await step('take', 5, 2)
  await expect(battery(row(guide, 1), 0)).toHaveAttribute('data-active', 'true')
  await step('charge', 6, 3)
  await step('take', 5, 3)
  await step('charge', 6, 4)
  await step('finish-row', 5, 4)
  await step('record-row', 7, 4)
  await step('stop', 3, 4)
  await expect(output).toHaveCount(0)
  await expect(practice).toHaveCount(0)
  await step('output', 8, 4)
  await showsRows(guide, [[4, 7], [5, 3]])
  await expect(output).toHaveText('[[4,7],[5,3]]')
  await expect(next).toBeDisabled()

  const verify = button(practice, '运行验证')
  const actualRounds = practice.getByTestId('nested-actual-rounds')
  const actualRows = practice.getByTestId('nested-actual-rows')
  await expect(verify).toBeDisabled()
  await practice.locator('[data-nested-case="0"]').click()
  await showsRows(practice.getByTestId('nested-starting-rows'), [[2, 0, 4], [5], [1, 3]])
  await practice.locator('[data-round-option="3"]').click()
  await expect(verify).toBeDisabled()
  await practice.locator('[data-rows-option="1"]').click()
  await expect(actualRows).toHaveCount(0)
  await verify.click()
  await expect(practice).toHaveAttribute('data-match', 'false')
  await expect(practice.locator('[data-nested-field="rounds"]')).toHaveAttribute('data-match', 'false')
  await expect(practice.locator('[data-nested-field="rows"]')).toHaveAttribute('data-match', 'true')
  await expect(actualRounds).toHaveText('6')
  await showsRows(actualRows, [[5, 3, 7], [8], [4, 6]])
  await expect(completed).toHaveCount(0)

  await practice.locator('[data-nested-case="1"]').click()
  await expect(actualRows).toHaveCount(0)
  await expect(verify).toBeDisabled()
  await showsRows(practice.getByTestId('nested-starting-rows'), [[0], [], [4, 2]])
  await practice.locator('[data-round-option="3"]').click()
  await practice.locator('[data-rows-option="0"]').click()
  await verify.click()
  await expect(practice.locator('[data-nested-field="rounds"]')).toHaveAttribute('data-match', 'true')
  await expect(practice.locator('[data-nested-field="rows"]')).toHaveAttribute('data-match', 'false')
  await expect(actualRounds).toHaveText('3')
  await showsRows(actualRows, [[3], [], [7, 5]])
  await expect(row(actualRows, 1)).toHaveAttribute('data-empty', 'true')
  await expect(completed).toHaveCount(0)

  await button(practice, '再猜一次').click()
  await expect(actualRows).toHaveCount(0)
  await expect(verify).toBeDisabled()
  await practice.locator('[data-round-option="3"]').click()
  await practice.locator('[data-rows-option="1"]').click()
  await verify.click()
  await expect(practice).toHaveAttribute('data-match', 'true')
  await expect(completed).toBeVisible()
})
