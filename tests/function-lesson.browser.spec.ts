import { expect, test, type Locator } from '@playwright/test'
import type { Catalog } from '../src/shared/types'

const button = (panel: Locator, name: string) => panel.getByRole('button', { name, exact: true })
const box = (scope: Locator, name: string) => scope.locator(`[data-binding="${name}"]`)
const field = (panel: Locator, name: string) => panel.locator(`[data-prediction-field="${name}"]`)

test('function parameters, local changes, and return are visible before predicting both values', async ({ page, request }) => {
  const response = await request.get('/api/levels')
  expect(response.ok()).toBe(true)
  const { levels, issues } = await response.json() as Catalog
  expect(issues).toEqual([])
  const lesson = levels.find(level => level.id === 'foundation-functions-notes')
  if (lesson?.kind !== 'lecture' || !lesson.execution?.functionLesson) throw new Error('Missing function lesson')
  const { cases, functionLesson } = lesson.execution
  const [example, second, third] = cases
  const { parameter, resultVariable } = functionLesson
  const source = lesson.execution.source.split('\n')

  await page.goto('/')
  await page.locator('[data-unit="foundations"]').click()
  const mission = page.locator('.mission-list').getByRole('button')
    .filter({ has: page.getByText(lesson.title.zh, { exact: true }) })
  await mission.click()
  await expect(page.getByRole('heading', { level: 1, name: lesson.title.zh, exact: true })).toBeVisible()
  const completed = mission.locator('.mission-check')
  const guide = page.getByTestId('guided-program')
  const stack = guide.getByTestId('walkthrough-stack')
  const code = guide.getByTestId('walkthrough-code')
  const main = stack.locator('[data-scope-role="main"]')
  const local = stack.locator('[data-scope-role="function"]')
  const transfer = guide.getByTestId('guided-transfer')
  const practice = page.getByTestId('function-prediction')
  const next = button(guide, '下一步')
  const previous = button(guide, '上一步')

  async function step(kind: string, line: number) {
    await next.click()
    await expect(guide).toHaveAttribute('data-trace-kind', kind)
    await expect(guide).toHaveAttribute('data-trace-line', String(line))
    await expect(code.locator(`[data-line="${line}"][aria-current="step"] code`)).toHaveText(source[line - 1].trim())
  }

  await expect(guide).toHaveAttribute('data-trace-kind', 'start')
  await expect(code.locator('code')).toHaveCount(0)
  await expect(local).toHaveCount(0)
  await expect(practice).toHaveCount(0)
  await expect(previous).toBeDisabled()
  await step('assign', 5)
  await expect(box(main, parameter).locator('dd')).toHaveText(String(example.input))
  await expect(box(main, resultVariable)).toHaveCount(0)

  await step('call', 6)
  await expect(main).toHaveAttribute('data-waiting', 'true')
  await expect(local).toHaveAttribute('data-active', 'true')
  await expect(box(local, parameter)).toHaveAttribute('data-parameter', 'true')
  await expect(box(local, parameter).locator('dd')).toHaveText(String(example.input))
  await expect(transfer).toHaveAttribute('data-transfer-kind', 'call')
  await expect(transfer).toContainText(String(example.input))
  await expect(code.locator('[data-line="1"] code')).toHaveText(source[0])
  await expect(code.locator('[data-line="3"]')).toHaveCount(0)

  await step('assign', 2)
  await expect(box(main, parameter).locator('dd')).toHaveText(String(example.input))
  await expect(box(local, parameter).locator('dd')).toHaveText(example.expected)
  await previous.click()
  await expect(box(local, parameter).locator('dd')).toHaveText(String(example.input))
  await step('assign', 2)

  await step('return', 3)
  await expect(transfer).toHaveAttribute('data-transfer-kind', 'return')
  await expect(transfer).toContainText(example.expected)
  await expect(local).toHaveCount(0)
  await expect(main).toHaveAttribute('data-active', 'true')
  await expect(box(main, parameter).locator('dd')).toHaveText(String(example.input))
  await expect(box(main, resultVariable)).toHaveCount(0)
  await step('assign', 6)
  await expect(box(main, resultVariable).locator('dd')).toHaveText(example.expected)
  await expect(box(main, parameter).locator('dd')).toHaveText(String(example.input))
  await step('output', 7)
  await expect(guide.getByTestId('walkthrough-output')).toHaveText(example.expected)
  await expect(practice).toHaveCount(0)
  await next.click()
  await expect(guide).toHaveAttribute('data-trace-kind', 'end')
  await expect(practice).toBeVisible()
  await expect(completed).toHaveCount(0)

  const verify = button(practice, '运行验证')
  const returned = field(practice, 'return')
  const caller = field(practice, 'caller')
  const choose = (target: Locator, value: string) => target.locator(`[data-prediction="${value}"]`).click()
  await expect(verify).toBeDisabled()
  await expect(practice.locator(`[data-charge-input="${example.input}"]`)).toHaveCount(0)
  await button(practice, second.label.zh).click()
  await choose(returned, second.expected)
  await expect(verify).toBeDisabled()
  await choose(caller, second.expected)
  await expect(practice.locator('[data-actual-value]')).toHaveCount(0)
  await verify.click()
  await expect(returned.locator('[data-actual-value]')).toHaveText(second.expected)
  await expect(caller.locator('[data-actual-value]')).toHaveText(String(second.input))
  await expect(caller).toHaveAttribute('data-match', 'false')
  await expect(completed).toHaveCount(0)

  await button(practice, '再猜一次').click()
  await expect(practice.locator('[data-actual-value]')).toHaveCount(0)
  await expect(verify).toBeDisabled()
  await button(practice, third.label.zh).click()
  await choose(returned, third.expected)
  await choose(caller, String(third.input))
  await expect(practice.locator('[data-actual-value]')).toHaveCount(0)
  await expect(completed).toHaveCount(0)
  await verify.click()
  await expect(returned.locator('[data-actual-value]')).toHaveText(third.expected)
  await expect(caller.locator('[data-actual-value]')).toHaveText(String(third.input))
  await expect(practice).toHaveAttribute('data-match', 'true')
  await expect(completed).toBeVisible()
})
