import { expect, test, type Locator } from '@playwright/test'
import type { Catalog } from '../src/shared/types'

const button = (container: Locator, name: string) => container.getByRole('button', { name, exact: true })
const field = (container: Locator, name: string) => container.locator(`[data-prediction-field="${name}"]`)
const box = (container: Locator, name: string) => container.locator(`[data-binding="${name}"]`)

test('variables compare calculating and writing before predicting the values from both real runs', async ({ page, request }) => {
  const response = await request.get('/api/levels')
  expect(response.ok()).toBe(true)
  const { levels, issues } = await response.json() as Catalog
  expect(issues).toEqual([])
  const lesson = levels.find(level => level.id === 'foundation-notes')
  if (lesson?.kind !== 'lecture' || !lesson.execution?.assignment) throw new Error('Missing variable assignment lesson')
  const { cases, assignment } = lesson.execution
  const [example, second, third] = cases

  await page.goto('/')
  await page.locator('[data-unit="foundations"]').click()
  const mission = page.locator('.mission-list').getByRole('button')
    .filter({ has: page.getByText(lesson.title.zh, { exact: true }) })
  await mission.click()
  await expect(page.getByRole('heading', { level: 1, name: lesson.title.zh, exact: true })).toBeVisible()
  const completed = mission.locator('.mission-check')
  const guide = page.getByTestId('assignment-lesson')
  const device = guide.getByRole('region', { name: 'Python 调试器', exact: true })
  const practice = page.getByTestId('variable-prediction')
  const code = guide.getByTestId('assignment-code')
  const next = button(guide, '下一步')
  const previous = button(guide, '上一步')
  const newVariable = guide.locator('[data-assignment-lane="new"]')
  const overwrite = guide.locator('[data-assignment-lane="overwrite"]')

  await expect(guide).toHaveAttribute('data-assignment-stage', 'start')
  await expect(code.locator('code')).toHaveCount(0)
  await expect(practice).toHaveCount(0)
  await expect(previous).toBeDisabled()
  await button(device, '读取电量 ' + example.input).click()
  await expect(guide).toHaveAttribute('data-assignment-stage', 'read')
  await expect(box(guide, assignment.inputVariable)).toContainText(String(example.input))
  await expect(code).toContainText('charge = scan()')
  await expect(code).not.toContainText('charge + 3')

  await next.click()
  await expect(guide).toHaveAttribute('data-assignment-stage', 'evaluate')
  await expect(code.locator('[data-highlight="right"]')).toHaveCount(2)
  await expect(code).toContainText(/result\s*=\s*charge\s*\+\s*3/)
  await expect(code).toContainText(/charge\s*=\s*charge\s*\+\s*3/)
  for (const lane of [newVariable, overwrite]) {
    await expect(box(lane, assignment.inputVariable)).toContainText(String(example.input))
    await expect(lane.getByTestId('assignment-rhs-value')).toHaveText(example.expected)
  }
  await expect(box(newVariable, assignment.resultVariable)).toContainText('待存入')
  await expect(box(overwrite, assignment.resultVariable)).toHaveCount(0)
  await expect(practice).toHaveCount(0)

  await button(device, '把两个结果分别写入左边的变量').click()
  await expect(guide).toHaveAttribute('data-assignment-stage', 'store')
  await expect(code.locator('[data-highlight="left"]')).toHaveCount(2)
  await expect(box(newVariable, assignment.inputVariable)).toContainText(String(example.input))
  await expect(box(newVariable, assignment.resultVariable)).toContainText(example.expected)
  await expect(box(overwrite, assignment.inputVariable)).toContainText(example.expected)
  await previous.click()
  await expect(box(overwrite, assignment.inputVariable)).toContainText(String(example.input))
  await expect(box(newVariable, assignment.resultVariable)).toContainText('待存入')
  await next.click()
  await next.click()
  await expect(guide).toHaveAttribute('data-assignment-stage', 'output')
  for (const lane of [newVariable, overwrite]) {
    await expect(lane.getByTestId('assignment-output')).toHaveText(example.expected)
  }
  await expect(practice).toBeVisible()
  await expect(completed).toHaveCount(0)

  const verify = button(practice, '运行验证')
  const newInput = field(practice, 'new-input')
  const newResult = field(practice, 'new-result')
  const updated = field(practice, 'overwrite-input')
  const choose = (group: Locator, value: string) => group.locator(`[data-prediction="${value}"]`).click()
  await expect(verify).toBeDisabled()
  await expect(practice.locator(`[data-charge-input="${example.input}"]`)).toHaveCount(0)
  await button(practice, second.label.zh).click()
  await choose(newInput, second.expected)
  await choose(newResult, second.expected)
  await expect(verify).toBeDisabled()
  await choose(updated, second.expected)
  await expect(practice.locator('[data-actual-value]')).toHaveCount(0)
  await verify.click()
  await expect(newInput).toHaveAttribute('data-match', 'false')
  await expect(newInput.locator('[data-actual-value]')).toHaveText(String(second.input))
  await expect(newResult.locator('[data-actual-value]')).toHaveText(second.expected)
  await expect(updated.locator('[data-actual-value]')).toHaveText(second.expected)
  await expect(completed).toHaveCount(0)

  await button(practice, '再猜一次').click()
  await expect(practice.locator('[data-actual-value]')).toHaveCount(0)
  await expect(verify).toBeDisabled()
  await button(practice, third.label.zh).click()
  await choose(newInput, String(third.input))
  await choose(newResult, third.expected)
  await choose(updated, third.expected)
  await expect(practice.locator('[data-actual-value]')).toHaveCount(0)
  await expect(completed).toHaveCount(0)
  await verify.click()
  await expect(newInput.locator('[data-actual-value]')).toHaveText(String(third.input))
  await expect(newResult.locator('[data-actual-value]')).toHaveText(third.expected)
  await expect(updated.locator('[data-actual-value]')).toHaveText(third.expected)
  await expect(completed).toBeVisible()
})
