export function runIssueText(locale: Locale, issue: RunIssue) {
  const message = tr(locale, ...(errors[issue.code] ?? errors.internal))
  return issue.line ? tr(locale, '第 ' + issue.line + ' 行 · ', 'Line ' + issue.line + ' · ') + message : message
}

